-- Sesión: apertura, cierre, validación.
CREATE FUNCTION caja.tg_sesion_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    c        caja.caja;
    s        record;
    v_esp    numeric;
    v_arq    numeric;
    v_dif    boolean := false;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Las sesiones de caja no se eliminan.';
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT * INTO c FROM caja.caja WHERE id = NEW.caja_id;
        IF NOT c.activa THEN
            RAISE EXCEPTION 'La caja % está inactiva.', c.codigo;
        END IF;
        NEW.estado       := 'ABIERTA';
        NEW.cerrada_por  := NULL; NEW.cerrada_en  := NULL;
        NEW.validada_por := NULL; NEW.validada_en := NULL;
        NEW.numero       := comun.siguiente_numero('caja.sesion:' || NEW.caja_id);
        RETURN NEW;
    END IF;

    -- UPDATE
    IF NEW.caja_id <> OLD.caja_id OR NEW.numero <> OLD.numero OR NEW.abierta_por <> OLD.abierta_por
       OR NEW.abierta_en <> OLD.abierta_en THEN
        RAISE EXCEPTION 'Los datos de apertura de una sesión no se modifican.';
    END IF;

    IF OLD.estado = 'ABIERTA' AND NEW.estado = 'CERRADA' THEN
        IF NOT EXISTS (SELECT 1 FROM caja.sesion_saldo WHERE sesion_id = NEW.id) THEN
            RAISE EXCEPTION 'La sesión no tiene saldos registrados: no hay nada que cerrar.';
        END IF;
        FOR s IN SELECT * FROM caja.sesion_saldo WHERE sesion_id = NEW.id ORDER BY moneda LOOP
            IF s.saldo_contado IS NULL THEN
                RAISE EXCEPTION 'Falta declarar el efectivo contado en %.', s.moneda;
            END IF;
            SELECT sum(subtotal) INTO v_arq FROM caja.arqueo WHERE sesion_id = NEW.id AND moneda = s.moneda;
            IF v_arq IS NOT NULL AND v_arq <> s.saldo_contado THEN
                RAISE EXCEPTION 'El arqueo de % suma % pero se declararon % contados.', s.moneda, v_arq, s.saldo_contado;
            END IF;
            v_esp := caja.saldo_efectivo(NEW.id, s.moneda);
            UPDATE caja.sesion_saldo SET saldo_esperado = v_esp WHERE id = s.id;
            IF s.saldo_contado <> v_esp THEN
                v_dif := true;
            END IF;
        END LOOP;
        IF v_dif AND length(btrim(COALESCE(NEW.observaciones, ''))) < 10 THEN
            RAISE EXCEPTION 'El efectivo contado no coincide con el esperado: explique la diferencia en observaciones.';
        END IF;
        RETURN NEW;
    END IF;

    IF OLD.estado = 'CERRADA' AND NEW.estado = 'VALIDADA' THEN
        IF (NEW.cerrada_por, NEW.cerrada_en) IS DISTINCT FROM (OLD.cerrada_por, OLD.cerrada_en) THEN
            RAISE EXCEPTION 'Los datos del cierre no se modifican al validar.';
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.estado <> OLD.estado THEN
        RAISE EXCEPTION 'Transición no permitida para la sesión: % → %.', OLD.estado, NEW.estado;
    END IF;
    IF OLD.estado <> 'ABIERTA' THEN
        RAISE EXCEPTION 'La sesión está % y no admite cambios.', OLD.estado;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER sesion_control
    BEFORE INSERT OR UPDATE OR DELETE ON caja.sesion
    FOR EACH ROW EXECUTE FUNCTION caja.tg_sesion_control();

-- Saldos: el inicial lo pone la base a partir del cierre anterior.
CREATE FUNCTION caja.tg_sesion_saldo_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_estado  varchar;
    v_caja    bigint;
    v_usd     boolean;
    v_previo  numeric;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los saldos de una sesión no se eliminan.';
    END IF;

    SELECT s.estado, s.caja_id, c.maneja_usd INTO v_estado, v_caja, v_usd
      FROM caja.sesion s JOIN caja.caja c ON c.id = s.caja_id
     WHERE s.id = NEW.sesion_id;

    IF v_estado <> 'ABIERTA' THEN
        RAISE EXCEPTION 'La sesión está %: sus saldos ya no se modifican.', v_estado;
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.moneda = 'USD' AND NOT v_usd THEN
            RAISE EXCEPTION 'Esta caja no maneja dólares.';
        END IF;
        SELECT ss.saldo_contado INTO v_previo
          FROM caja.sesion_saldo ss
          JOIN caja.sesion s ON s.id = ss.sesion_id
         WHERE s.caja_id = v_caja AND s.id <> NEW.sesion_id AND s.estado <> 'ABIERTA'
           AND ss.moneda = NEW.moneda
         ORDER BY s.numero DESC
         LIMIT 1;
        IF FOUND THEN
            NEW.saldo_inicial := v_previo;   -- continuidad: se arranca con lo contado al cerrar
        END IF;
        NEW.saldo_esperado := NULL;
        RETURN NEW;
    END IF;

    IF NEW.saldo_inicial <> OLD.saldo_inicial OR NEW.moneda <> OLD.moneda OR NEW.sesion_id <> OLD.sesion_id THEN
        RAISE EXCEPTION 'El saldo inicial sale del cierre anterior y no se modifica.';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER sesion_saldo_control
    BEFORE INSERT OR UPDATE OR DELETE ON caja.sesion_saldo
    FOR EACH ROW EXECUTE FUNCTION caja.tg_sesion_saldo_control();

CREATE FUNCTION caja.tg_arqueo_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_sesion bigint := CASE WHEN TG_OP = 'DELETE' THEN OLD.sesion_id ELSE NEW.sesion_id END;
BEGIN
    IF (SELECT estado FROM caja.sesion WHERE id = v_sesion) <> 'ABIERTA' THEN
        RAISE EXCEPTION 'El arqueo solo se registra mientras la sesión está abierta.';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;

CREATE TRIGGER arqueo_control
    BEFORE INSERT OR UPDATE OR DELETE ON caja.arqueo
    FOR EACH ROW EXECUTE FUNCTION caja.tg_arqueo_control();

-- Movimientos.
CREATE FUNCTION caja.tg_movimiento_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    s       caja.sesion;
    c       caja.caja;
    k       caja.concepto;
    v_saldo numeric;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los movimientos de caja no se eliminan: se anulan con motivo (comprobante %).', OLD.numero;
    END IF;

    -- La sesión se bloquea para que dos egresos simultáneos no se salten el control de saldo.
    SELECT * INTO s FROM caja.sesion WHERE id = NEW.sesion_id FOR UPDATE;
    IF s.estado <> 'ABIERTA' THEN
        RAISE EXCEPTION 'La sesión % de caja está %: no admite movimientos.', s.numero, s.estado;
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT * INTO c FROM caja.caja WHERE id = s.caja_id;
        SELECT * INTO k FROM caja.concepto WHERE id = NEW.concepto_id;
        IF NOT k.activo THEN
            RAISE EXCEPTION 'El concepto «%» está inactivo.', k.nombre;
        END IF;
        NEW.caja_id := s.caja_id;
        NEW.tipo    := k.tipo;              -- el tipo lo define el concepto
        NEW.estado  := 'VIGENTE';
        NEW.anulado_por := NULL; NEW.anulado_en := NULL; NEW.motivo_anulacion := NULL;

        IF NOT EXISTS (SELECT 1 FROM caja.sesion_saldo WHERE sesion_id = s.id AND moneda = NEW.moneda) THEN
            RAISE EXCEPTION 'La sesión no tiene saldo abierto en %.', NEW.moneda;
        END IF;

        IF NEW.tipo = 'EGRESO' AND NEW.forma_pago = 'EFECTIVO' THEN
            v_saldo := caja.saldo_efectivo(s.id, NEW.moneda);
            IF v_saldo < NEW.monto THEN
                RAISE EXCEPTION 'Saldo insuficiente en caja: hay % % en efectivo y el egreso es de %.', v_saldo, NEW.moneda, NEW.monto;
            END IF;
        END IF;

        NEW.numero := comun.generar_codigo('caja.comprobante:' || c.id, c.formato_comprobante,
                                           c.reinicio_comprobante, NEW.fecha::date,
                                           jsonb_build_object('CAJA', c.codigo));
        RETURN NEW;
    END IF;

    -- UPDATE: lo único permitido es anular.
    IF (NEW.sesion_id, NEW.caja_id, NEW.numero, NEW.fecha, NEW.tipo, NEW.concepto_id, NEW.monto, NEW.moneda,
        NEW.forma_pago, NEW.banco_id, NEW.nro_documento, NEW.persona_nombre, NEW.persona_ci, NEW.glosa, NEW.registrado_por)
       IS DISTINCT FROM
       (OLD.sesion_id, OLD.caja_id, OLD.numero, OLD.fecha, OLD.tipo, OLD.concepto_id, OLD.monto, OLD.moneda,
        OLD.forma_pago, OLD.banco_id, OLD.nro_documento, OLD.persona_nombre, OLD.persona_ci, OLD.glosa, OLD.registrado_por) THEN
        RAISE EXCEPTION 'Un movimiento de caja no se corrige: se anula y se registra otro (comprobante %).', OLD.numero;
    END IF;
    IF OLD.estado = 'ANULADO' THEN
        RAISE EXCEPTION 'El comprobante % ya está anulado.', OLD.numero;
    END IF;
    IF NEW.estado = 'ANULADO' AND NEW.tipo = 'INGRESO' AND NEW.forma_pago = 'EFECTIVO' THEN
        v_saldo := caja.saldo_efectivo(s.id, NEW.moneda);
        IF v_saldo - NEW.monto < 0 THEN
            RAISE EXCEPTION 'Anular este ingreso dejaría la caja en negativo (saldo %).', v_saldo;
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER movimiento_control
    BEFORE INSERT OR UPDATE OR DELETE ON caja.movimiento
    FOR EACH ROW EXECUTE FUNCTION caja.tg_movimiento_control();


