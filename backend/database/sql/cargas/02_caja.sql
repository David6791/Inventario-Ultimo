/* =====================================================================
   02 — MÓDULO DE CAJA — ESQUEMA caja (PostgreSQL 16)
   ---------------------------------------------------------------------
   Módulo propio, independiente de cargas: la caja también paga sueldos,
   alquileres, servicios, préstamos. Cargas la USA para pagar anticipos y
   bonos, pero caja no depende de cargas.

   Flujo:
     1. APERTURA   se abre una sesión por caja (solo una abierta a la vez).
                   El saldo inicial de cada moneda es el CONTADO del cierre
                   anterior: la caja empieza con lo que realmente había.
     2. MOVIMIENTOS ingresos y egresos con comprobante numerado. Un egreso
                   en efectivo no puede dejar la caja en negativo. Un
                   movimiento no se edita: se anula con motivo, y solo
                   mientras la sesión está abierta.
     3. CIERRE     el cajero declara lo contado (opcional: arqueo por corte
                   de billetes). La base calcula lo esperado y la diferencia;
                   si hay diferencia, exige una explicación.
     4. VALIDACIÓN un supervisor (otro usuario) revisa y valida el cierre.

   Solo el EFECTIVO mueve el saldo físico. Cheques y transferencias se
   registran (con banco y número) pero no cuentan en el arqueo.
   ===================================================================== */

BEGIN;

CREATE SCHEMA IF NOT EXISTS caja;

/* ---------------------------------------------------------------------
   Cajas
   --------------------------------------------------------------------- */
CREATE TABLE caja.caja (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo               varchar(10) NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9]+$'),
    nombre               varchar(100) NOT NULL,
    almacen_id           bigint NOT NULL REFERENCES public.almacenes(id),
    maneja_usd           boolean NOT NULL DEFAULT false,
    formato_comprobante  varchar(60) NOT NULL DEFAULT '{CAJA}-{AAAA}-{N:6}',
    reinicio_comprobante varchar(10) NOT NULL DEFAULT 'ANUAL',
    activa               boolean NOT NULL DEFAULT true,
    created_at           timestamp(0),
    updated_at           timestamp(0)
);
COMMENT ON COLUMN caja.caja.formato_comprobante IS 'Formato del número de comprobante. Marcadores: {CAJA} {AAAA} {AA} {MM} {DD} {N:k}.';

CREATE FUNCTION caja.tg_caja_formato() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    PERFORM comun.validar_formato(NEW.formato_comprobante, NEW.reinicio_comprobante, ARRAY['CAJA']);
    RETURN NEW;
END $$;

CREATE TRIGGER caja_formato
    BEFORE INSERT OR UPDATE OF formato_comprobante, reinicio_comprobante ON caja.caja
    FOR EACH ROW EXECUTE FUNCTION caja.tg_caja_formato();

/* ---------------------------------------------------------------------
   Conceptos (reemplaza "Cuentas"; el tipo ya no va en la descripción)
   --------------------------------------------------------------------- */
CREATE TABLE caja.concepto (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     varchar(40)  NOT NULL UNIQUE,
    nombre     varchar(120) NOT NULL,
    tipo       varchar(7)   NOT NULL CHECK (tipo IN ('INGRESO','EGRESO')),
    origen     varchar(40)  NOT NULL DEFAULT 'MANUAL' CHECK (origen ~ '^[A-Z_]+$'),
    activo     boolean NOT NULL DEFAULT true,
    created_at timestamp(0),
    updated_at timestamp(0)
);
-- Evita "PAGO BONO TRANSPORTE" dos veces.
CREATE UNIQUE INDEX ux_concepto_nombre
    ON caja.concepto (upper(regexp_replace(btrim(nombre), '\s+', ' ', 'g')));
COMMENT ON COLUMN caja.concepto.origen IS
  'MANUAL = lo registra el cajero. Cualquier otro valor (p. ej. CARGAS_ANTICIPO) = solo lo puede generar ese módulo, vinculado a su documento.';

/* ---------------------------------------------------------------------
   Sesiones (apertura → cierre → validación)
   --------------------------------------------------------------------- */
CREATE TABLE caja.sesion (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caja_id       bigint  NOT NULL REFERENCES caja.caja(id),
    numero        integer NOT NULL,
    estado        varchar(10) NOT NULL DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA','CERRADA','VALIDADA')),
    abierta_por   bigint NOT NULL REFERENCES public.users(id),
    abierta_en    timestamp(0) NOT NULL DEFAULT now(),
    cerrada_por   bigint REFERENCES public.users(id),
    cerrada_en    timestamp(0),
    validada_por  bigint REFERENCES public.users(id),
    validada_en   timestamp(0),
    observaciones text,
    created_at    timestamp(0),
    updated_at    timestamp(0),
    CONSTRAINT uq_sesion_numero UNIQUE (caja_id, numero),
    CONSTRAINT ck_sesion_cerrada  CHECK (estado = 'ABIERTA' OR (cerrada_por IS NOT NULL AND cerrada_en IS NOT NULL)),
    CONSTRAINT ck_sesion_validada CHECK (estado <> 'VALIDADA' OR (validada_por IS NOT NULL AND validada_en IS NOT NULL)),
    CONSTRAINT ck_sesion_segregacion CHECK (validada_por IS NULL OR validada_por <> cerrada_por)
);
CREATE UNIQUE INDEX ux_sesion_una_abierta ON caja.sesion (caja_id) WHERE estado = 'ABIERTA';

-- Saldo de cada moneda en la sesión.
CREATE TABLE caja.sesion_saldo (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id      bigint NOT NULL REFERENCES caja.sesion(id),
    moneda         char(3) NOT NULL CHECK (moneda IN ('BOB','USD')),
    saldo_inicial  numeric(14,2) NOT NULL CHECK (saldo_inicial >= 0),
    saldo_esperado numeric(14,2),
    saldo_contado  numeric(14,2) CHECK (saldo_contado IS NULL OR saldo_contado >= 0),
    diferencia     numeric(14,2) GENERATED ALWAYS AS (saldo_contado - saldo_esperado) STORED,
    CONSTRAINT uq_sesion_moneda UNIQUE (sesion_id, moneda)
);
COMMENT ON COLUMN caja.sesion_saldo.diferencia IS 'Contado − esperado: positivo = sobrante, negativo = faltante.';

-- Arqueo por corte (opcional). Si se registra, debe sumar lo contado.
CREATE TABLE caja.arqueo (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id    bigint NOT NULL REFERENCES caja.sesion(id),
    moneda       char(3) NOT NULL CHECK (moneda IN ('BOB','USD')),
    denominacion numeric(8,2) NOT NULL CHECK (denominacion > 0),
    cantidad     integer NOT NULL CHECK (cantidad >= 0),
    subtotal     numeric(14,2) GENERATED ALWAYS AS (denominacion * cantidad) STORED,
    CONSTRAINT uq_arqueo_corte UNIQUE (sesion_id, moneda, denominacion)
);

/* ---------------------------------------------------------------------
   Movimientos
   --------------------------------------------------------------------- */
CREATE TABLE caja.movimiento (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id        bigint NOT NULL REFERENCES caja.sesion(id),
    caja_id          bigint NOT NULL REFERENCES caja.caja(id),
    numero           varchar(40) NOT NULL UNIQUE,
    fecha            timestamp(0) NOT NULL DEFAULT now(),
    tipo             varchar(7) NOT NULL CHECK (tipo IN ('INGRESO','EGRESO')),
    concepto_id      bigint NOT NULL REFERENCES caja.concepto(id),
    monto            numeric(14,2) NOT NULL CHECK (monto > 0),
    moneda           char(3) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB','USD')),
    forma_pago       varchar(15) NOT NULL DEFAULT 'EFECTIVO' CHECK (forma_pago IN ('EFECTIVO','CHEQUE','TRANSFERENCIA')),
    banco_id         bigint REFERENCES comun.banco(id),
    nro_documento    varchar(40),
    persona_nombre   varchar(150) NOT NULL,
    persona_ci       varchar(15),
    glosa            varchar(250) NOT NULL,
    estado           varchar(8) NOT NULL DEFAULT 'VIGENTE' CHECK (estado IN ('VIGENTE','ANULADO')),
    registrado_por   bigint NOT NULL REFERENCES public.users(id),
    anulado_por      bigint REFERENCES public.users(id),
    anulado_en       timestamp(0),
    motivo_anulacion varchar(250),
    created_at       timestamp(0),
    updated_at       timestamp(0),
    CONSTRAINT ck_mov_documento CHECK (forma_pago = 'EFECTIVO' OR (banco_id IS NOT NULL AND nro_documento IS NOT NULL)),
    CONSTRAINT ck_mov_anulado   CHECK (estado <> 'ANULADO' OR (anulado_por IS NOT NULL AND anulado_en IS NOT NULL AND motivo_anulacion IS NOT NULL))
);
CREATE INDEX ix_mov_sesion   ON caja.movimiento (sesion_id);
CREATE INDEX ix_mov_concepto ON caja.movimiento (concepto_id);
CREATE INDEX ix_mov_fecha    ON caja.movimiento (fecha);
COMMENT ON COLUMN caja.movimiento.persona_nombre IS 'A quién se paga (egreso) o quién entrega el dinero (ingreso).';

-- Saldo en efectivo de una sesión y moneda, al momento.
CREATE FUNCTION caja.saldo_efectivo(p_sesion_id bigint, p_moneda char) RETURNS numeric
LANGUAGE sql STABLE AS $$
    SELECT COALESCE((SELECT saldo_inicial FROM caja.sesion_saldo
                      WHERE sesion_id = p_sesion_id AND moneda = p_moneda), 0)
         + COALESCE((SELECT sum(CASE tipo WHEN 'INGRESO' THEN monto ELSE -monto END)
                       FROM caja.movimiento
                      WHERE sesion_id = p_sesion_id AND moneda = p_moneda
                        AND forma_pago = 'EFECTIVO' AND estado = 'VIGENTE'), 0)
$$;


