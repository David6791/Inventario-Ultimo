CREATE VIEW caja.v_sesion_resumen AS
SELECT s.id AS sesion_id, c.codigo AS caja, s.numero, s.estado,
       s.abierta_en, s.cerrada_en, ss.moneda,
       ss.saldo_inicial,
       COALESCE(m.ingresos_efectivo, 0)    AS ingresos_efectivo,
       COALESCE(m.egresos_efectivo, 0)     AS egresos_efectivo,
       COALESCE(m.ingresos_no_efectivo, 0) AS ingresos_no_efectivo,
       COALESCE(m.egresos_no_efectivo, 0)  AS egresos_no_efectivo,
       caja.saldo_efectivo(s.id, ss.moneda) AS saldo_efectivo_actual,
       ss.saldo_esperado, ss.saldo_contado, ss.diferencia
  FROM caja.sesion s
  JOIN caja.caja c          ON c.id = s.caja_id
  JOIN caja.sesion_saldo ss ON ss.sesion_id = s.id
  LEFT JOIN LATERAL (
        SELECT sum(monto) FILTER (WHERE tipo = 'INGRESO' AND forma_pago =  'EFECTIVO') AS ingresos_efectivo,
               sum(monto) FILTER (WHERE tipo = 'EGRESO'  AND forma_pago =  'EFECTIVO') AS egresos_efectivo,
               sum(monto) FILTER (WHERE tipo = 'INGRESO' AND forma_pago <> 'EFECTIVO') AS ingresos_no_efectivo,
               sum(monto) FILTER (WHERE tipo = 'EGRESO'  AND forma_pago <> 'EFECTIVO') AS egresos_no_efectivo
          FROM caja.movimiento
         WHERE sesion_id = s.id AND moneda = ss.moneda AND estado = 'VIGENTE') m ON true;

COMMIT;
