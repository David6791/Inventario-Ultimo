CREATE FUNCTION cargas.tg_bono_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    p cargas.pesaje; t cargas.bono_transporte_tramo;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los bonos de transporte no se eliminan: se anulan con motivo.';
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT * INTO p FROM cargas.pesaje WHERE id = NEW.pesaje_id;
        IF p.tipo <> 'INGRESO' OR p.anulado THEN
            RAISE EXCEPTION 'Solo un pesaje de INGRESO vigente genera bono de transporte.';
        END IF;
        IF NEW.tramo_id IS NULL THEN
            NEW.tramo_id := cargas.tramo_bono(p.peso_neto_kg, p.fecha::date);
        END IF;
        SELECT * INTO t FROM cargas.bono_transporte_tramo
         WHERE id = NEW.tramo_id
           AND numrange(peso_desde_kg, peso_hasta_kg, '[)') @> p.peso_neto_kg
           AND daterange(vigente_desde, vigente_hasta, '[)') @> p.fecha::date;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No hay tramo de bono vigente para % kg al %.', p.peso_neto_kg, p.fecha::date;
        END IF;
        NEW.monto  := t.monto;                    -- el monto sale del tramo, no se digita
        NEW.moneda := t.moneda;
        NEW.estado := 'PENDIENTE';
        NEW.movimiento_caja_id := NULL;
        NEW.beneficiario_nombre := COALESCE(NEW.beneficiario_nombre, p.chofer_nombre);
        NEW.beneficiario_ci     := COALESCE(NEW.beneficiario_ci, p.chofer_ci);
        RETURN NEW;
    END IF;

    -- UPDATE
    IF (NEW.pesaje_id, NEW.tramo_id, NEW.monto, NEW.moneda, NEW.registrado_por)
       IS DISTINCT FROM (OLD.pesaje_id, OLD.tramo_id, OLD.monto, OLD.moneda, OLD.registrado_por) THEN
        RAISE EXCEPTION 'Los datos de un bono de transporte no se modifican.';
    END IF;
    IF NEW.estado <> OLD.estado THEN
        IF NOT (OLD.estado = 'PENDIENTE' AND NEW.estado IN ('PAGADO','ANULADO')) THEN
            RAISE EXCEPTION 'Transición no permitida para el bono: % → %.', OLD.estado, NEW.estado;
        END IF;
        IF NEW.estado = 'PAGADO' THEN
            PERFORM cargas.validar_movimiento_caja(NEW.movimiento_caja_id, 'EGRESO', 'CARGAS_BONO',
                                                   NEW.monto, NEW.moneda, 'el bono de transporte');
        END IF;
    ELSIF NEW.movimiento_caja_id IS DISTINCT FROM OLD.movimiento_caja_id THEN
        RAISE EXCEPTION 'El comprobante de pago del bono no se cambia.';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER bono_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.bono_transporte
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_bono_control();


