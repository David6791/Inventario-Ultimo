    RETURN comun.generar_codigo('cargas.correlativo:' || c.clave, c.formato, c.reinicio, p_fecha);
END $$;


/* =====================================================================
   4. TABLAS DE PRECIO (reemplazan precios_carga y precios_sacos)
   - Cabecera con vigencia y aprobación por un segundo usuario.
   - Tramos con rango semiabierto [ley_desde, ley_hasta): sin huecos ni
     solapes posibles.
   - NO se guarda el valor calculado: se calcula con la regla vigente.
     Así no puede volver a pasar que una ley mayor pague menos.
   ===================================================================== */
CREATE TABLE cargas.tabla_precio (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    linea_producto_id bigint NOT NULL REFERENCES cargas.linea_producto(id),
    elemento_id       bigint NOT NULL REFERENCES cargas.elemento(id),
    modalidad         varchar(15) NOT NULL CHECK (modalidad IN ('POR_PUNTO','POR_PORCENTAJE')),
    moneda            char(3) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB','USD')),
    factor_conversion numeric(14,6),
    descripcion       varchar(200),
    vigente_desde     date NOT NULL,
    vigente_hasta     date,
    estado            varchar(10) NOT NULL DEFAULT 'BORRADOR' CHECK (estado IN ('BORRADOR','APROBADA','ANULADA')),
    creado_por        bigint NOT NULL REFERENCES public.users(id),
    aprobado_por      bigint REFERENCES public.users(id),
    aprobado_en       timestamp(0),
    created_at        timestamp(0),
    updated_at        timestamp(0),
    CONSTRAINT ck_tp_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta > vigente_desde),
    CONSTRAINT ck_tp_factor CHECK (
        (modalidad = 'POR_PORCENTAJE' AND factor_conversion > 0) OR
        (modalidad = 'POR_PUNTO'      AND factor_conversion IS NULL)),
    CONSTRAINT ck_tp_aprobada CHECK (estado <> 'APROBADA' OR (aprobado_por IS NOT NULL AND aprobado_en IS NOT NULL)),
    CONSTRAINT ck_tp_segregacion CHECK (aprobado_por IS NULL OR aprobado_por <> creado_por),
    CONSTRAINT ex_tp_solape EXCLUDE USING gist (
        linea_producto_id WITH =, elemento_id WITH =,
        daterange(vigente_desde, vigente_hasta, '[)') WITH &&) WHERE (estado = 'APROBADA')
);
COMMENT ON COLUMN cargas.tabla_precio.factor_conversion IS
  'Solo POR_PORCENTAJE: convierte (ley × % pagable) a la unidad de la cotización por TM, y a la moneda de la tabla si hace falta.';

CREATE TABLE cargas.tabla_precio_tramo (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_precio_id    bigint NOT NULL REFERENCES cargas.tabla_precio(id) ON DELETE CASCADE,
    ley_desde          numeric(12,4) NOT NULL CHECK (ley_desde >= 0),
    ley_hasta          numeric(12,4),
    precio_punto       numeric(14,4) CHECK (precio_punto IS NULL OR precio_punto > 0),
    porcentaje_pagable numeric(6,3)  CHECK (porcentaje_pagable IS NULL OR (porcentaje_pagable > 0 AND porcentaje_pagable <= 100)),
    CONSTRAINT ck_tramo_rango CHECK (ley_hasta IS NULL OR ley_hasta > ley_desde),
    CONSTRAINT ck_tramo_un_valor CHECK ((precio_punto IS NOT NULL) <> (porcentaje_pagable IS NOT NULL)),
    CONSTRAINT ex_tramo_solape EXCLUDE USING gist (
        tabla_precio_id WITH =, numrange(ley_desde, ley_hasta, '[)') WITH &&)
);

-- Los tramos solo se tocan mientras la tabla está en BORRADOR.
CREATE FUNCTION cargas.tg_tramo_solo_borrador() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_tabla bigint; v_estado varchar;
BEGIN
    v_tabla := CASE WHEN TG_OP = 'DELETE' THEN OLD.tabla_precio_id ELSE NEW.tabla_precio_id END;
    SELECT estado INTO v_estado FROM cargas.tabla_precio WHERE id = v_tabla;
    IF v_estado IS NOT NULL AND v_estado <> 'BORRADOR' THEN
        RAISE EXCEPTION 'La tabla de precios % está %: sus tramos no se pueden modificar. Cree una tabla nueva con otra vigencia.', v_tabla, v_estado;
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.tabla_precio_id <> OLD.tabla_precio_id THEN
        RAISE EXCEPTION 'Un tramo no se puede mover a otra tabla de precios.';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;

CREATE TRIGGER tramo_solo_borrador
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.tabla_precio_tramo
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_tramo_solo_borrador();

-- Control de la cabecera: validaciones al aprobar e inmutabilidad después.
CREATE FUNCTION cargas.tg_tabla_precio_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_modalidad_linea varchar;
    v_n          integer;
    r            record;
    v_hay_prev   boolean := false;
    v_prev_hasta numeric;
    v_prev_valor numeric;
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.estado <> 'BORRADOR' THEN
            RAISE EXCEPTION 'Solo se elimina una tabla de precios en BORRADOR; la tabla % está %. Anúlela o cierre su vigencia.', OLD.id, OLD.estado;
        END IF;
        RETURN OLD;
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.estado <> 'BORRADOR' THEN
            RAISE EXCEPTION 'Una tabla de precios nace en BORRADOR; se aprueba después de cargar sus tramos.';
        END IF;
        RETURN NEW;
    END IF;

    -- UPDATE
    IF OLD.estado = 'ANULADA' THEN
        RAISE EXCEPTION 'La tabla de precios % está anulada y no admite cambios.', OLD.id;
    END IF;

    IF OLD.estado = 'APROBADA' THEN
        IF NEW.estado = 'BORRADOR' THEN
            RAISE EXCEPTION 'Una tabla de precios aprobada no vuelve a borrador.';
        END IF;
        IF (NEW.linea_producto_id, NEW.elemento_id, NEW.modalidad, NEW.moneda, NEW.factor_conversion,
            NEW.vigente_desde, NEW.creado_por, NEW.aprobado_por, NEW.aprobado_en)
           IS DISTINCT FROM
           (OLD.linea_producto_id, OLD.elemento_id, OLD.modalidad, OLD.moneda, OLD.factor_conversion,
            OLD.vigente_desde, OLD.creado_por, OLD.aprobado_por, OLD.aprobado_en) THEN
            RAISE EXCEPTION 'Una tabla de precios aprobada solo admite cerrar su vigencia (vigente_hasta) o anularse.';
        END IF;
        RETURN NEW;
    END IF;

    -- OLD.estado = 'BORRADOR'
    IF NEW.estado = 'APROBADA' THEN
        SELECT modalidad_precio INTO v_modalidad_linea
          FROM cargas.linea_producto WHERE id = NEW.linea_producto_id;
        IF v_modalidad_linea <> NEW.modalidad THEN
            RAISE EXCEPTION 'La línea de producto se paga %, pero la tabla es %.', v_modalidad_linea, NEW.modalidad;
        END IF;

        SELECT count(*) INTO v_n FROM cargas.tabla_precio_tramo WHERE tabla_precio_id = NEW.id;
        IF v_n = 0 THEN
            RAISE EXCEPTION 'La tabla de precios % no tiene tramos: no se puede aprobar.', NEW.id;
        END IF;

        IF EXISTS (SELECT 1 FROM cargas.tabla_precio_tramo
                    WHERE tabla_precio_id = NEW.id
                      AND ((NEW.modalidad = 'POR_PUNTO'      AND precio_punto IS NULL) OR
                           (NEW.modalidad = 'POR_PORCENTAJE' AND porcentaje_pagable IS NULL))) THEN
            RAISE EXCEPTION 'Hay tramos que no corresponden a la modalidad % de la tabla.', NEW.modalidad;
        END IF;

        FOR r IN SELECT ley_desde, ley_hasta, COALESCE(precio_punto, porcentaje_pagable) AS valor
                   FROM cargas.tabla_precio_tramo
                  WHERE tabla_precio_id = NEW.id
                  ORDER BY ley_desde
        LOOP
            IF v_hay_prev THEN
                IF v_prev_hasta IS NULL OR r.ley_desde <> v_prev_hasta THEN
                    RAISE EXCEPTION 'Hay un hueco entre los tramos: uno termina en % y el siguiente empieza en %. Una ley en ese intervalo no tendría precio.',
                        COALESCE(v_prev_hasta::text, '∞'), r.ley_desde;
                END IF;
                IF r.valor < v_prev_valor THEN
                    RAISE EXCEPTION 'El tramo que empieza en ley % paga % y el anterior paga %: una ley mayor no puede valer menos.',
                        r.ley_desde, r.valor, v_prev_valor;
                END IF;
            END IF;
            v_hay_prev   := true;
            v_prev_hasta := r.ley_hasta;
            v_prev_valor := r.valor;
        END LOOP;
    END IF;

    RETURN NEW;
END $$;

CREATE TRIGGER tabla_precio_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.tabla_precio
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_tabla_precio_control();

-- Tabla aprobada vigente para una línea, un elemento y una fecha.
CREATE FUNCTION cargas.tabla_precio_vigente(p_linea_id bigint, p_elemento_id bigint, p_fecha date)
RETURNS bigint LANGUAGE sql STABLE AS $$
    SELECT id FROM cargas.tabla_precio
     WHERE linea_producto_id = p_linea_id
       AND elemento_id = p_elemento_id
       AND estado = 'APROBADA'
       AND daterange(vigente_desde, vigente_hasta, '[)') @> p_fecha
$$;

-- Valor por TM según la tabla. POR_PORCENTAJE necesita la cotización.
CREATE FUNCTION cargas.valor_por_tm(p_tabla_id bigint, p_ley numeric, p_cotizacion numeric DEFAULT NULL)
RETURNS numeric LANGUAGE plpgsql STABLE AS $$
DECLARE
    t  cargas.tabla_precio;
    tr cargas.tabla_precio_tramo;
BEGIN
    SELECT * INTO t FROM cargas.tabla_precio WHERE id = p_tabla_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La tabla de precios % no existe.', p_tabla_id;
    END IF;

    SELECT * INTO tr FROM cargas.tabla_precio_tramo
     WHERE tabla_precio_id = p_tabla_id
       AND numrange(ley_desde, ley_hasta, '[)') @> p_ley;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La ley % no cae en ningún tramo de la tabla de precios %.', p_ley, p_tabla_id;
    END IF;

    IF t.modalidad = 'POR_PUNTO' THEN
        RETURN round(p_ley * tr.precio_punto, 2);
    END IF;

    IF p_cotizacion IS NULL THEN
        RAISE EXCEPTION 'La tabla % es POR_PORCENTAJE: el valor depende de la cotización y no se pasó ninguna.', p_tabla_id;
    END IF;
    RETURN round(p_ley * tr.porcentaje_pagable / 100 * p_cotizacion * t.factor_conversion, 2);
END $$;


/* =====================================================================
   5. COTIZACIONES (reemplaza "cotizaciones" con período en texto libre)
   El período es año + mes + quincena; las fechas se derivan solas.
   ===================================================================== */
CREATE TABLE cargas.cotizacion (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elemento_id      bigint   NOT NULL REFERENCES cargas.elemento(id),
    tipo             varchar(10) NOT NULL DEFAULT 'OFICIAL' CHECK (tipo IN ('OFICIAL','REFERENCIA')),
    anio             smallint NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
    mes              smallint NOT NULL CHECK (mes BETWEEN 1 AND 12),
    quincena         smallint NOT NULL CHECK (quincena IN (1, 2)),
    periodo_desde    date GENERATED ALWAYS AS
                       (make_date(anio, mes, CASE quincena WHEN 1 THEN 1 ELSE 16 END)) STORED,
    periodo_hasta    date GENERATED ALWAYS AS
                       (CASE quincena WHEN 1 THEN make_date(anio, mes, 15)
                        ELSE (make_date(anio, mes, 1) + interval '1 month - 1 day')::date END) STORED,
    valor            numeric(14,4) NOT NULL CHECK (valor > 0),
    unidad           varchar(5) NOT NULL CHECK (unidad IN ('LF','OT','TMF','TM')),
    alicuota_rm_exportacion   numeric(7,4) CHECK (alicuota_rm_exportacion   BETWEEN 0 AND 100),
    alicuota_rm_venta_interna numeric(7,4) CHECK (alicuota_rm_venta_interna BETWEEN 0 AND 100),
    fuente           varchar(150),
    fecha_publicacion date,
    registrado_por   bigint NOT NULL REFERENCES public.users(id),
    created_at       timestamp(0),
    updated_at       timestamp(0),
    CONSTRAINT uq_cotizacion_periodo UNIQUE (elemento_id, tipo, anio, mes, quincena)
);
COMMENT ON TABLE cargas.cotizacion IS
  'Cotizaciones quincenales. OFICIAL = la publicada por el Ministerio de Minería (incluye alícuotas de regalía). REFERENCIA = cotización interna para tablas de compra.';

CREATE FUNCTION cargas.cotizacion_vigente(p_elemento_id bigint, p_fecha date, p_tipo varchar DEFAULT 'OFICIAL')
RETURNS numeric LANGUAGE sql STABLE AS $$
    SELECT valor FROM cargas.cotizacion
     WHERE elemento_id = p_elemento_id
       AND tipo = p_tipo
       AND p_fecha BETWEEN periodo_desde AND periodo_hasta
$$;


