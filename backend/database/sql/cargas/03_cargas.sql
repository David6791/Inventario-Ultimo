CREATE FUNCTION cargas.siguiente_correlativo(p_clave varchar, p_fecha date DEFAULT current_date)
RETURNS varchar LANGUAGE plpgsql AS $$
DECLARE
    c cargas.correlativo;
BEGIN
    SELECT * INTO c FROM cargas.correlativo WHERE clave = p_clave;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'No existe el correlativo «%».', p_clave;
