CREATE FUNCTION cargas.tg_lote_antes_insertar() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    s  cargas.serie_lote;
    v_mina_propia boolean; v_mina_municipio bigint;
BEGIN
    SELECT * INTO s FROM cargas.serie_lote WHERE id = NEW.serie_id;
    IF NOT FOUND OR NOT s.activa THEN
        RAISE EXCEPTION 'La serie de lotes % no existe o está inactiva.', NEW.serie_id;
    END IF;

    -- La serie manda: línea y origen no se eligen a mano.
    NEW.linea_producto_id := s.linea_producto_id;
    NEW.origen            := s.origen;
    NEW.estado            := 'RECIBIDO';

    IF NEW.productor_id IS NOT NULL AND NEW.cooperativa_id IS NULL THEN
        SELECT cooperativa_id INTO NEW.cooperativa_id FROM cargas.productor WHERE id = NEW.productor_id;
    END IF;

    IF NEW.mina_id IS NOT NULL THEN
        SELECT propia, municipio_id INTO v_mina_propia, v_mina_municipio
          FROM cargas.mina WHERE id = NEW.mina_id;
        IF NEW.municipio_id IS NULL THEN
            NEW.municipio_id := v_mina_municipio;
        END IF;
        IF NEW.origen = 'PROPIA' AND NOT v_mina_propia THEN
            RAISE EXCEPTION 'Un lote de producción propia debe venir de una mina propia de la empresa.';
        END IF;
        IF NEW.origen = 'COMPRA' AND v_mina_propia THEN
            RAISE EXCEPTION 'La mina % es propia: su mineral entra por una serie de producción propia, no de compra.', NEW.mina_id;
        END IF;
    ELSIF NEW.origen = 'PROPIA' THEN
        RAISE EXCEPTION 'Un lote de producción propia debe indicar la mina y la bocamina.';
    END IF;

    -- El código SIEMPRE lo genera la serie (con la fecha de recepción) y se
    -- toma al final: si algo de arriba falla, el número no se consume.
    NEW.codigo := cargas.generar_codigo_lote(NEW.serie_id, NEW.fecha_recepcion::date);
    RETURN NEW;
END $$;

CREATE TRIGGER lote_antes_insertar
    BEFORE INSERT ON cargas.lote
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_lote_antes_insertar();

CREATE FUNCTION cargas.tg_lote_antes_actualizar() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_faltan text;
BEGIN
    IF (NEW.codigo, NEW.serie_id, NEW.linea_producto_id, NEW.origen, NEW.registrado_por)
       IS DISTINCT FROM
       (OLD.codigo, OLD.serie_id, OLD.linea_producto_id, OLD.origen, OLD.registrado_por) THEN
        RAISE EXCEPTION 'El código, la serie, la línea, el origen y quién registró un lote no se pueden modificar.';
    END IF;

    IF OLD.estado IN ('ANULADO','LIQUIDADO') THEN
        RAISE EXCEPTION 'El lote % está % y ya no admite cambios.', OLD.codigo, OLD.estado;
    END IF;

    IF NEW.estado IS DISTINCT FROM OLD.estado THEN
        IF NOT ( (OLD.estado = 'RECIBIDO'   AND NEW.estado IN ('MUESTREADO','ANULADO'))
              OR (OLD.estado = 'MUESTREADO' AND NEW.estado IN ('ANALIZADO','ANULADO'))
              OR (OLD.estado = 'ANALIZADO'  AND NEW.estado IN ('MUESTREADO','LIQUIDADO','ANULADO')) ) THEN
            RAISE EXCEPTION 'Transición no permitida para el lote %: % → %.', OLD.codigo, OLD.estado, NEW.estado;
        END IF;

        IF NEW.estado = 'MUESTREADO' AND OLD.estado = 'RECIBIDO' THEN
            IF NOT EXISTS (SELECT 1 FROM cargas.pesaje
                            WHERE lote_id = NEW.id AND tipo = 'INGRESO' AND NOT anulado) THEN
                RAISE EXCEPTION 'El lote % no tiene ningún pesaje de ingreso vigente: no se puede muestrear.', NEW.codigo;
            END IF;
            IF NOT EXISTS (SELECT 1 FROM cargas.muestra WHERE lote_id = NEW.id) THEN
                RAISE EXCEPTION 'El lote % no tiene muestra registrada.', NEW.codigo;
            END IF;
        END IF;

        IF NEW.estado = 'ANULADO' AND EXISTS (
               SELECT 1 FROM cargas.anticipo
                WHERE lote_id = NEW.id AND estado IN ('PENDIENTE','AUTORIZADO','PAGADO')) THEN
            RAISE EXCEPTION 'El lote % tiene anticipos pendientes o pagados: anúlelos o registre su devolución antes de anular el lote.', NEW.codigo;
        END IF;

        IF NEW.estado = 'ANALIZADO' THEN
            SELECT string_agg(e.codigo, ', ' ORDER BY e.codigo) INTO v_faltan
              FROM cargas.elemento e
             WHERE (e.codigo = 'H2O'
                    OR e.id IN (SELECT elemento_id FROM cargas.linea_producto_elemento
                                 WHERE linea_producto_id = NEW.linea_producto_id AND rol = 'PAGABLE'))
               AND NOT EXISTS (SELECT 1 FROM cargas.lote_ley ll
                                WHERE ll.lote_id = NEW.id AND ll.elemento_id = e.id);
            IF v_faltan IS NOT NULL THEN
                RAISE EXCEPTION 'Falta la ley final de: % (lote %).', v_faltan, NEW.codigo;
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER lote_antes_actualizar
    BEFORE UPDATE ON cargas.lote
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_lote_antes_actualizar();

CREATE FUNCTION cargas.tg_lote_bitacora() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO cargas.lote_evento (lote_id, estado_anterior, estado_nuevo, usuario_id, detalle)
        VALUES (NEW.id, NULL, NEW.estado, NEW.registrado_por, 'Recepción');
    ELSIF NEW.estado IS DISTINCT FROM OLD.estado THEN
        INSERT INTO cargas.lote_evento (lote_id, estado_anterior, estado_nuevo, usuario_id, detalle)
        VALUES (NEW.id, OLD.estado, NEW.estado, cargas.usuario_actual(),
                CASE WHEN NEW.estado = 'ANULADO' THEN NEW.motivo_anulacion END);
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER lote_bitacora
    AFTER INSERT OR UPDATE ON cargas.lote
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_lote_bitacora();

