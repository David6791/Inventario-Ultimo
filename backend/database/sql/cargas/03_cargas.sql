/* =====================================================================
   11. ANTICIPOS (reemplaza "recibo")
   Un anticipo SIEMPRE pertenece a un lote: así la liquidación descuenta
   exactamente lo que se adelantó por esa carga. El productor se toma del
   lote. Se paga y se devuelve con movimientos de caja vinculados.
     PENDIENTE → AUTORIZADO → PAGADO → DEVUELTO
     PENDIENTE | AUTORIZADO → ANULADO
   Lo que la liquidación descuenta = anticipos PAGADOS del lote
   (los DEVUELTOS ya volvieron a caja).
   ===================================================================== */
CREATE TABLE cargas.anticipo (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero                   varchar(40) NOT NULL UNIQUE,
    lote_id                  bigint NOT NULL REFERENCES cargas.lote(id),
    productor_id             bigint NOT NULL REFERENCES cargas.productor(id),
    fecha                    date NOT NULL DEFAULT current_date,
    monto                    numeric(14,2) NOT NULL CHECK (monto > 0),
    moneda                   char(3) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB','USD')),
    concepto                 varchar(250) NOT NULL,
    estado                   varchar(10) NOT NULL DEFAULT 'PENDIENTE'
                             CHECK (estado IN ('PENDIENTE','AUTORIZADO','PAGADO','DEVUELTO','ANULADO')),
    registrado_por           bigint NOT NULL REFERENCES public.users(id),
    autorizado_por           bigint REFERENCES public.users(id),
    autorizado_en            timestamp(0),
    movimiento_pago_id       bigint UNIQUE REFERENCES caja.movimiento(id),
    movimiento_devolucion_id bigint UNIQUE REFERENCES caja.movimiento(id),
    anulado_por              bigint REFERENCES public.users(id),
    anulado_en               timestamp(0),
    motivo_anulacion         varchar(250),
    created_at               timestamp(0),
    updated_at               timestamp(0),
    CONSTRAINT ck_anticipo_segregacion CHECK (autorizado_por IS NULL OR autorizado_por <> registrado_por),
    CONSTRAINT ck_anticipo_autorizado  CHECK (estado IN ('PENDIENTE','ANULADO') OR (autorizado_por IS NOT NULL AND autorizado_en IS NOT NULL)),
    CONSTRAINT ck_anticipo_pago        CHECK ((estado IN ('PAGADO','DEVUELTO')) = (movimiento_pago_id IS NOT NULL)),
    CONSTRAINT ck_anticipo_devolucion  CHECK ((estado = 'DEVUELTO') = (movimiento_devolucion_id IS NOT NULL)),
    CONSTRAINT ck_anticipo_anulado     CHECK (estado <> 'ANULADO' OR (anulado_por IS NOT NULL AND anulado_en IS NOT NULL AND motivo_anulacion IS NOT NULL))
);
CREATE INDEX ix_anticipo_lote      ON cargas.anticipo (lote_id);
CREATE INDEX ix_anticipo_productor ON cargas.anticipo (productor_id);

CREATE FUNCTION cargas.tg_anticipo_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    l cargas.lote;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los anticipos no se eliminan: se anulan con motivo (anticipo %).', OLD.numero;
    END IF;

    SELECT * INTO l FROM cargas.lote WHERE id = NEW.lote_id;

    IF TG_OP = 'INSERT' THEN
        IF l.origen = 'PROPIA' THEN
            RAISE EXCEPTION 'El lote % es de producción propia: no recibe anticipos.', l.codigo;
        END IF;
        IF l.estado IN ('ANULADO','LIQUIDADO') THEN
            RAISE EXCEPTION 'El lote % está % y no admite anticipos.', l.codigo, l.estado;
        END IF;
        NEW.productor_id := l.productor_id;        -- el productor sale del lote
        NEW.estado := 'PENDIENTE';
        NEW.autorizado_por := NULL; NEW.autorizado_en := NULL;
        NEW.movimiento_pago_id := NULL; NEW.movimiento_devolucion_id := NULL;
        NEW.numero := cargas.siguiente_correlativo('ANTICIPO', NEW.fecha);
        RETURN NEW;
    END IF;

    -- UPDATE
    IF (NEW.numero, NEW.lote_id, NEW.productor_id, NEW.monto, NEW.moneda, NEW.fecha, NEW.registrado_por)
       IS DISTINCT FROM
       (OLD.numero, OLD.lote_id, OLD.productor_id, OLD.monto, OLD.moneda, OLD.fecha, OLD.registrado_por) THEN
        RAISE EXCEPTION 'Los datos del anticipo % no se modifican; si están mal, anúlelo y registre otro.', OLD.numero;
    END IF;
    IF OLD.movimiento_pago_id IS NOT NULL AND NEW.movimiento_pago_id IS DISTINCT FROM OLD.movimiento_pago_id THEN
        RAISE EXCEPTION 'El comprobante de pago del anticipo % no se cambia.', OLD.numero;
    END IF;

    IF NEW.estado <> OLD.estado THEN
        IF NOT ( (OLD.estado = 'PENDIENTE'  AND NEW.estado IN ('AUTORIZADO','ANULADO'))
              OR (OLD.estado = 'AUTORIZADO' AND NEW.estado IN ('PAGADO','ANULADO'))
              OR (OLD.estado = 'PAGADO'     AND NEW.estado = 'DEVUELTO') ) THEN
            RAISE EXCEPTION 'Transición no permitida para el anticipo %: % → %.', OLD.numero, OLD.estado, NEW.estado;
        END IF;
        IF NEW.estado = 'PAGADO' THEN
            IF l.estado IN ('ANULADO','LIQUIDADO') THEN
                RAISE EXCEPTION 'El lote % está %: el anticipo % ya no se paga.', l.codigo, l.estado, OLD.numero;
            END IF;
            PERFORM cargas.validar_movimiento_caja(NEW.movimiento_pago_id, 'EGRESO', 'CARGAS_ANTICIPO',
                                                   NEW.monto, NEW.moneda, 'el anticipo ' || NEW.numero);
        END IF;
        IF NEW.estado = 'DEVUELTO' THEN
            IF l.estado = 'LIQUIDADO' THEN
                RAISE EXCEPTION 'El lote % ya está liquidado: el anticipo % ya se descontó.', l.codigo, OLD.numero;
            END IF;
            PERFORM cargas.validar_movimiento_caja(NEW.movimiento_devolucion_id, 'INGRESO', 'CARGAS_ANTICIPO_DEVOLUCION',
                                                   NEW.monto, NEW.moneda, 'la devolución del anticipo ' || NEW.numero);
        END IF;
    ELSIF NEW.movimiento_devolucion_id IS DISTINCT FROM OLD.movimiento_devolucion_id THEN
        RAISE EXCEPTION 'El comprobante de devolución solo se registra al pasar a DEVUELTO.';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER anticipo_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.anticipo
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_anticipo_control();


/* =====================================================================
   12. INTEGRACIÓN CON CAJA
   Reglas que cargas impone sobre caja.movimiento (caja no las conoce):
   a) Un movimiento con concepto de origen CARGAS_* debe quedar vinculado
      a su documento de cargas antes de que termine la transacción. Así no
      puede existir un "anticipo" pagado por caja sin lote.
   b) Un movimiento que respalda un pago de cargas no se anula desde caja.
   ===================================================================== */
CREATE FUNCTION cargas.tg_mov_caja_vinculado() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_origen varchar;
BEGIN
    SELECT origen INTO v_origen FROM caja.concepto WHERE id = NEW.concepto_id;
    IF v_origen NOT LIKE 'CARGAS\_%' THEN
        RETURN NULL;
    END IF;
    IF v_origen = 'CARGAS_ANTICIPO' THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.anticipo WHERE movimiento_pago_id = NEW.id) THEN
            RAISE EXCEPTION 'El comprobante % es un pago de anticipo pero no está vinculado a ningún anticipo de un lote.', NEW.numero;
        END IF;
    ELSIF v_origen = 'CARGAS_ANTICIPO_DEVOLUCION' THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.anticipo WHERE movimiento_devolucion_id = NEW.id) THEN
            RAISE EXCEPTION 'El comprobante % es una devolución de anticipo pero no está vinculado a ningún anticipo.', NEW.numero;
        END IF;
    ELSIF v_origen = 'CARGAS_BONO' THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.bono_transporte WHERE movimiento_caja_id = NEW.id) THEN
            RAISE EXCEPTION 'El comprobante % es un pago de bono de transporte pero no está vinculado a ningún bono.', NEW.numero;
        END IF;
    ELSE
        RAISE EXCEPTION 'El concepto de origen % todavía no tiene documento en cargas: no se puede usar.', v_origen;
    END IF;
    RETURN NULL;
END $$;

-- Diferido: se verifica al confirmar la transacción, cuando el servicio
-- ya creó el movimiento Y vinculó el documento.
CREATE CONSTRAINT TRIGGER cargas_mov_vinculado
    AFTER INSERT ON caja.movimiento
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_mov_caja_vinculado();

CREATE FUNCTION cargas.tg_mov_caja_no_anular() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_doc varchar;
BEGIN
    IF NEW.estado = 'ANULADO' AND OLD.estado = 'VIGENTE' THEN
        SELECT 'el anticipo ' || numero INTO v_doc FROM cargas.anticipo
         WHERE movimiento_pago_id = NEW.id OR movimiento_devolucion_id = NEW.id;
        IF v_doc IS NULL THEN
            SELECT 'un bono de transporte' INTO v_doc FROM cargas.bono_transporte WHERE movimiento_caja_id = NEW.id;
        END IF;
        IF v_doc IS NOT NULL THEN
            RAISE EXCEPTION 'El comprobante % respalda %: no se anula desde caja. Si el pago fue indebido, registre la devolución.', NEW.numero, v_doc;
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER cargas_mov_no_anular
    BEFORE UPDATE OF estado ON caja.movimiento
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_mov_caja_no_anular();


