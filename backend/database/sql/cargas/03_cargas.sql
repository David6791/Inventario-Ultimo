/* =====================================================================
   03 — MÓDULO DE MANEJO DE CARGAS — ESQUEMA cargas (PostgreSQL 16)
   Exportadora MACGYCASUCHOS S.R.L.
   ---------------------------------------------------------------------
   Alcance: desde la llegada del camión hasta ANTES de la liquidación.
     catálogos → tablas de precio → cotizaciones → retenciones
     → lote (recepción) → pesaje → bono de transporte → muestreo
     → análisis → ley final → anticipos
   La liquidación queda para la siguiente etapa (falta la planilla Excel).

   Depende de: comun (numeración, bancos) y caja (pagos). Los anticipos y
   los bonos se pagan con un movimiento de caja vinculado; caja no sabe
   nada de cargas.

   Convenciones heredadas del módulo de activos:
     - Esquema propio; usuarios y almacenes siguen en public.
     - Parámetros y tarifas con vigencia: cambiar un valor es cerrar la
       fila vigente y abrir otra, nunca un UPDATE del valor.
     - Segregación de funciones: quien registra no autoriza.
     - Los lotes no se borran: se anulan.

   Requisito: extensión btree_gist (es "trusted": la puede crear el dueño
   de la base sin ser superusuario).

   Identificación del usuario en los cambios de estado:
     Las transiciones de estado del lote se registran en la bitácora con el
     usuario de la transacción. La aplicación debe ejecutar, al iniciar
     cada transacción:
         SELECT set_config('cargas.usuario_id', '<id del usuario>', true);
     (en Laravel: DB::select("select set_config('cargas.usuario_id', ?, true)", [$id])
      dentro de DB::transaction). Sin eso, el cambio de estado se rechaza.
   ===================================================================== */

BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA IF NOT EXISTS cargas;

/* ---------------------------------------------------------------------
   Utilidad: usuario de la transacción (para la bitácora)
   --------------------------------------------------------------------- */
CREATE FUNCTION cargas.usuario_actual() RETURNS bigint
LANGUAGE plpgsql STABLE AS $$
DECLARE
    v text := current_setting('cargas.usuario_id', true);
BEGIN
    IF v IS NULL OR v = '' THEN
        RAISE EXCEPTION 'Falta identificar al usuario de la transacción: ejecute set_config(''cargas.usuario_id'', <id>, true) antes de cambiar estados.';
    END IF;
    RETURN v::bigint;
END $$;


/* =====================================================================
   1. PARÁMETROS (mismo patrón que activos.parametro, con una mejora:
      además del único por fecha, se impide que dos vigencias se pisen)
   ===================================================================== */
CREATE TABLE cargas.parametro (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave         varchar(60)  NOT NULL,
    valor         varchar(200) NOT NULL,
    tipo_dato     varchar(10)  NOT NULL CHECK (tipo_dato IN ('texto','numero','fecha','booleano')),
    descripcion   text,
    vigente_desde date NOT NULL,
    vigente_hasta date,
    created_at    timestamp(0),
    updated_at    timestamp(0),
    CONSTRAINT ck_parametro_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta > vigente_desde),
    CONSTRAINT ex_parametro_solape EXCLUDE USING gist
        (clave WITH =, daterange(vigente_desde, vigente_hasta, '[)') WITH &&)
);
COMMENT ON TABLE cargas.parametro IS 'Parámetros del módulo con historia de valores (p. ej. tipo de cambio).';


/* =====================================================================
   2. CATÁLOGOS
   ===================================================================== */

-- Elementos químicos y la humedad. La ley de cada elemento se guarda
-- SIEMPRE en su unidad_ley; las tablas de precio y los análisis la usan.
CREATE TABLE cargas.elemento (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            varchar(10) NOT NULL UNIQUE,
    nombre            varchar(60) NOT NULL,
    unidad_ley        varchar(10) NOT NULL CHECK (unidad_ley IN ('%','DM','G_TM','OZ_TM','PPM')),
    unidad_cotizacion varchar(5)  CHECK (unidad_cotizacion IN ('LF','OT','TMF','TM')),
    activo            boolean NOT NULL DEFAULT true,
    created_at        timestamp(0),
    updated_at        timestamp(0)
);
COMMENT ON COLUMN cargas.elemento.unidad_ley IS '% · DM (decimarcos) · G_TM · OZ_TM · PPM. Todas las leyes del elemento se expresan en esta unidad.';
COMMENT ON COLUMN cargas.elemento.unidad_cotizacion IS 'LF libra fina · OT onza troy · TMF tonelada métrica fina · TM tonelada métrica.';

-- Municipios: el municipio productor reparte la regalía (85% Gobernación / 15% municipio).
CREATE TABLE cargas.municipio (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       varchar(10) UNIQUE,
    nombre       varchar(100) NOT NULL,
    departamento varchar(30)  NOT NULL DEFAULT 'POTOSI',
    created_at   timestamp(0),
    updated_at   timestamp(0),
    CONSTRAINT uq_municipio_nombre UNIQUE (departamento, nombre)
);

CREATE TABLE cargas.cooperativa (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       varchar(150) NOT NULL,
    sigla        varchar(30),
    nit          varchar(20) UNIQUE,
    nim          varchar(30) UNIQUE,
    municipio_id bigint REFERENCES cargas.municipio(id),
    activa       boolean NOT NULL DEFAULT true,
    created_at   timestamp(0),
    updated_at   timestamp(0)
);
-- Evita el "CERRO RICO R.L." duplicado del sistema anterior: compara sin
-- mayúsculas y colapsando espacios.
CREATE UNIQUE INDEX ux_cooperativa_nombre
    ON cargas.cooperativa (upper(regexp_replace(btrim(nombre), '\s+', ' ', 'g')));

-- Minas: de cooperativas, de particulares o PROPIAS de la empresa.
CREATE TABLE cargas.mina (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         varchar(150) NOT NULL,
    propia         boolean NOT NULL DEFAULT false,
    cooperativa_id bigint REFERENCES cargas.cooperativa(id),
    municipio_id   bigint REFERENCES cargas.municipio(id),
    activa         boolean NOT NULL DEFAULT true,
    created_at     timestamp(0),
    updated_at     timestamp(0),
    CONSTRAINT ck_mina_propia_sin_cooperativa CHECK (NOT propia OR cooperativa_id IS NULL)
);
CREATE UNIQUE INDEX ux_mina_nombre
    ON cargas.mina (COALESCE(cooperativa_id, 0), upper(regexp_replace(btrim(nombre), '\s+', ' ', 'g')));

-- Bocaminas: puntos de extracción. Obligatorias para la producción propia.
CREATE TABLE cargas.bocamina (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mina_id    bigint NOT NULL REFERENCES cargas.mina(id),
    codigo     varchar(20)  NOT NULL,
    nombre     varchar(100),
    activa     boolean NOT NULL DEFAULT true,
    created_at timestamp(0),
    updated_at timestamp(0),
    CONSTRAINT uq_bocamina_codigo UNIQUE (mina_id, codigo),
    CONSTRAINT uq_bocamina_id_mina UNIQUE (id, mina_id)      -- destino de la FK compuesta del lote
);

-- Productor = el "cliente" del sistema anterior: quien entrega mineral.
CREATE TABLE cargas.productor (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo           varchar(15) NOT NULL CHECK (tipo IN ('COOPERATIVISTA','PARTICULAR','EMPRESA','INGENIO')),
    nombre         varchar(150) NOT NULL,
    ci             varchar(15) UNIQUE,
    nit            varchar(20) UNIQUE,
    nim            varchar(30) UNIQUE,
    telefono       varchar(20),
    domicilio      varchar(200),
    cooperativa_id bigint REFERENCES cargas.cooperativa(id),
    activo         boolean NOT NULL DEFAULT true,
    created_at     timestamp(0),
    updated_at     timestamp(0),
    CONSTRAINT ck_productor_cooperativa CHECK (tipo <> 'COOPERATIVISTA' OR cooperativa_id IS NOT NULL),
    CONSTRAINT ck_productor_identificacion CHECK (ci IS NOT NULL OR nit IS NOT NULL)
);
CREATE INDEX ix_productor_cooperativa ON cargas.productor (cooperativa_id);
CREATE INDEX ix_productor_nombre ON cargas.productor (upper(nombre));

CREATE TABLE cargas.laboratorio (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     varchar(120) NOT NULL UNIQUE,
    nit        varchar(20),
    propio     boolean NOT NULL DEFAULT false,
    acreditado boolean NOT NULL DEFAULT false,
    activo     boolean NOT NULL DEFAULT true,
    created_at timestamp(0),
    updated_at timestamp(0)
);


/* =====================================================================
   3. LÍNEAS DE PRODUCTO Y SERIES DE LOTE
   El sistema anterior mezclaba en "numeracion" el tipo de producto y la
   procedencia. Aquí la LÍNEA dice qué es y cómo se paga; la SERIE dice
   cómo se numera y si es compra o producción propia.
   ===================================================================== */
CREATE TABLE cargas.linea_producto (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           varchar(20)  NOT NULL UNIQUE,
    nombre           varchar(100) NOT NULL,
    forma            varchar(15)  NOT NULL CHECK (forma IN ('CARGA','BROSA','CONCENTRADO','SACOS')),
    modalidad_precio varchar(25)  NOT NULL CHECK (modalidad_precio IN ('POR_PUNTO','POR_PORCENTAJE','VALORACION_CONCENTRADO')),
    activa           boolean NOT NULL DEFAULT true,
    created_at       timestamp(0),
    updated_at       timestamp(0)
);
COMMENT ON COLUMN cargas.linea_producto.modalidad_precio IS
  'POR_PUNTO: valor/TM = ley × precio por punto. POR_PORCENTAJE: valor/TM = ley × % pagable × cotización × factor. VALORACION_CONCENTRADO: fórmula de concentrado (etapa de liquidación).';

-- Qué elementos se miden en cada línea y con qué rol.
CREATE TABLE cargas.linea_producto_elemento (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    linea_producto_id bigint NOT NULL REFERENCES cargas.linea_producto(id) ON DELETE CASCADE,
    elemento_id       bigint NOT NULL REFERENCES cargas.elemento(id),
    rol               varchar(15) NOT NULL CHECK (rol IN ('PAGABLE','PENALIZABLE','INFORMATIVO')),
    split_limit       numeric(12,4) CHECK (split_limit IS NULL OR split_limit > 0),
    CONSTRAINT uq_linea_elemento UNIQUE (linea_producto_id, elemento_id)
);
COMMENT ON COLUMN cargas.linea_producto_elemento.split_limit IS
  'Diferencia máxima tolerada entre el ensaye de la empresa y el del productor, en la unidad del elemento. Si se supera, se va a dirimencia.';

/* ---------------------------------------------------------------------
   Series de lote con FORMATO CONFIGURABLE (desde la interfaz).
   Marcadores disponibles para lotes, además de los generales de
   comun.validar_formato ({AAAA} {AA} {MM} {DD} {N:k}):
       {PREFIJO}  prefijo de la serie          (CZP)
       {LINEA}    código de la línea           (COMPLEJO_ZN_AG)
       {ORIGEN}   C = compra, P = producción propia
       {SIGLA}    parámetro SIGLA_EMPRESA vigente (MAC)
   La fecha que se usa es la de recepción del lote.
   Ejemplos:
       '{PREFIJO}-{AAAA}{MM}-{N:4}'  MENSUAL → CZP-202610-0001
       '{SIGLA}{ORIGEN}-{AA}-{N:5}'  ANUAL   → MACC-26-00001
       '{PREFIJO}{N:6}'              NUNCA   → CZP000001
   --------------------------------------------------------------------- */
CREATE TABLE cargas.serie_lote (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prefijo           varchar(10)  NOT NULL UNIQUE CHECK (prefijo ~ '^[A-Z0-9]+(-[A-Z0-9]+)*$'),
    nombre            varchar(100) NOT NULL,
    linea_producto_id bigint NOT NULL REFERENCES cargas.linea_producto(id),
    origen            varchar(10)  NOT NULL CHECK (origen IN ('COMPRA','PROPIA')),
    formato           varchar(60)  NOT NULL DEFAULT '{PREFIJO}-{AAAA}{MM}-{N:4}',
    reinicio          varchar(10)  NOT NULL DEFAULT 'MENSUAL',
    activa            boolean  NOT NULL DEFAULT true,
    created_at        timestamp(0),
    updated_at        timestamp(0)
);
COMMENT ON COLUMN cargas.serie_lote.formato IS
  'Formato del código de lote. Marcadores: {PREFIJO} {LINEA} {ORIGEN} {SIGLA} {AAAA} {AA} {MM} {DD} {N:k}.';
COMMENT ON COLUMN cargas.serie_lote.reinicio IS 'Cuándo vuelve a 1 el correlativo: NUNCA, ANUAL, MENSUAL o DIARIO.';

CREATE FUNCTION cargas.marcadores_lote() RETURNS text[]
LANGUAGE sql IMMUTABLE AS $$ SELECT ARRAY['PREFIJO','LINEA','ORIGEN','SIGLA'] $$;

CREATE FUNCTION cargas.tg_serie_lote_formato() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    PERFORM comun.validar_formato(NEW.formato, NEW.reinicio, cargas.marcadores_lote());
    RETURN NEW;
END $$;

CREATE TRIGGER serie_lote_formato
    BEFORE INSERT OR UPDATE OF formato, reinicio ON cargas.serie_lote
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_serie_lote_formato();

CREATE FUNCTION cargas.parametro_vigente(p_clave varchar, p_fecha date DEFAULT current_date)
RETURNS varchar LANGUAGE sql STABLE AS $$
    SELECT valor FROM cargas.parametro
     WHERE clave = p_clave
       AND daterange(vigente_desde, vigente_hasta, '[)') @> p_fecha
$$;

-- Datos de la serie que el formato puede usar.
CREATE FUNCTION cargas.datos_codigo_lote(p_serie_id bigint, p_fecha date) RETURNS jsonb
LANGUAGE sql STABLE AS $$
    SELECT jsonb_build_object(
               'PREFIJO', s.prefijo,
               'LINEA',   lp.codigo,
               'ORIGEN',  CASE s.origen WHEN 'COMPRA' THEN 'C' ELSE 'P' END,
               'SIGLA',   cargas.parametro_vigente('SIGLA_EMPRESA', p_fecha))
      FROM cargas.serie_lote s
      JOIN cargas.linea_producto lp ON lp.id = s.linea_producto_id
     WHERE s.id = p_serie_id
$$;

-- Genera (y consume) el código del lote.
CREATE FUNCTION cargas.generar_codigo_lote(p_serie_id bigint, p_fecha date) RETURNS varchar
LANGUAGE plpgsql AS $$
DECLARE
    s cargas.serie_lote;
BEGIN
    SELECT * INTO s FROM cargas.serie_lote WHERE id = p_serie_id;
    IF NOT FOUND OR NOT s.activa THEN
        RAISE EXCEPTION 'La serie de lotes % no existe o está inactiva.', p_serie_id;
    END IF;
    RETURN comun.generar_codigo('cargas.serie_lote:' || s.id, s.formato, s.reinicio, p_fecha,
                                cargas.datos_codigo_lote(s.id, p_fecha));
END $$;

/* Vista previa para la pantalla de configuración: cómo saldría el PRÓXIMO
   lote. Si se pasan p_formato/p_reinicio, previsualiza un formato que
   todavía no se guardó (y lo valida). No consume números. */
CREATE FUNCTION cargas.vista_previa_codigo_lote(p_serie_id bigint, p_fecha date DEFAULT current_date,
                                                p_formato varchar DEFAULT NULL, p_reinicio varchar DEFAULT NULL)
RETURNS varchar LANGUAGE plpgsql STABLE AS $$
DECLARE
    s cargas.serie_lote;
BEGIN
    SELECT * INTO s FROM cargas.serie_lote WHERE id = p_serie_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La serie de lotes % no existe.', p_serie_id;
    END IF;
    RETURN comun.vista_previa_codigo('cargas.serie_lote:' || s.id,
                                     COALESCE(p_formato, s.formato), COALESCE(p_reinicio, s.reinicio),
                                     p_fecha, cargas.datos_codigo_lote(s.id, p_fecha),
                                     cargas.marcadores_lote());
END $$;

