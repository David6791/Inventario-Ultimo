-- Comparación de ensayes de la última muestra de cada lote.
CREATE VIEW cargas.v_lote_comparacion_leyes AS
WITH ultima AS (
    SELECT DISTINCT ON (lote_id) id AS muestra_id, lote_id
      FROM cargas.muestra
     ORDER BY lote_id, id DESC
), r AS (
    SELECT u.lote_id, a.tipo, ar.elemento_id, ar.valor
      FROM ultima u
      JOIN cargas.analisis a            ON a.muestra_id = u.muestra_id AND NOT a.anulado
      JOIN cargas.analisis_resultado ar ON ar.analisis_id = a.id
     WHERE a.tipo IN ('EMPRESA','PRODUCTOR','DIRIMENTE')
), p AS (
    SELECT lote_id, elemento_id,
           max(valor) FILTER (WHERE tipo = 'EMPRESA')   AS ley_empresa,
           max(valor) FILTER (WHERE tipo = 'PRODUCTOR') AS ley_productor,
           max(valor) FILTER (WHERE tipo = 'DIRIMENTE') AS ley_dirimente
      FROM r GROUP BY lote_id, elemento_id
)
SELECT l.id AS lote_id, l.codigo AS lote, e.codigo AS elemento,
       p.ley_empresa, p.ley_productor, p.ley_dirimente,
       abs(p.ley_empresa - p.ley_productor)                     AS diferencia,
       lpe.split_limit,
       abs(p.ley_empresa - p.ley_productor) > lpe.split_limit   AS excede_split_limit,
       round((p.ley_empresa + p.ley_productor) / 2, 4)          AS promedio
  FROM p
  JOIN cargas.lote l     ON l.id = p.lote_id
  JOIN cargas.elemento e ON e.id = p.elemento_id
  LEFT JOIN cargas.linea_producto_elemento lpe
         ON lpe.linea_producto_id = l.linea_producto_id AND lpe.elemento_id = p.elemento_id;

-- Resumen de cada lote: pesos, humedad, peso seco, leyes y anticipos.
CREATE VIEW cargas.v_lote_resumen AS
SELECT l.id AS lote_id, l.codigo AS lote, l.estado, l.origen, l.fecha_recepcion,
       lp.codigo AS linea, pr.nombre AS productor, c.nombre AS cooperativa,
       ps.num_pesajes, ps.num_sacos,
       ps.peso_neto_humedo_kg,
       h.valor                                                       AS humedad_pct,
       round(ps.peso_neto_humedo_kg * (1 - h.valor / 100), 2)        AS peso_neto_seco_kg,
       max(ll.valor) FILTER (WHERE e.codigo = 'ZN') AS ley_zn,
       max(ll.valor) FILTER (WHERE e.codigo = 'PB') AS ley_pb,
       max(ll.valor) FILTER (WHERE e.codigo = 'AG') AS ley_ag,
       COALESCE(an.pagado_bob, 0) AS anticipos_pagados_bob,
       COALESCE(an.pagado_usd, 0) AS anticipos_pagados_usd,
       COALESCE(an.por_pagar, 0)  AS anticipos_por_pagar
  FROM cargas.lote l
  JOIN cargas.linea_producto lp ON lp.id = l.linea_producto_id
  LEFT JOIN cargas.productor   pr ON pr.id = l.productor_id
  LEFT JOIN cargas.cooperativa c  ON c.id  = l.cooperativa_id
  LEFT JOIN LATERAL (
        SELECT count(*) AS num_pesajes, sum(num_sacos) AS num_sacos,
               COALESCE(sum(peso_neto_kg), 0) AS peso_neto_humedo_kg
          FROM cargas.pesaje
         WHERE lote_id = l.id AND tipo = 'INGRESO' AND NOT anulado) ps ON true
  LEFT JOIN cargas.lote_ley ll ON ll.lote_id = l.id
  LEFT JOIN cargas.elemento e  ON e.id = ll.elemento_id
  LEFT JOIN LATERAL (
        SELECT x.valor FROM cargas.lote_ley x
          JOIN cargas.elemento ex ON ex.id = x.elemento_id AND ex.codigo = 'H2O'
         WHERE x.lote_id = l.id) h ON true
  LEFT JOIN LATERAL (
        SELECT sum(monto) FILTER (WHERE moneda = 'BOB' AND estado = 'PAGADO') AS pagado_bob,
               sum(monto) FILTER (WHERE moneda = 'USD' AND estado = 'PAGADO') AS pagado_usd,
               count(*)   FILTER (WHERE estado IN ('PENDIENTE','AUTORIZADO'))  AS por_pagar
          FROM cargas.anticipo
         WHERE lote_id = l.id) an ON true
 GROUP BY l.id, lp.codigo, pr.nombre, c.nombre, ps.num_pesajes, ps.num_sacos,
          ps.peso_neto_humedo_kg, h.valor, an.pagado_bob, an.pagado_usd, an.por_pagar;

-- Lo que la liquidación de cada lote deberá descontar.
CREATE VIEW cargas.v_lote_anticipos_a_descontar AS
SELECT l.id AS lote_id, l.codigo AS lote, a.moneda,
       sum(a.monto) AS total, count(*) AS cantidad,
       string_agg(a.numero, ', ' ORDER BY a.numero) AS anticipos
  FROM cargas.anticipo a
  JOIN cargas.lote l ON l.id = a.lote_id
 WHERE a.estado = 'PAGADO'
 GROUP BY l.id, l.codigo, a.moneda;

-- Anticipos por productor (cuenta corriente previa a la liquidación).
CREATE VIEW cargas.v_productor_anticipos AS
SELECT pr.id AS productor_id, pr.nombre AS productor, a.moneda,
       sum(a.monto) FILTER (WHERE a.estado = 'PAGADO')                                  AS pagado_vigente,
       sum(a.monto) FILTER (WHERE a.estado = 'PAGADO' AND l.estado <> 'LIQUIDADO')      AS en_lotes_sin_liquidar,
       sum(a.monto) FILTER (WHERE a.estado = 'DEVUELTO')                                AS devuelto,
       sum(a.monto) FILTER (WHERE a.estado IN ('PENDIENTE','AUTORIZADO'))               AS por_pagar
  FROM cargas.anticipo a
  JOIN cargas.productor pr ON pr.id = a.productor_id
  JOIN cargas.lote l       ON l.id = a.lote_id
 GROUP BY pr.id, pr.nombre, a.moneda;

COMMIT;
