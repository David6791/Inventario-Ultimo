/* Un pago de cargas se respalda con un movimiento de caja que cumpla:
   vigente, del tipo y concepto correctos, mismo monto y misma moneda. */
CREATE FUNCTION cargas.validar_movimiento_caja(p_movimiento_id bigint, p_tipo varchar, p_origen varchar,
                                               p_monto numeric, p_moneda char, p_documento varchar)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    m caja.movimiento; v_origen varchar;
BEGIN
    IF p_movimiento_id IS NULL THEN
        RAISE EXCEPTION 'Para registrar % indique el comprobante de caja que lo respalda.', p_documento;
    END IF;
    SELECT * INTO m FROM caja.movimiento WHERE id = p_movimiento_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El movimiento de caja % no existe.', p_movimiento_id;
    END IF;
    SELECT origen INTO v_origen FROM caja.concepto WHERE id = m.concepto_id;
    IF m.estado <> 'VIGENTE' THEN
        RAISE EXCEPTION 'El comprobante % está anulado: no respalda %.', m.numero, p_documento;
    END IF;
    IF m.tipo <> p_tipo OR v_origen <> p_origen THEN
        RAISE EXCEPTION 'El comprobante % no corresponde a % (debe ser un % con concepto de origen %).', m.numero, p_documento, p_tipo, p_origen;
    END IF;
    IF m.monto <> p_monto OR m.moneda <> p_moneda THEN
        RAISE EXCEPTION 'El comprobante % es por % % y % es por % %.', m.numero, m.monto, m.moneda, p_documento, p_monto, p_moneda;
    END IF;
END $$;

