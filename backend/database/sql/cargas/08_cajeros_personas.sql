/* =====================================================================
   08 — CAJEROS Y PERSONAS (sprint 2) — esquema caja
   ---------------------------------------------------------------------
   1. CAJEROS. Cada caja tiene sus cajeros asignados. Solo ellos abren la
      sesión, registran movimientos, los anulan y cierran la caja. Tener el
      permiso no basta: el permiso dice QUÉ puede hacer el usuario, la
      asignación dice EN QUÉ CAJA. Quien administra o supervisa las cajas
      las consulta, pero no opera en ellas si no está asignado.

   2. PERSONAS. Registro de todas las personas (o empresas) a quienes la
      caja paga o de quienes recibe dinero. Cada movimiento queda vinculado
      a su persona: así se puede ver todo lo que se le pagó a alguien.
      La base la resuelve sola al registrar el movimiento:
        - con persona_id, copia el nombre y el CI de la persona;
        - sin persona_id, la busca por CI (o por nombre si no hay CI) y, si
          no existe, la crea.
      El movimiento guarda además el nombre y el CI tal como estaban ese día
      (lo que sale impreso en el comprobante), aunque después se corrijan
      en el registro de personas.

   3. Datos ya existentes: los cajeros se toman de quienes ya abrieron o
      registraron en cada caja, y las personas de los movimientos ya hechos.
   ===================================================================== */

BEGIN;

/* ---------------------------------------------------------------------
   1. Cajeros
   --------------------------------------------------------------------- */
CREATE TABLE caja.caja_cajero (
    caja_id      bigint NOT NULL REFERENCES caja.caja(id),
    user_id      bigint NOT NULL REFERENCES public.users(id),
    asignado_por bigint REFERENCES public.users(id),
    asignado_en  timestamp(0) NOT NULL DEFAULT now(),
    PRIMARY KEY (caja_id, user_id)
);
CREATE INDEX ix_caja_cajero_usuario ON caja.caja_cajero (user_id);
COMMENT ON TABLE caja.caja_cajero IS 'Usuarios que pueden operar cada caja (abrir, registrar, anular, cerrar).';

CREATE FUNCTION caja.es_cajero(p_caja_id bigint, p_user_id bigint) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (SELECT 1 FROM caja.caja_cajero WHERE caja_id = p_caja_id AND user_id = p_user_id)
$$;

CREATE FUNCTION caja.exigir_cajero(p_caja_id bigint, p_user_id bigint, p_accion text) RETURNS void
LANGUAGE plpgsql STABLE AS $$
DECLARE
    v_caja    varchar;
    v_usuario varchar;
BEGIN
    IF p_user_id IS NULL OR caja.es_cajero(p_caja_id, p_user_id) THEN
        RETURN;
    END IF;
    SELECT codigo INTO v_caja FROM caja.caja WHERE id = p_caja_id;
    SELECT name INTO v_usuario FROM public.users WHERE id = p_user_id;
    RAISE EXCEPTION '% no está asignado como cajero de la caja %: no puede %. Pida que lo asignen en Caja → Cajas.',
        COALESCE(v_usuario, 'El usuario ' || p_user_id), v_caja, p_accion;
END $$;

CREATE FUNCTION caja.tg_sesion_cajero() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM caja.exigir_cajero(NEW.caja_id, NEW.abierta_por, 'abrirla');
    ELSIF OLD.estado = 'ABIERTA' AND NEW.estado = 'CERRADA' THEN
        PERFORM caja.exigir_cajero(NEW.caja_id, NEW.cerrada_por, 'cerrarla');
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER sesion_cajero
    BEFORE INSERT OR UPDATE OF estado ON caja.sesion
    FOR EACH ROW EXECUTE FUNCTION caja.tg_sesion_cajero();

CREATE FUNCTION caja.tg_movimiento_cajero() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_caja bigint := (SELECT caja_id FROM caja.sesion WHERE id = NEW.sesion_id);
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM caja.exigir_cajero(v_caja, NEW.registrado_por, 'registrar movimientos');
    ELSIF OLD.estado = 'VIGENTE' AND NEW.estado = 'ANULADO' THEN
        PERFORM caja.exigir_cajero(v_caja, NEW.anulado_por, 'anular comprobantes');
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER movimiento_cajero
    BEFORE INSERT OR UPDATE OF estado ON caja.movimiento
    FOR EACH ROW EXECUTE FUNCTION caja.tg_movimiento_cajero();

/* ---------------------------------------------------------------------
   2. Personas
   --------------------------------------------------------------------- */
CREATE TABLE caja.persona (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        varchar(150) NOT NULL CHECK (btrim(nombre) <> ''),
    ci            varchar(15) UNIQUE,
    telefono      varchar(30),
    observaciones varchar(250),
    activo        boolean NOT NULL DEFAULT true,
    created_at    timestamp(0),
    updated_at    timestamp(0)
);
CREATE INDEX ix_persona_nombre ON caja.persona (upper(nombre));
COMMENT ON TABLE caja.persona IS 'Personas o empresas a quienes la caja paga o de quienes recibe dinero.';
COMMENT ON COLUMN caja.persona.ci IS 'CI o NIT. Sin documento, la persona se identifica por su nombre.';

-- Mismo criterio que el formulario: mayúsculas y un solo espacio.
CREATE FUNCTION caja.normalizar_nombre(p_texto text) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
    SELECT NULLIF(upper(regexp_replace(btrim(COALESCE(p_texto, '')), '\s+', ' ', 'g')), '')
$$;

-- Busca la persona por CI (o por nombre si no hay CI) y la crea si no existe.
CREATE FUNCTION caja.registrar_persona(p_nombre text, p_ci text) RETURNS bigint
LANGUAGE plpgsql AS $$
DECLARE
    v_nombre text := caja.normalizar_nombre(p_nombre);
    v_ci     text := caja.normalizar_nombre(p_ci);
    v_id     bigint;
BEGIN
    IF v_ci IS NOT NULL THEN
        SELECT id INTO v_id FROM caja.persona WHERE ci = v_ci;
        IF FOUND THEN
            RETURN v_id;
        END IF;
    ELSE
        SELECT id INTO v_id FROM caja.persona
         WHERE ci IS NULL AND caja.normalizar_nombre(nombre) = v_nombre
         ORDER BY id LIMIT 1;
        IF FOUND THEN
            RETURN v_id;
        END IF;
    END IF;

    IF v_nombre IS NULL THEN
        RAISE EXCEPTION 'Indique a quién se paga o quién entrega el dinero.';
    END IF;

    INSERT INTO caja.persona (nombre, ci, created_at, updated_at)
    VALUES (v_nombre, v_ci, now(), now())
    ON CONFLICT (ci) DO UPDATE SET ci = EXCLUDED.ci     -- otra transacción la creó al mismo tiempo
    RETURNING id INTO v_id;
    RETURN v_id;
END $$;

ALTER TABLE caja.movimiento ADD COLUMN persona_id bigint REFERENCES caja.persona(id);
CREATE INDEX ix_mov_persona ON caja.movimiento (persona_id);
COMMENT ON COLUMN caja.movimiento.persona_id IS 'Persona del registro. persona_nombre y persona_ci guardan cómo se llamaba ese día (sale en el comprobante).';

CREATE FUNCTION caja.tg_movimiento_persona() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    p caja.persona;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.persona_id IS DISTINCT FROM OLD.persona_id THEN
            RAISE EXCEPTION 'La persona de un movimiento no se cambia: anule el comprobante % y registre otro.', OLD.numero;
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.persona_id IS NULL THEN
        NEW.persona_id := caja.registrar_persona(NEW.persona_nombre, NEW.persona_ci);
    END IF;

    SELECT * INTO p FROM caja.persona WHERE id = NEW.persona_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La persona elegida no existe.';
    END IF;
    IF NOT p.activo THEN
        RAISE EXCEPTION '% está desactivada en el registro de personas.', p.nombre;
    END IF;

    NEW.persona_nombre := p.nombre;
    NEW.persona_ci     := p.ci;
    RETURN NEW;
END $$;

CREATE TRIGGER movimiento_persona
    BEFORE INSERT OR UPDATE OF persona_id ON caja.movimiento
    FOR EACH ROW EXECUTE FUNCTION caja.tg_movimiento_persona();

-- Movimientos y saldos por persona (para la ficha y los reportes).
CREATE VIEW caja.v_persona_resumen AS
SELECT p.id AS persona_id, p.nombre, p.ci, m.moneda,
       count(*)                                                   AS movimientos,
       COALESCE(sum(m.monto) FILTER (WHERE m.tipo = 'INGRESO'), 0) AS total_ingresos,
       COALESCE(sum(m.monto) FILTER (WHERE m.tipo = 'EGRESO'), 0)  AS total_egresos,
       max(m.fecha)                                               AS ultimo_movimiento
  FROM caja.persona p
  JOIN caja.movimiento m ON m.persona_id = p.id AND m.estado = 'VIGENTE'
 GROUP BY p.id, p.nombre, p.ci, m.moneda;

/* ---------------------------------------------------------------------
   3. Datos existentes
   --------------------------------------------------------------------- */
INSERT INTO caja.caja_cajero (caja_id, user_id)
SELECT caja_id, abierta_por FROM caja.sesion
UNION
SELECT s.caja_id, m.registrado_por FROM caja.movimiento m JOIN caja.sesion s ON s.id = m.sesion_id
ON CONFLICT DO NOTHING;

-- Los movimientos no se modifican (las reglas lo impiden), salvo esta vez
-- para vincular la persona: se suspenden sus disparadores durante el ajuste.
ALTER TABLE caja.movimiento DISABLE TRIGGER USER;
UPDATE caja.movimiento SET persona_id = caja.registrar_persona(persona_nombre, persona_ci) WHERE persona_id IS NULL;
ALTER TABLE caja.movimiento ENABLE TRIGGER USER;

COMMIT;
