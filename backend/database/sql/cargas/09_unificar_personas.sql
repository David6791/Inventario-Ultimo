/* =====================================================================
   09 — UNIFICAR PERSONAS DUPLICADAS (sprint 2) — esquema caja
   ---------------------------------------------------------------------
   Una misma persona puede quedar registrada dos veces, por ejemplo con el
   CI mal digitado en un movimiento (6698508 en vez de 6698509). Unificar
   pasa todos los movimientos del registro duplicado al correcto y elimina
   el duplicado. Queda constancia en caja.persona_unificacion.

   Los comprobantes NO cambian: cada movimiento conserva el nombre y el CI
   con que se imprimió (persona_nombre, persona_ci); solo cambia a qué
   persona del registro pertenece.
   ===================================================================== */

BEGIN;

CREATE TABLE caja.persona_unificacion (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origen_id      bigint NOT NULL,                       -- ya no existe: se guarda cómo era
    origen_nombre  varchar(150) NOT NULL,
    origen_ci      varchar(15),
    destino_id     bigint NOT NULL REFERENCES caja.persona(id),
    movimientos    integer NOT NULL,
    unificado_por  bigint NOT NULL REFERENCES public.users(id),
    unificado_en   timestamp(0) NOT NULL DEFAULT now(),
    motivo         varchar(250)
);
COMMENT ON TABLE caja.persona_unificacion IS 'Constancia de cada unificación de personas duplicadas.';

CREATE FUNCTION caja.unificar_personas(p_origen bigint, p_destino bigint, p_usuario bigint, p_motivo text DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    o caja.persona;
    d caja.persona;
    n integer;
BEGIN
    IF p_usuario IS NULL THEN
        RAISE EXCEPTION 'Falta identificar al usuario que unifica.';
    END IF;
    IF p_origen = p_destino THEN
        RAISE EXCEPTION 'Elija dos personas distintas para unificar.';
    END IF;

    -- En orden de id para que dos unificaciones cruzadas no se bloqueen entre sí.
    PERFORM 1 FROM caja.persona WHERE id IN (p_origen, p_destino) ORDER BY id FOR UPDATE;
    SELECT * INTO o FROM caja.persona WHERE id = p_origen;
    IF NOT FOUND THEN RAISE EXCEPTION 'La persona a unificar ya no existe.'; END IF;
    SELECT * INTO d FROM caja.persona WHERE id = p_destino;
    IF NOT FOUND THEN RAISE EXCEPTION 'La persona que se conserva ya no existe.'; END IF;

    -- Los movimientos no se modifican nunca, salvo esto: cambiar a qué persona
    -- pertenecen. Las reglas de caja que lo impedirían (un movimiento anulado
    -- o de una sesión cerrada también se reasigna) no corren mientras está
    -- puesta esta marca, que vale solo dentro de esta función.
    PERFORM set_config('caja.unificando', 'si', true);
    UPDATE caja.movimiento SET persona_id = p_destino WHERE persona_id = p_origen;
    GET DIAGNOSTICS n = ROW_COUNT;
    PERFORM set_config('caja.unificando', '', true);

    INSERT INTO caja.persona_unificacion (origen_id, origen_nombre, origen_ci, destino_id, movimientos, unificado_por, motivo)
    VALUES (o.id, o.nombre, o.ci, d.id, n, p_usuario, NULLIF(btrim(p_motivo), ''));

    DELETE FROM caja.persona WHERE id = p_origen;

    -- Si el que se conserva no tenía CI y el duplicado sí, se lo queda.
    IF d.ci IS NULL AND o.ci IS NOT NULL THEN
        UPDATE caja.persona SET ci = o.ci, updated_at = now() WHERE id = p_destino;
    END IF;

    RETURN n;
END $$;

-- Las tres reglas de los movimientos se saltan solo durante la unificación.
-- (Con WHEN y no con ALTER TABLE ... DISABLE TRIGGER: eso bloquea la tabla
-- entera y falla si la transacción ya tiene reglas diferidas pendientes.)
DROP TRIGGER movimiento_control ON caja.movimiento;
CREATE TRIGGER movimiento_control
    BEFORE INSERT OR UPDATE OR DELETE ON caja.movimiento
    FOR EACH ROW WHEN (current_setting('caja.unificando', true) IS DISTINCT FROM 'si')
    EXECUTE FUNCTION caja.tg_movimiento_control();

DROP TRIGGER movimiento_persona ON caja.movimiento;
CREATE TRIGGER movimiento_persona
    BEFORE INSERT OR UPDATE OF persona_id ON caja.movimiento
    FOR EACH ROW WHEN (current_setting('caja.unificando', true) IS DISTINCT FROM 'si')
    EXECUTE FUNCTION caja.tg_movimiento_persona();

DROP TRIGGER movimiento_cajero ON caja.movimiento;
CREATE TRIGGER movimiento_cajero
    BEFORE INSERT OR UPDATE OF estado ON caja.movimiento
    FOR EACH ROW WHEN (current_setting('caja.unificando', true) IS DISTINCT FROM 'si')
    EXECUTE FUNCTION caja.tg_movimiento_cajero();

-- Posibles duplicados: el mismo nombre registrado más de una vez.
CREATE VIEW caja.v_persona_homonimos AS
SELECT p.id, count(*) OVER (PARTITION BY caja.normalizar_nombre(p.nombre)) - 1 AS homonimos
  FROM caja.persona p;

COMMIT;
