/* =====================================================================
   14. LABORATORIO: MUESTRA, ANÁLISIS Y LEY FINAL (sprint 5)
   ---------------------------------------------------------------------
   Se transa siempre con dos análisis de la misma muestra: el de la
   empresa y el del productor. Si para un elemento la diferencia supera el
   split limit de la línea, ese elemento va a dirimencia (análisis de un
   tercer laboratorio, la «tercera» del sistema anterior).

   Reglas nuevas:
   a) La primera muestra del lote es PRINCIPAL; las siguientes son
      REMUESTREO. Una muestra no se borra ni cambia de lote. Un remuestreo
      deja sin efecto las leyes fijadas con la muestra anterior.
   b) Los análisis van a la última muestra y solo con el lote MUESTREADO.
      No se corrigen: se anulan con motivo y se registra otro. El dirimente
      exige los dos análisis previos y un laboratorio distinto a ambos.
   c) Cada resultado es de un elemento de la línea (o la humedad), y un
      valor en % no pasa de 100.
   d) La ley final la calcula la base según el criterio: PROMEDIO de
      empresa y productor, EMPRESA, DIRIMENTE (el valor del dirimente) o
      ACUERDO (valor digitado, con observación). Con la diferencia fuera
      del split limit solo valen DIRIMENTE o ACUERDO.
   e) Toda ley cambiada o quitada queda en el historial.
   f) El cambio de estado del lote lleva el detalle que indique el
      servicio (set_config('cargas.detalle_evento', …)) en la bitácora.
   g) Lectura estimada en recepción: referencial, nunca se usa para pagar.
   ===================================================================== */

-- --------------------------------------------------------------- a) muestra
CREATE FUNCTION cargas.tg_muestra_tipo() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.tipo := CASE WHEN EXISTS (SELECT 1 FROM cargas.muestra WHERE lote_id = NEW.lote_id)
                     THEN 'REMUESTREO' ELSE 'PRINCIPAL' END;
    RETURN NEW;
END $$;

CREATE TRIGGER muestra_tipo
    BEFORE INSERT ON cargas.muestra
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_muestra_tipo();

CREATE FUNCTION cargas.tg_muestra_fija() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Las muestras no se eliminan (muestra %).', OLD.codigo;
    END IF;
    IF (NEW.lote_id, NEW.codigo, NEW.tipo, NEW.registrado_por) IS DISTINCT FROM
       (OLD.lote_id, OLD.codigo, OLD.tipo, OLD.registrado_por) THEN
        RAISE EXCEPTION 'El lote, el código y el tipo de la muestra % no se modifican.', OLD.codigo;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER muestra_fija
    BEFORE UPDATE OR DELETE ON cargas.muestra
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_muestra_fija();

-- Historial de leyes finales (lo que se cambió o quitó, y quién).
CREATE TABLE cargas.lote_ley_historial (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id               bigint NOT NULL REFERENCES cargas.lote(id),
    elemento_id           bigint NOT NULL REFERENCES cargas.elemento(id),
    valor                 numeric(12,4) NOT NULL,
    criterio              varchar(12) NOT NULL,
    analisis_dirimente_id bigint REFERENCES cargas.analisis(id),
    determinado_por       bigint NOT NULL REFERENCES public.users(id),
    determinado_en        timestamp(0) NOT NULL,
    observacion           varchar(250),
    accion                varchar(10) NOT NULL CHECK (accion IN ('CAMBIADA','QUITADA')),
    cambiado_por          bigint REFERENCES public.users(id),
    cambiado_en           timestamp(0) NOT NULL DEFAULT now()
);
CREATE INDEX ix_ley_historial_lote ON cargas.lote_ley_historial (lote_id);

CREATE FUNCTION cargas.tg_lote_ley_historial() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO cargas.lote_ley_historial (lote_id, elemento_id, valor, criterio, analisis_dirimente_id,
                                           determinado_por, determinado_en, observacion, accion, cambiado_por)
    VALUES (OLD.lote_id, OLD.elemento_id, OLD.valor, OLD.criterio, OLD.analisis_dirimente_id,
            OLD.determinado_por, OLD.determinado_en, OLD.observacion,
            CASE WHEN TG_OP = 'DELETE' THEN 'QUITADA' ELSE 'CAMBIADA' END,
            NULLIF(current_setting('cargas.usuario_id', true), '')::bigint);
    RETURN NULL;
END $$;

CREATE TRIGGER lote_ley_historial
    AFTER UPDATE OR DELETE ON cargas.lote_ley
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_lote_ley_historial();

-- Un remuestreo deja sin efecto las leyes de la muestra anterior.
CREATE FUNCTION cargas.tg_muestra_remuestreo() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.tipo = 'REMUESTREO' THEN
        DELETE FROM cargas.lote_ley WHERE lote_id = NEW.lote_id;
    END IF;
    RETURN NULL;
END $$;

CREATE TRIGGER muestra_remuestreo
    AFTER INSERT ON cargas.muestra
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_muestra_remuestreo();

-- ------------------------------------------------------------- b) análisis
CREATE FUNCTION cargas.tg_analisis_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_lote cargas.lote; v_ultima bigint; v_lab_emp bigint; v_lab_pro bigint;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los análisis no se eliminan: se anulan con motivo.';
    END IF;

    SELECT l.* INTO v_lote FROM cargas.lote l JOIN cargas.muestra m ON m.lote_id = l.id WHERE m.id = NEW.muestra_id;

    IF TG_OP = 'INSERT' THEN
        IF NEW.anulado THEN
            RAISE EXCEPTION 'Un análisis no se registra ya anulado.';
        END IF;
        IF v_lote.estado <> 'MUESTREADO' THEN
            RAISE EXCEPTION 'El lote % está %: los análisis se cargan con el lote MUESTREADO.', v_lote.codigo, v_lote.estado;
        END IF;
        SELECT max(id) INTO v_ultima FROM cargas.muestra WHERE lote_id = v_lote.id;
        IF NEW.muestra_id <> v_ultima THEN
            RAISE EXCEPTION 'La muestra no es la última del lote %: los análisis van a la muestra vigente.', v_lote.codigo;
        END IF;
        IF NEW.tipo = 'DIRIMENTE' THEN
            SELECT max(laboratorio_id) FILTER (WHERE tipo = 'EMPRESA'),
                   max(laboratorio_id) FILTER (WHERE tipo = 'PRODUCTOR')
              INTO v_lab_emp, v_lab_pro
              FROM cargas.analisis WHERE muestra_id = NEW.muestra_id AND NOT anulado;
            IF v_lab_emp IS NULL OR v_lab_pro IS NULL THEN
                RAISE EXCEPTION 'La dirimencia se pide con los análisis de la empresa y del productor ya cargados.';
            END IF;
            IF NEW.laboratorio_id IN (v_lab_emp, v_lab_pro) THEN
                RAISE EXCEPTION 'El laboratorio dirimente debe ser distinto al de la empresa y al del productor.';
            END IF;
        END IF;
        RETURN NEW;
    END IF;

    -- UPDATE: solo se adjunta el certificado o se anula.
    IF (NEW.muestra_id, NEW.laboratorio_id, NEW.tipo, NEW.numero_certificado, NEW.fecha_emision, NEW.registrado_por)
       IS DISTINCT FROM
       (OLD.muestra_id, OLD.laboratorio_id, OLD.tipo, OLD.numero_certificado, OLD.fecha_emision, OLD.registrado_por) THEN
        RAISE EXCEPTION 'Un análisis registrado no se corrige: se anula con motivo y se registra otro.';
    END IF;
    IF OLD.anulado AND (NOT NEW.anulado OR NEW.archivo_path IS DISTINCT FROM OLD.archivo_path) THEN
        RAISE EXCEPTION 'El análisis está anulado y no admite cambios.';
    END IF;
    IF NEW.anulado AND NOT OLD.anulado THEN
        IF v_lote.estado <> 'MUESTREADO' THEN
            RAISE EXCEPTION 'El lote % está %: para anular un análisis, primero reabra el lote.', v_lote.codigo, v_lote.estado;
        END IF;
        IF length(btrim(COALESCE(NEW.motivo_anulacion, ''))) < 10 THEN
            RAISE EXCEPTION 'Indique el motivo de la anulación del análisis (al menos 10 caracteres).';
        END IF;
        -- Las leyes que dependían de este análisis dejan de valer.
        IF OLD.tipo = 'DIRIMENTE' THEN
            DELETE FROM cargas.lote_ley WHERE analisis_dirimente_id = OLD.id;
        ELSE
            DELETE FROM cargas.lote_ley ll
             WHERE ll.lote_id = v_lote.id
               AND ll.criterio <> 'ACUERDO'
               AND ll.elemento_id IN (SELECT elemento_id FROM cargas.analisis_resultado WHERE analisis_id = OLD.id);
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER analisis_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.analisis
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_analisis_control();

-- ----------------------------------------------------------- c) resultados
CREATE FUNCTION cargas.tg_analisis_resultado_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_anulado boolean; v_lote cargas.lote; v_elem cargas.elemento;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'Los resultados de un análisis no se corrigen: anule el análisis y registre otro.';
    END IF;
    SELECT a.anulado INTO v_anulado FROM cargas.analisis a WHERE a.id = NEW.analisis_id;
    SELECT l.* INTO v_lote
      FROM cargas.analisis a JOIN cargas.muestra m ON m.id = a.muestra_id JOIN cargas.lote l ON l.id = m.lote_id
     WHERE a.id = NEW.analisis_id;
    IF v_anulado THEN
        RAISE EXCEPTION 'El análisis está anulado: no admite resultados.';
    END IF;
    IF v_lote.estado <> 'MUESTREADO' THEN
        RAISE EXCEPTION 'El lote % está %: los resultados se cargan con el lote MUESTREADO.', v_lote.codigo, v_lote.estado;
    END IF;
    SELECT * INTO v_elem FROM cargas.elemento WHERE id = NEW.elemento_id;
    IF v_elem.codigo <> 'H2O' AND NOT EXISTS (
           SELECT 1 FROM cargas.linea_producto_elemento
            WHERE linea_producto_id = v_lote.linea_producto_id AND elemento_id = NEW.elemento_id) THEN
        RAISE EXCEPTION 'El elemento % no es de la línea del lote %.', v_elem.codigo, v_lote.codigo;
    END IF;
    IF v_elem.unidad_ley = '%' AND NEW.valor > 100 THEN
        RAISE EXCEPTION 'Un valor de % %% para % no es posible.', NEW.valor, v_elem.codigo;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER analisis_resultado_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.analisis_resultado
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_analisis_resultado_control();

-- ---------------------------------------------------------- d) ley final
/* Los ensayes vigentes de la última muestra por elemento, con el split
   limit de la línea y si lo excede. Reemplaza a v_lote_comparacion_leyes
   en la pantalla (aquella queda por compatibilidad). */
CREATE VIEW cargas.v_lote_ensayes AS
WITH ultima AS (
    SELECT DISTINCT ON (lote_id) id AS muestra_id, lote_id, codigo AS muestra
      FROM cargas.muestra ORDER BY lote_id, id DESC
), r AS (
    SELECT u.lote_id, u.muestra_id, u.muestra, a.id AS analisis_id, a.tipo, ar.elemento_id, ar.valor
      FROM ultima u
      JOIN cargas.analisis a            ON a.muestra_id = u.muestra_id AND NOT a.anulado
      JOIN cargas.analisis_resultado ar ON ar.analisis_id = a.id
     WHERE a.tipo IN ('EMPRESA','PRODUCTOR','DIRIMENTE')
)
SELECT r.lote_id, r.muestra_id, r.muestra, r.elemento_id, e.codigo AS elemento, e.unidad_ley,
       max(r.valor) FILTER (WHERE r.tipo = 'EMPRESA')          AS ley_empresa,
       max(r.valor) FILTER (WHERE r.tipo = 'PRODUCTOR')        AS ley_productor,
       max(r.valor) FILTER (WHERE r.tipo = 'DIRIMENTE')        AS ley_dirimente,
       max(r.analisis_id) FILTER (WHERE r.tipo = 'DIRIMENTE')  AS analisis_dirimente_id,
       abs(max(r.valor) FILTER (WHERE r.tipo = 'EMPRESA') - max(r.valor) FILTER (WHERE r.tipo = 'PRODUCTOR')) AS diferencia,
       lpe.split_limit,
       COALESCE(abs(max(r.valor) FILTER (WHERE r.tipo = 'EMPRESA') - max(r.valor) FILTER (WHERE r.tipo = 'PRODUCTOR'))
                > lpe.split_limit, false)                     AS excede_split_limit,
       round((max(r.valor) FILTER (WHERE r.tipo = 'EMPRESA') + max(r.valor) FILTER (WHERE r.tipo = 'PRODUCTOR')) / 2, 4) AS promedio
  FROM r
  JOIN cargas.lote l     ON l.id = r.lote_id
  JOIN cargas.elemento e ON e.id = r.elemento_id
  LEFT JOIN cargas.linea_producto_elemento lpe
         ON lpe.linea_producto_id = l.linea_producto_id AND lpe.elemento_id = r.elemento_id
 GROUP BY r.lote_id, r.muestra_id, r.muestra, r.elemento_id, e.codigo, e.unidad_ley, lpe.split_limit;

CREATE OR REPLACE FUNCTION cargas.tg_lote_ley_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_lote bigint; v_estado varchar; v_codigo varchar; v_elem varchar; c record;
BEGIN
    v_lote := CASE WHEN TG_OP = 'DELETE' THEN OLD.lote_id ELSE NEW.lote_id END;
    SELECT estado, codigo INTO v_estado, v_codigo FROM cargas.lote WHERE id = v_lote;
    IF v_estado <> 'MUESTREADO' THEN
        RAISE EXCEPTION 'La ley final del lote % solo se fija mientras está MUESTREADO (está %).', v_codigo, v_estado;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    SELECT codigo INTO v_elem FROM cargas.elemento WHERE id = NEW.elemento_id;
    SELECT * INTO c FROM cargas.v_lote_ensayes WHERE lote_id = NEW.lote_id AND elemento_id = NEW.elemento_id;

    IF c.ley_empresa IS NULL THEN
        RAISE EXCEPTION 'Falta el análisis de la empresa para % en la muestra vigente del lote %.', v_elem, v_codigo;
    END IF;
    IF c.ley_productor IS NULL AND v_elem <> 'H2O' THEN
        RAISE EXCEPTION 'Falta el análisis del productor para % en la muestra vigente del lote %: se transa con los dos.', v_elem, v_codigo;
    END IF;

    CASE NEW.criterio
        WHEN 'PROMEDIO' THEN
            IF c.ley_productor IS NULL THEN
                RAISE EXCEPTION 'Sin el análisis del productor para % no hay promedio: use el de la empresa.', v_elem;
            END IF;
            IF c.excede_split_limit THEN
                RAISE EXCEPTION '% excede el split limit (diferencia % > %): se resuelve por dirimencia o acuerdo, no por promedio.',
                                v_elem, c.diferencia, c.split_limit;
            END IF;
            NEW.valor := c.promedio;
            NEW.analisis_dirimente_id := NULL;
        WHEN 'EMPRESA' THEN
            IF c.excede_split_limit THEN
                RAISE EXCEPTION '% excede el split limit (diferencia % > %): se resuelve por dirimencia o acuerdo.',
                                v_elem, c.diferencia, c.split_limit;
            END IF;
            NEW.valor := c.ley_empresa;
            NEW.analisis_dirimente_id := NULL;
        WHEN 'DIRIMENTE' THEN
            IF c.ley_dirimente IS NULL THEN
                RAISE EXCEPTION 'No hay análisis dirimente con resultado de % en la muestra vigente.', v_elem;
            END IF;
            NEW.valor := c.ley_dirimente;
            NEW.analisis_dirimente_id := c.analisis_dirimente_id;
        WHEN 'ACUERDO' THEN
            IF NEW.valor IS NULL THEN
                RAISE EXCEPTION 'Indique el valor acordado para %.', v_elem;
            END IF;
            IF length(btrim(COALESCE(NEW.observacion, ''))) < 10 THEN
                RAISE EXCEPTION 'Un acuerdo para % se explica en la observación (al menos 10 caracteres).', v_elem;
            END IF;
            NEW.analisis_dirimente_id := NULL;
    END CASE;

    IF v_elem = 'H2O' AND NEW.valor >= 100 THEN
        RAISE EXCEPTION 'Una humedad de % %% no es posible.', NEW.valor;
    END IF;
    IF TG_OP = 'UPDATE' THEN
        NEW.determinado_en := now();
    END IF;
    RETURN NEW;
END $$;

-- ---------------------------------------------------- f) detalle bitácora
CREATE OR REPLACE FUNCTION cargas.tg_lote_bitacora() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO cargas.lote_evento (lote_id, estado_anterior, estado_nuevo, usuario_id, detalle)
        VALUES (NEW.id, NULL, NEW.estado, NEW.registrado_por, 'Recepción');
    ELSIF NEW.estado IS DISTINCT FROM OLD.estado THEN
        INSERT INTO cargas.lote_evento (lote_id, estado_anterior, estado_nuevo, usuario_id, detalle)
        VALUES (NEW.id, OLD.estado, NEW.estado, cargas.usuario_actual(),
                CASE WHEN NEW.estado = 'ANULADO' THEN NEW.motivo_anulacion
                     ELSE left(NULLIF(current_setting('cargas.detalle_evento', true), ''), 250) END);
    END IF;
    RETURN NEW;
END $$;

-- ------------------------------------------------ g) lectura estimada
CREATE TABLE cargas.lote_lectura_estimada (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id        bigint NOT NULL REFERENCES cargas.lote(id),
    elemento_id    bigint NOT NULL REFERENCES cargas.elemento(id),
    valor          numeric(12,4) NOT NULL CHECK (valor >= 0),
    metodo         varchar(30),
    registrado_por bigint NOT NULL REFERENCES public.users(id),
    registrado_en  timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT uq_lectura_estimada UNIQUE (lote_id, elemento_id)
);
COMMENT ON TABLE cargas.lote_lectura_estimada IS
    'Lectura estimada al recibir (visual o analizador portátil). Referencial: nunca se usa para pagar.';

CREATE FUNCTION cargas.tg_lectura_estimada_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_lote cargas.lote; v_elem cargas.elemento;
BEGIN
    SELECT * INTO v_lote FROM cargas.lote WHERE id = COALESCE(NEW.lote_id, OLD.lote_id);
    IF v_lote.estado NOT IN ('RECIBIDO','MUESTREADO') THEN
        RAISE EXCEPTION 'El lote % está %: la lectura estimada ya no se modifica.', v_lote.codigo, v_lote.estado;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    SELECT * INTO v_elem FROM cargas.elemento WHERE id = NEW.elemento_id;
    IF v_elem.codigo <> 'H2O' AND NOT EXISTS (
           SELECT 1 FROM cargas.linea_producto_elemento
            WHERE linea_producto_id = v_lote.linea_producto_id AND elemento_id = NEW.elemento_id) THEN
        RAISE EXCEPTION 'El elemento % no es de la línea del lote %.', v_elem.codigo, v_lote.codigo;
    END IF;
    IF v_elem.unidad_ley = '%' AND NEW.valor > 100 THEN
        RAISE EXCEPTION 'Un valor de % %% para % no es posible.', NEW.valor, v_elem.codigo;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER lectura_estimada_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.lote_lectura_estimada
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_lectura_estimada_control();

-- ------------------------------------------------------ bandeja de trabajo
/* Situación de laboratorio de cada lote por muestrear o en análisis. */
CREATE VIEW cargas.v_lote_laboratorio AS
WITH requeridos AS (
    SELECT l.id AS lote_id, e.id AS elemento_id
      FROM cargas.lote l
      JOIN cargas.elemento e ON e.codigo = 'H2O'
         OR e.id IN (SELECT elemento_id FROM cargas.linea_producto_elemento
                      WHERE linea_producto_id = l.linea_producto_id AND rol = 'PAGABLE')
     WHERE l.estado IN ('RECIBIDO','MUESTREADO')
), ultima AS (
    SELECT DISTINCT ON (lote_id) id, lote_id, codigo FROM cargas.muestra ORDER BY lote_id, id DESC
), an AS (
    SELECT u.lote_id,
           bool_or(a.tipo = 'EMPRESA')   AS con_empresa,
           bool_or(a.tipo = 'PRODUCTOR') AS con_productor,
           bool_or(a.tipo = 'DIRIMENTE') AS con_dirimente
      FROM ultima u JOIN cargas.analisis a ON a.muestra_id = u.id AND NOT a.anulado
     GROUP BY u.lote_id
)
SELECT l.id AS lote_id, l.codigo, l.estado, l.almacen_id, l.fecha_recepcion,
       u.codigo AS muestra,
       COALESCE(an.con_empresa, false)   AS con_empresa,
       COALESCE(an.con_productor, false) AS con_productor,
       COALESCE(an.con_dirimente, false) AS con_dirimente,
       EXISTS (SELECT 1 FROM cargas.v_lote_ensayes x WHERE x.lote_id = l.id AND x.excede_split_limit
                AND x.ley_dirimente IS NULL) AS requiere_dirimencia,
       (SELECT count(*) FROM requeridos r WHERE r.lote_id = l.id) AS leyes_requeridas,
       (SELECT count(*) FROM requeridos r JOIN cargas.lote_ley ll
            ON ll.lote_id = r.lote_id AND ll.elemento_id = r.elemento_id WHERE r.lote_id = l.id) AS leyes_fijadas
  FROM cargas.lote l
  LEFT JOIN ultima u ON u.lote_id = l.id
  LEFT JOIN an ON an.lote_id = l.id
 WHERE l.estado IN ('RECIBIDO','MUESTREADO');

-- ------------------------------------------- criterio sugerido (parámetro)
INSERT INTO cargas.parametro (clave, valor, tipo_dato, descripcion, vigente_desde)
SELECT 'CRITERIO_LEY_DENTRO_LIMITE', 'PROMEDIO', 'texto',
       'Criterio que se sugiere para la ley final cuando empresa y productor caben en el split limit (PROMEDIO o EMPRESA).',
       DATE '2026-01-01'
 WHERE NOT EXISTS (SELECT 1 FROM cargas.parametro WHERE clave = 'CRITERIO_LEY_DENTRO_LIMITE');
