/* =====================================================================
   15. PESO DEL CLIENTE: BRUTO O NETO, Y CORRECCIÓN CON MOTIVO
   ---------------------------------------------------------------------
   Caso real: el cliente declaró 24.500 kg (su peso BRUTO) y se anotó como
   neto; la comparación dio +100 %. Y el pesaje no se podía corregir:
   anularlo estaba bloqueado porque el bono ya se había pagado.

   a) pesaje.peso_cliente_tipo dice qué declaró el cliente: NETO (como
      hasta ahora) o BRUTO. Si es bruto, su neto se calcula con la tara de
      la báscula de la empresa, y así se compara siempre neto con neto.
   b) El peso del cliente es informativo (no mueve el lote, el bono ni la
      liquidación): se corrige con cargas.corregir_peso_cliente(), con
      motivo y quién, aunque el bono esté pagado. Cualquier otro cambio
      sigue rechazado. Cada corrección queda en pesaje_cliente_correccion.
   ===================================================================== */

ALTER TABLE cargas.pesaje
    ADD COLUMN peso_cliente_tipo varchar(5) NOT NULL DEFAULT 'NETO'
        CONSTRAINT ck_pesaje_cliente_tipo CHECK (peso_cliente_tipo IN ('NETO','BRUTO'));
ALTER TABLE cargas.pesaje
    ADD CONSTRAINT ck_pesaje_cliente_bruto CHECK (
        peso_cliente_kg IS NULL OR peso_cliente_tipo = 'NETO' OR peso_cliente_kg > tara_kg);
COMMENT ON COLUMN cargas.pesaje.peso_cliente_tipo IS
    'Qué declaró el cliente: NETO, o BRUTO (su neto = bruto declarado − tara de la empresa).';

CREATE TABLE cargas.pesaje_cliente_correccion (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pesaje_id          bigint NOT NULL REFERENCES cargas.pesaje(id),
    anterior_kg        numeric(12,2),
    anterior_tipo      varchar(5) NOT NULL,
    nuevo_kg           numeric(12,2),
    nuevo_tipo         varchar(5) NOT NULL,
    motivo             varchar(250) NOT NULL CHECK (length(btrim(motivo)) >= 10),
    corregido_por      bigint NOT NULL REFERENCES public.users(id),
    corregido_en       timestamp(0) NOT NULL DEFAULT now()
);
CREATE INDEX ix_pcc_pesaje ON cargas.pesaje_cliente_correccion (pesaje_id);

-- El control de pesajes deja pasar SOLO la corrección hecha por la función.
CREATE OR REPLACE FUNCTION cargas.tg_pesaje_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_estado varchar; v_codigo varchar;
    v_corrigiendo boolean := COALESCE(current_setting('cargas.corrigiendo_peso_cliente', true), '') = 'si';
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los pesajes no se eliminan: se anulan con motivo.';
    END IF;

    SELECT estado, codigo INTO v_estado, v_codigo FROM cargas.lote WHERE id = NEW.lote_id;

    IF TG_OP = 'UPDATE' THEN
        IF (NEW.lote_id, NEW.tipo, NEW.bascula, NEW.ticket, NEW.peso_bruto_kg, NEW.tara_kg)
           IS DISTINCT FROM
           (OLD.lote_id, OLD.tipo, OLD.bascula, OLD.ticket, OLD.peso_bruto_kg, OLD.tara_kg)
           OR (NOT v_corrigiendo AND (NEW.peso_cliente_kg, NEW.peso_cliente_tipo)
                                     IS DISTINCT FROM (OLD.peso_cliente_kg, OLD.peso_cliente_tipo)) THEN
            RAISE EXCEPTION 'Un pesaje registrado no se corrige: se anula y se registra otro.';
        END IF;
        IF OLD.anulado AND NOT NEW.anulado THEN
            RAISE EXCEPTION 'Un pesaje anulado no se reactiva.';
        END IF;
        IF v_corrigiendo THEN
            RETURN NEW;      -- la función ya validó estado y motivo
        END IF;
    END IF;

    IF NEW.tipo = 'INGRESO' AND v_estado <> 'RECIBIDO' THEN
        RAISE EXCEPTION 'El lote % está %: los pesajes de ingreso solo se registran o anulan mientras está RECIBIDO.', v_codigo, v_estado;
    END IF;
    IF v_estado IN ('ANULADO','LIQUIDADO') THEN
        RAISE EXCEPTION 'El lote % está % y no admite pesajes.', v_codigo, v_estado;
    END IF;
    RETURN NEW;
END $$;

CREATE FUNCTION cargas.corregir_peso_cliente(p_pesaje bigint, p_kg numeric, p_tipo varchar, p_motivo varchar, p_usuario bigint)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    p cargas.pesaje; v_estado varchar; v_codigo varchar;
BEGIN
    SELECT * INTO p FROM cargas.pesaje WHERE id = p_pesaje FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El pesaje % no existe.', p_pesaje;
    END IF;
    SELECT estado, codigo INTO v_estado, v_codigo FROM cargas.lote WHERE id = p.lote_id;
    IF p.anulado THEN
        RAISE EXCEPTION 'El pesaje % está anulado: no se corrige.', p.ticket;
    END IF;
    IF v_estado IN ('ANULADO','LIQUIDADO') THEN
        RAISE EXCEPTION 'El lote % está %: el peso del cliente ya no se corrige.', v_codigo, v_estado;
    END IF;
    IF length(btrim(COALESCE(p_motivo, ''))) < 10 THEN
        RAISE EXCEPTION 'Indique el motivo de la corrección (al menos 10 caracteres).';
    END IF;
    IF (p.peso_cliente_kg, p.peso_cliente_tipo) IS NOT DISTINCT FROM (p_kg, COALESCE(p_tipo, 'NETO')) THEN
        RAISE EXCEPTION 'El peso del cliente ya es ese: no hay nada que corregir.';
    END IF;

    INSERT INTO cargas.pesaje_cliente_correccion (pesaje_id, anterior_kg, anterior_tipo, nuevo_kg, nuevo_tipo, motivo, corregido_por)
    VALUES (p.id, p.peso_cliente_kg, p.peso_cliente_tipo, p_kg, COALESCE(p_tipo, 'NETO'), btrim(p_motivo), p_usuario);

    PERFORM set_config('cargas.corrigiendo_peso_cliente', 'si', true);
    UPDATE cargas.pesaje SET peso_cliente_kg = p_kg, peso_cliente_tipo = COALESCE(p_tipo, 'NETO'), updated_at = now()
     WHERE id = p.id;
    PERFORM set_config('cargas.corrigiendo_peso_cliente', '', true);
END $$;

-- Neto del cliente: el declarado, o bruto declarado − tara de la empresa.
DROP VIEW cargas.v_lote_peso_cliente;
CREATE VIEW cargas.v_lote_peso_cliente AS
WITH p AS (
    SELECT lote_id, peso_neto_kg,
           CASE WHEN peso_cliente_kg IS NULL THEN NULL
                WHEN peso_cliente_tipo = 'BRUTO' THEN peso_cliente_kg - tara_kg
                ELSE peso_cliente_kg END AS cliente_neto_kg
      FROM cargas.pesaje
     WHERE tipo = 'INGRESO' AND NOT anulado
)
SELECT lote_id,
       sum(peso_neto_kg)                                         AS peso_empresa_kg,
       sum(COALESCE(cliente_neto_kg, peso_neto_kg))              AS peso_cliente_kg,
       sum(COALESCE(cliente_neto_kg, peso_neto_kg) - peso_neto_kg) AS diferencia_kg,
       count(cliente_neto_kg)                                    AS pesajes_con_peso_cliente
  FROM p
 GROUP BY lote_id;
