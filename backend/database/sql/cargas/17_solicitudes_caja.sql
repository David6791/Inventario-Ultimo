/* =====================================================================
   17 — SOLICITUDES DE DINERO Y APROBACIÓN DE CAJA — esquema caja
   ---------------------------------------------------------------------
   1. PRÓXIMO COMPROBANTE. Una caja puede seguir la numeración de otro
      sistema: se indica con qué número sale el próximo comprobante del
      período actual. Solo hacia adelante (volver atrás repetiría números)
      y queda registrado quién lo cambió, de cuánto a cuánto y por qué.

   2. CAJAS CON APROBACIÓN. caja.requiere_aprobacion:
        - false: la cajera paga directo, como hasta ahora.
        - true : los egresos manuales salen solo de una solicitud aprobada.
      Los egresos de otros módulos (anticipos, bonos) traen su propia
      autorización y no pasan por aquí. Un concepto puede quedar exento
      (por ejemplo, el depósito en banco: el dinero no sale de la empresa).

   3. APROBADORES. Cada caja con aprobación tiene sus aprobadores asignados,
      como los cajeros. Es un papel distinto al del supervisor de caja, que
      valida cierres.

   4. SOLICITUDES. Las registra el propio solicitante (desde su usuario) o
      la cajera a nombre de una persona del registro.
        PENDIENTE → APROBADA → PAGADA
                  ↘ RECHAZADA      (con motivo)
        PENDIENTE o APROBADA → ANULADA (la anula quien la registró o un
                                        cajero, con motivo)
      Separación de funciones, en la base:
        - nadie aprueba su propia solicitud ni una a su propio nombre;
        - quien aprobó no la paga.
      Al pagarla, la cajera emite el comprobante (caja.movimiento con
      solicitud_id): monto, moneda, concepto y persona salen de la
      solicitud. Si ese comprobante se anula, la solicitud vuelve a
      APROBADA para pagarse de nuevo.
   ===================================================================== */

BEGIN;

/* ---------------------------------------------------------------------
   1. Próximo comprobante
   --------------------------------------------------------------------- */
CREATE TABLE caja.ajuste_numeracion (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caja_id    bigint NOT NULL REFERENCES caja.caja(id),
    periodo    varchar(10) NOT NULL,
    anterior   integer NOT NULL,
    proximo    integer NOT NULL,
    motivo     varchar(250),
    usuario_id bigint REFERENCES public.users(id),
    creado_en  timestamp(0) NOT NULL DEFAULT now()
);
CREATE INDEX ix_ajuste_numeracion_caja ON caja.ajuste_numeracion (caja_id);
COMMENT ON TABLE caja.ajuste_numeracion IS 'Cambios del próximo número de comprobante de una caja (por ejemplo, para seguir la numeración de otro sistema).';

-- Último número emitido por la caja en el período de la fecha.
CREATE FUNCTION caja.ultimo_comprobante(p_caja_id bigint, p_fecha date DEFAULT current_date) RETURNS integer
LANGUAGE sql STABLE AS $$
    SELECT COALESCE((SELECT ultimo_numero FROM comun.contador
                      WHERE clave = 'caja.comprobante:' || p_caja_id
                        AND periodo = comun.periodo_de(c.reinicio_comprobante, p_fecha)), 0)
      FROM caja.caja c WHERE c.id = p_caja_id
$$;

CREATE FUNCTION caja.fijar_proximo_comprobante(p_caja_id bigint, p_proximo integer,
                                               p_usuario bigint, p_motivo text DEFAULT NULL)
RETURNS varchar LANGUAGE plpgsql AS $$
DECLARE
    c         caja.caja;
    v_periodo varchar;
    v_ultimo  integer;
    v_codigo  varchar;
BEGIN
    SELECT * INTO c FROM caja.caja WHERE id = p_caja_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La caja no existe.';
    END IF;
    IF p_proximo IS NULL OR p_proximo < 1 THEN
        RAISE EXCEPTION 'El próximo comprobante debe ser un número mayor que cero.';
    END IF;

    v_periodo := comun.periodo_de(c.reinicio_comprobante, current_date);
    v_ultimo  := caja.ultimo_comprobante(c.id);

    IF p_proximo = v_ultimo + 1 THEN
        RETURN NULL;                                  -- sin cambio
    END IF;
    IF p_proximo <= v_ultimo THEN
        RAISE EXCEPTION 'La caja % ya emitió hasta el comprobante %: el próximo no puede ser %, se repetirían números.',
            c.codigo, comun.formatear_codigo(c.formato_comprobante, current_date, v_ultimo, jsonb_build_object('CAJA', c.codigo)), p_proximo;
    END IF;

    v_codigo := comun.formatear_codigo(c.formato_comprobante, current_date, p_proximo, jsonb_build_object('CAJA', c.codigo));
    IF EXISTS (SELECT 1 FROM caja.movimiento WHERE numero = v_codigo) THEN
        RAISE EXCEPTION 'El comprobante % ya existe: elija otro número.', v_codigo;
    END IF;

    INSERT INTO comun.contador (clave, periodo, ultimo_numero)
    VALUES ('caja.comprobante:' || c.id, v_periodo, p_proximo - 1)
    ON CONFLICT (clave, periodo) DO UPDATE SET ultimo_numero = EXCLUDED.ultimo_numero, updated_at = now();

    INSERT INTO caja.ajuste_numeracion (caja_id, periodo, anterior, proximo, motivo, usuario_id)
    VALUES (c.id, v_periodo, v_ultimo + 1, p_proximo, NULLIF(btrim(COALESCE(p_motivo, '')), ''), p_usuario);

    RETURN v_codigo;
END $$;

/* ---------------------------------------------------------------------
   2. Cajas con aprobación y conceptos exentos
   --------------------------------------------------------------------- */
ALTER TABLE caja.caja ADD COLUMN requiere_aprobacion boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN caja.caja.requiere_aprobacion IS 'true: los egresos manuales se pagan solo desde una solicitud aprobada.';

ALTER TABLE caja.concepto ADD COLUMN exento_aprobacion boolean NOT NULL DEFAULT false;
COMMENT ON COLUMN caja.concepto.exento_aprobacion IS 'Egreso que la cajera registra directo aun en cajas con aprobación (por ejemplo, depósito en banco).';
UPDATE caja.concepto SET exento_aprobacion = true WHERE codigo = 'DEPOSITO_BANCARIO';

/* ---------------------------------------------------------------------
   3. Aprobadores
   --------------------------------------------------------------------- */
CREATE TABLE caja.caja_aprobador (
    caja_id      bigint NOT NULL REFERENCES caja.caja(id),
    user_id      bigint NOT NULL REFERENCES public.users(id),
    asignado_por bigint REFERENCES public.users(id),
    asignado_en  timestamp(0) NOT NULL DEFAULT now(),
    PRIMARY KEY (caja_id, user_id)
);
CREATE INDEX ix_caja_aprobador_usuario ON caja.caja_aprobador (user_id);
COMMENT ON TABLE caja.caja_aprobador IS 'Usuarios que aprueban o rechazan las solicitudes de dinero de cada caja.';

CREATE FUNCTION caja.es_aprobador(p_caja_id bigint, p_user_id bigint) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (SELECT 1 FROM caja.caja_aprobador WHERE caja_id = p_caja_id AND user_id = p_user_id)
$$;

/* ---------------------------------------------------------------------
   4. Solicitudes
   --------------------------------------------------------------------- */
CREATE TABLE caja.solicitud (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero           varchar(30) NOT NULL UNIQUE,
    caja_id          bigint NOT NULL REFERENCES caja.caja(id),
    concepto_id      bigint NOT NULL REFERENCES caja.concepto(id),
    monto            numeric(14,2) NOT NULL CHECK (monto > 0),
    moneda           char(3) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB','USD')),
    persona_id       bigint NOT NULL REFERENCES caja.persona(id),
    persona_nombre   varchar(150) NOT NULL,
    persona_ci       varchar(15),
    glosa            varchar(250) NOT NULL CHECK (length(btrim(glosa)) >= 5),
    estado           varchar(10) NOT NULL DEFAULT 'PENDIENTE'
                     CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA','PAGADA','ANULADA')),
    registrado_por   bigint NOT NULL REFERENCES public.users(id),
    registrado_en    timestamp(0) NOT NULL DEFAULT now(),
    resuelto_por     bigint REFERENCES public.users(id),
    resuelto_en      timestamp(0),
    observacion      varchar(250),
    movimiento_id    bigint,
    anulado_por      bigint REFERENCES public.users(id),
    anulado_en       timestamp(0),
    motivo_anulacion varchar(250),
    created_at       timestamp(0),
    updated_at       timestamp(0),
    CONSTRAINT ck_sol_resuelta  CHECK (estado IN ('PENDIENTE','ANULADA') OR (resuelto_por IS NOT NULL AND resuelto_en IS NOT NULL)),
    CONSTRAINT ck_sol_rechazo   CHECK (estado <> 'RECHAZADA' OR length(btrim(COALESCE(observacion, ''))) >= 5),
    CONSTRAINT ck_sol_pagada    CHECK ((estado = 'PAGADA') = (movimiento_id IS NOT NULL)),
    CONSTRAINT ck_sol_anulada   CHECK (estado <> 'ANULADA' OR (anulado_por IS NOT NULL AND anulado_en IS NOT NULL
                                                             AND length(btrim(COALESCE(motivo_anulacion, ''))) >= 5))
);
CREATE INDEX ix_sol_caja_estado ON caja.solicitud (caja_id, estado);
CREATE INDEX ix_sol_registrado  ON caja.solicitud (registrado_por);
CREATE INDEX ix_sol_persona     ON caja.solicitud (persona_id);
COMMENT ON TABLE caja.solicitud IS 'Solicitudes de dinero de cajas con aprobación: se aprueban o rechazan y la cajera paga las aprobadas.';
COMMENT ON COLUMN caja.solicitud.persona_id IS 'Quién recibe el dinero. Nombre y CI quedan copiados como estaban ese día.';

ALTER TABLE caja.movimiento ADD COLUMN solicitud_id bigint REFERENCES caja.solicitud(id);
CREATE INDEX ix_mov_solicitud ON caja.movimiento (solicitud_id);
ALTER TABLE caja.solicitud ADD CONSTRAINT fk_sol_movimiento FOREIGN KEY (movimiento_id) REFERENCES caja.movimiento(id);

-- Control de la solicitud: alta, transiciones y separación de funciones.
CREATE FUNCTION caja.tg_solicitud_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    c         caja.caja;
    k         caja.concepto;
    p         caja.persona;
    v_usuario varchar;
    v_ci      varchar;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Las solicitudes no se eliminan: se anulan con motivo (solicitud %).', OLD.numero;
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT * INTO c FROM caja.caja WHERE id = NEW.caja_id;
        IF NOT c.activa THEN
            RAISE EXCEPTION 'La caja % está inactiva.', c.codigo;
        END IF;
        IF NOT c.requiere_aprobacion THEN
            RAISE EXCEPTION 'La caja % paga directo, sin solicitud: pida el dinero a la cajera.', c.codigo;
        END IF;
        IF NEW.moneda = 'USD' AND NOT c.maneja_usd THEN
            RAISE EXCEPTION 'La caja % no maneja dólares.', c.codigo;
        END IF;

        SELECT * INTO k FROM caja.concepto WHERE id = NEW.concepto_id;
        IF k.tipo <> 'EGRESO' OR k.origen <> 'MANUAL' OR NOT k.activo THEN
            RAISE EXCEPTION 'El concepto «%» no sirve para solicitar dinero: elija un egreso manual activo.', k.nombre;
        END IF;

        IF NEW.persona_id IS NULL THEN
            NEW.persona_id := caja.registrar_persona(NEW.persona_nombre, NEW.persona_ci);
        END IF;
        SELECT * INTO p FROM caja.persona WHERE id = NEW.persona_id;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'La persona elegida no existe.';
        END IF;
        IF NOT p.activo THEN
            RAISE EXCEPTION '% está desactivada en el registro de personas.', p.nombre;
        END IF;
        NEW.persona_nombre := p.nombre;
        NEW.persona_ci     := p.ci;

        NEW.numero := comun.generar_codigo('caja.solicitud', 'SOL-{AAAA}-{N:5}', 'ANUAL', current_date);
        NEW.estado := 'PENDIENTE';
        NEW.registrado_en := now();
        NEW.resuelto_por := NULL; NEW.resuelto_en := NULL; NEW.observacion := NULL; NEW.movimiento_id := NULL;
        NEW.anulado_por := NULL; NEW.anulado_en := NULL; NEW.motivo_anulacion := NULL;
        RETURN NEW;
    END IF;

    -- UPDATE: los datos de la solicitud no se corrigen.
    IF (NEW.numero, NEW.caja_id, NEW.concepto_id, NEW.monto, NEW.moneda, NEW.persona_id,
        NEW.persona_nombre, NEW.persona_ci, NEW.glosa, NEW.registrado_por, NEW.registrado_en)
       IS DISTINCT FROM
       (OLD.numero, OLD.caja_id, OLD.concepto_id, OLD.monto, OLD.moneda, OLD.persona_id,
        OLD.persona_nombre, OLD.persona_ci, OLD.glosa, OLD.registrado_por, OLD.registrado_en) THEN
        RAISE EXCEPTION 'Una solicitud no se corrige: anule la % y registre otra.', OLD.numero;
    END IF;

    IF NEW.estado = OLD.estado THEN
        RETURN NEW;
    END IF;

    -- Aprobar o rechazar
    IF OLD.estado = 'PENDIENTE' AND NEW.estado IN ('APROBADA', 'RECHAZADA') THEN
        SELECT name, ci INTO v_usuario, v_ci FROM public.users WHERE id = NEW.resuelto_por;
        IF NOT caja.es_aprobador(NEW.caja_id, NEW.resuelto_por) THEN
            RAISE EXCEPTION '% no es aprobador de la caja %: no puede aprobar ni rechazar sus solicitudes.',
                COALESCE(v_usuario, 'El usuario'), (SELECT codigo FROM caja.caja WHERE id = NEW.caja_id);
        END IF;
        IF NEW.resuelto_por = OLD.registrado_por THEN
            RAISE EXCEPTION 'No puede aprobar ni rechazar una solicitud que usted registró (%): debe hacerlo otro aprobador.', OLD.numero;
        END IF;
        IF v_ci IS NOT NULL AND OLD.persona_ci IS NOT NULL AND upper(btrim(v_ci)) = OLD.persona_ci THEN
            RAISE EXCEPTION 'La solicitud % es a su nombre: debe aprobarla otro aprobador.', OLD.numero;
        END IF;
        NEW.resuelto_en := COALESCE(NEW.resuelto_en, now());
        RETURN NEW;
    END IF;

    -- Pagar (lo marca el comprobante, no el usuario)
    IF OLD.estado = 'APROBADA' AND NEW.estado = 'PAGADA' THEN
        IF current_setting('caja.pagando_solicitud', true) IS DISTINCT FROM OLD.id::text THEN
            RAISE EXCEPTION 'La solicitud % se paga emitiendo su comprobante en caja.', OLD.numero;
        END IF;
        RETURN NEW;
    END IF;

    -- Comprobante anulado: vuelve a aprobada
    IF OLD.estado = 'PAGADA' AND NEW.estado = 'APROBADA' THEN
        IF current_setting('caja.pagando_solicitud', true) IS DISTINCT FROM OLD.id::text THEN
            RAISE EXCEPTION 'La solicitud % vuelve a aprobada solo al anular su comprobante.', OLD.numero;
        END IF;
        RETURN NEW;
    END IF;

    -- Anular
    IF OLD.estado IN ('PENDIENTE', 'APROBADA') AND NEW.estado = 'ANULADA' THEN
        IF NEW.anulado_por IS DISTINCT FROM OLD.registrado_por AND NOT caja.es_cajero(OLD.caja_id, NEW.anulado_por) THEN
            RAISE EXCEPTION 'La solicitud % la anula quien la registró o un cajero de la caja.', OLD.numero;
        END IF;
        NEW.anulado_en := COALESCE(NEW.anulado_en, now());
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'La solicitud % está % y no puede pasar a %.', OLD.numero, lower(OLD.estado), lower(NEW.estado);
END $$;

CREATE TRIGGER solicitud_control
    BEFORE INSERT OR UPDATE OR DELETE ON caja.solicitud
    FOR EACH ROW EXECUTE FUNCTION caja.tg_solicitud_control();

-- Comprobante de una caja con aprobación: el egreso manual sale de una
-- solicitud aprobada, con sus datos; quien aprobó no paga.
CREATE FUNCTION caja.tg_movimiento_solicitud() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    c caja.caja;
    k caja.concepto;
    s caja.solicitud;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.solicitud_id IS DISTINCT FROM OLD.solicitud_id THEN
            RAISE EXCEPTION 'La solicitud de un comprobante no se cambia (comprobante %).', OLD.numero;
        END IF;
        RETURN NEW;
    END IF;

    SELECT * INTO c FROM caja.caja WHERE id = (SELECT caja_id FROM caja.sesion WHERE id = NEW.sesion_id);
    SELECT * INTO k FROM caja.concepto WHERE id = NEW.concepto_id;

    IF NEW.solicitud_id IS NULL THEN
        IF c.requiere_aprobacion AND k.tipo = 'EGRESO' AND k.origen = 'MANUAL' AND NOT k.exento_aprobacion THEN
            RAISE EXCEPTION 'La caja % requiere aprobación: los egresos se pagan desde una solicitud aprobada (Caja → Solicitudes).', c.codigo;
        END IF;
        RETURN NEW;
    END IF;

    SELECT * INTO s FROM caja.solicitud WHERE id = NEW.solicitud_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La solicitud no existe.';
    END IF;
    IF s.caja_id <> c.id THEN
        RAISE EXCEPTION 'La solicitud % es de otra caja.', s.numero;
    END IF;
    IF s.estado <> 'APROBADA' THEN
        RAISE EXCEPTION 'La solicitud % está % : solo se pagan las aprobadas.', s.numero, lower(s.estado);
    END IF;
    IF NEW.registrado_por = s.resuelto_por THEN
        RAISE EXCEPTION 'Usted aprobó la solicitud %: debe pagarla otro cajero.', s.numero;
    END IF;

    -- Lo que se paga es lo aprobado.
    NEW.concepto_id    := s.concepto_id;
    NEW.monto          := s.monto;
    NEW.moneda         := s.moneda;
    NEW.persona_id     := s.persona_id;
    NEW.persona_nombre := s.persona_nombre;
    NEW.persona_ci     := s.persona_ci;
    RETURN NEW;
END $$;

-- Antes que movimiento_persona (orden alfabético de triggers): los datos de
-- la persona ya llegan de la solicitud.
CREATE TRIGGER movimiento_a_solicitud
    BEFORE INSERT OR UPDATE OF solicitud_id ON caja.movimiento
    FOR EACH ROW EXECUTE FUNCTION caja.tg_movimiento_solicitud();

-- Después de guardar el comprobante: la solicitud pasa a pagada, o vuelve a
-- aprobada si el comprobante se anula.
CREATE FUNCTION caja.tg_movimiento_solicitud_estado() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.solicitud_id IS NULL THEN
        RETURN NULL;
    END IF;
    PERFORM set_config('caja.pagando_solicitud', NEW.solicitud_id::text, true);
    IF TG_OP = 'INSERT' THEN
        UPDATE caja.solicitud SET estado = 'PAGADA', movimiento_id = NEW.id, updated_at = now()
         WHERE id = NEW.solicitud_id;
    ELSIF OLD.estado = 'VIGENTE' AND NEW.estado = 'ANULADO' THEN
        UPDATE caja.solicitud SET estado = 'APROBADA', movimiento_id = NULL, updated_at = now()
         WHERE id = NEW.solicitud_id AND movimiento_id = NEW.id;
    END IF;
    PERFORM set_config('caja.pagando_solicitud', '', true);
    RETURN NULL;
END $$;

CREATE TRIGGER movimiento_solicitud_estado
    AFTER INSERT OR UPDATE OF estado ON caja.movimiento
    FOR EACH ROW EXECUTE FUNCTION caja.tg_movimiento_solicitud_estado();

-- Una caja no deja de pedir aprobación con solicitudes en curso.
CREATE FUNCTION caja.tg_caja_aprobacion() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_n integer;
BEGIN
    IF OLD.requiere_aprobacion AND NOT NEW.requiere_aprobacion THEN
        SELECT count(*) INTO v_n FROM caja.solicitud WHERE caja_id = OLD.id AND estado IN ('PENDIENTE', 'APROBADA');
        IF v_n > 0 THEN
            RAISE EXCEPTION 'La caja % tiene % solicitud(es) pendiente(s) o aprobada(s) sin pagar: resuélvalas antes de quitar la aprobación.', OLD.codigo, v_n;
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER caja_aprobacion
    BEFORE UPDATE OF requiere_aprobacion ON caja.caja
    FOR EACH ROW EXECUTE FUNCTION caja.tg_caja_aprobacion();

COMMIT;
