/* =====================================================================
   18 — COMPROBANTES PROVISIONALES Y AJUSTE EN EL DÍA — esquema caja
   ---------------------------------------------------------------------
   Caso: se entregan Bs 10.000 para un repuesto que al final cuesta 15.000
   (o 8.000). El comprobante no se rehace al día siguiente: se ajusta el
   MISMO día, con la caja abierta, y el arqueo de la noche ya cuenta lo real.

   1. La cajera marca el egreso como PROVISIONAL al emitirlo (solo egresos
      manuales en efectivo). El saldo baja en lo entregado.
   2. Mientras la sesión del día está abierta, se ajusta el monto:
        - baja (gastó menos): se aplica al momento; la cajera recibe la
          devolución y el saldo sube;
        - sube (gastó más): en cajas con aprobación queda PENDIENTE hasta
          que un aprobador lo acepte; recién entonces la cajera entrega la
          diferencia (APLICADO). En cajas sin aprobación se aplica directo.
      Cada ajuste queda registrado: monto anterior, nuevo, motivo, factura,
      quién lo pidió, quién lo aprobó y quién lo aplicó.
   3. La cajera VALIDA el comprobante con el monto final. Validado, ya no
      se ajusta. No se valida con un ajuste en curso.
   4. La sesión no se cierra con comprobantes provisionales sin validar:
      ningún ajuste cae en otro día ni toca un cierre.

   Separación de funciones (igual que las solicitudes): quien aprueba un
   aumento no lo pidió ni lo paga.
   ===================================================================== */

BEGIN;

/* ---------------------------------------------------------------------
   1. Columnas del comprobante
   --------------------------------------------------------------------- */
ALTER TABLE caja.movimiento
    ADD COLUMN provisional  boolean NOT NULL DEFAULT false,
    ADD COLUMN validado_por bigint REFERENCES public.users(id),
    ADD COLUMN validado_en  timestamp(0),
    ADD CONSTRAINT ck_mov_validado CHECK ((validado_por IS NULL) = (validado_en IS NULL)
                                         AND (validado_por IS NULL OR provisional));
CREATE INDEX ix_mov_provisional ON caja.movimiento (sesion_id) WHERE provisional AND validado_por IS NULL;
COMMENT ON COLUMN caja.movimiento.provisional IS 'Egreso a rendir en el día: su monto se ajusta mientras la sesión está abierta, hasta que se valida.';

/* ---------------------------------------------------------------------
   2. Ajustes
   --------------------------------------------------------------------- */
CREATE TABLE caja.movimiento_ajuste (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movimiento_id  bigint NOT NULL REFERENCES caja.movimiento(id),
    monto_anterior numeric(14,2) NOT NULL CHECK (monto_anterior > 0),
    monto_nuevo    numeric(14,2) NOT NULL CHECK (monto_nuevo > 0),
    motivo         varchar(250) NOT NULL CHECK (length(btrim(motivo)) >= 5),
    documento      varchar(60),
    estado         varchar(10) NOT NULL DEFAULT 'PENDIENTE'
                   CHECK (estado IN ('PENDIENTE','APROBADO','RECHAZADO','APLICADO','ANULADO')),
    registrado_por bigint NOT NULL REFERENCES public.users(id),
    registrado_en  timestamp(0) NOT NULL DEFAULT now(),
    resuelto_por   bigint REFERENCES public.users(id),
    resuelto_en    timestamp(0),
    observacion    varchar(250),
    aplicado_por   bigint REFERENCES public.users(id),
    aplicado_en    timestamp(0),
    CONSTRAINT ck_ajuste_cambia    CHECK (monto_nuevo <> monto_anterior),
    CONSTRAINT ck_ajuste_rechazo   CHECK (estado <> 'RECHAZADO' OR length(btrim(COALESCE(observacion, ''))) >= 5),
    CONSTRAINT ck_ajuste_aplicado  CHECK ((estado = 'APLICADO') = (aplicado_por IS NOT NULL AND aplicado_en IS NOT NULL))
);
CREATE INDEX ix_ajuste_movimiento ON caja.movimiento_ajuste (movimiento_id);
CREATE INDEX ix_ajuste_estado ON caja.movimiento_ajuste (estado) WHERE estado IN ('PENDIENTE', 'APROBADO');
CREATE UNIQUE INDEX ux_ajuste_en_curso ON caja.movimiento_ajuste (movimiento_id) WHERE estado IN ('PENDIENTE', 'APROBADO');
COMMENT ON TABLE caja.movimiento_ajuste IS 'Ajustes del monto de un comprobante provisional, dentro del día. Historial completo.';

-- Las filas de ajuste solo las escriben las funciones de abajo.
CREATE FUNCTION caja.tg_ajuste_solo_funciones() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF current_setting('caja.ajuste_fn', true) IS DISTINCT FROM 'si' THEN
        RAISE EXCEPTION 'Los ajustes de comprobante se registran, aprueban y aplican desde caja, no directamente.';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;

CREATE TRIGGER ajuste_solo_funciones
    BEFORE INSERT OR UPDATE OR DELETE ON caja.movimiento_ajuste
    FOR EACH ROW EXECUTE FUNCTION caja.tg_ajuste_solo_funciones();

/* ---------------------------------------------------------------------
   3. Control del comprobante: se agrega el ajuste de monto
   --------------------------------------------------------------------- */
CREATE OR REPLACE FUNCTION caja.tg_movimiento_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    s        caja.sesion;
    c        caja.caja;
    k        caja.concepto;
    v_saldo  numeric;
    v_ajuste boolean;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los movimientos de caja no se eliminan: se anulan con motivo (comprobante %).', OLD.numero;
    END IF;

    -- La sesión se bloquea para que dos egresos simultáneos no se salten el control de saldo.
    SELECT * INTO s FROM caja.sesion WHERE id = NEW.sesion_id FOR UPDATE;
    IF s.estado <> 'ABIERTA' THEN
        RAISE EXCEPTION 'La sesión % de caja está %: no admite movimientos.', s.numero, s.estado;
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT * INTO c FROM caja.caja WHERE id = s.caja_id;
        SELECT * INTO k FROM caja.concepto WHERE id = NEW.concepto_id;
        IF NOT k.activo THEN
            RAISE EXCEPTION 'El concepto «%» está inactivo.', k.nombre;
        END IF;
        NEW.caja_id := s.caja_id;
        NEW.tipo    := k.tipo;              -- el tipo lo define el concepto
        NEW.estado  := 'VIGENTE';
        NEW.anulado_por := NULL; NEW.anulado_en := NULL; NEW.motivo_anulacion := NULL;

        IF NOT EXISTS (SELECT 1 FROM caja.sesion_saldo WHERE sesion_id = s.id AND moneda = NEW.moneda) THEN
            RAISE EXCEPTION 'La sesión no tiene saldo abierto en %.', NEW.moneda;
        END IF;

        IF NEW.tipo = 'EGRESO' AND NEW.forma_pago = 'EFECTIVO' THEN
            v_saldo := caja.saldo_efectivo(s.id, NEW.moneda);
            IF v_saldo < NEW.monto THEN
                RAISE EXCEPTION 'Saldo insuficiente en caja: hay % % en efectivo y el egreso es de %.', v_saldo, NEW.moneda, NEW.monto;
            END IF;
        END IF;

        NEW.numero := comun.generar_codigo('caja.comprobante:' || c.id, c.formato_comprobante,
                                           c.reinicio_comprobante, NEW.fecha::date,
                                           jsonb_build_object('CAJA', c.codigo));
        RETURN NEW;
    END IF;

    -- UPDATE: se anula, o se ajusta el monto de un provisional (desde caja.aplicar_ajuste).
    v_ajuste := current_setting('caja.ajustando_movimiento', true) IS NOT DISTINCT FROM OLD.id::text;

    IF (NEW.sesion_id, NEW.caja_id, NEW.numero, NEW.fecha, NEW.tipo, NEW.concepto_id, NEW.moneda,
        NEW.forma_pago, NEW.banco_id, NEW.nro_documento, NEW.persona_nombre, NEW.persona_ci, NEW.glosa, NEW.registrado_por)
       IS DISTINCT FROM
       (OLD.sesion_id, OLD.caja_id, OLD.numero, OLD.fecha, OLD.tipo, OLD.concepto_id, OLD.moneda,
        OLD.forma_pago, OLD.banco_id, OLD.nro_documento, OLD.persona_nombre, OLD.persona_ci, OLD.glosa, OLD.registrado_por)
       OR (NEW.monto IS DISTINCT FROM OLD.monto AND NOT v_ajuste) THEN
        RAISE EXCEPTION 'Un movimiento de caja no se corrige: se anula y se registra otro (comprobante %).', OLD.numero;
    END IF;
    IF OLD.estado = 'ANULADO' THEN
        RAISE EXCEPTION 'El comprobante % ya está anulado.', OLD.numero;
    END IF;

    -- Aumento de un egreso en efectivo: la diferencia sale de la caja.
    IF v_ajuste AND NEW.monto > OLD.monto AND OLD.tipo = 'EGRESO' AND OLD.forma_pago = 'EFECTIVO' THEN
        v_saldo := caja.saldo_efectivo(s.id, OLD.moneda);
        IF v_saldo < NEW.monto - OLD.monto THEN
            RAISE EXCEPTION 'Saldo insuficiente en caja: hay % % en efectivo y la diferencia a entregar es de %.',
                v_saldo, OLD.moneda, NEW.monto - OLD.monto;
        END IF;
    END IF;

    IF NEW.estado = 'ANULADO' AND NEW.tipo = 'INGRESO' AND NEW.forma_pago = 'EFECTIVO' THEN
        v_saldo := caja.saldo_efectivo(s.id, NEW.moneda);
        IF v_saldo - NEW.monto < 0 THEN
            RAISE EXCEPTION 'Anular este ingreso dejaría la caja en negativo (saldo %).', v_saldo;
        END IF;
    END IF;
    RETURN NEW;
END $$;

-- Provisional: solo egresos manuales en efectivo; se fija al emitir y la
-- validación la hace la función caja.validar_movimiento.
CREATE FUNCTION caja.tg_movimiento_provisional() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    k caja.concepto;
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.validado_por := NULL; NEW.validado_en := NULL;
        IF NEW.provisional THEN
            SELECT * INTO k FROM caja.concepto WHERE id = NEW.concepto_id;
            IF k.tipo <> 'EGRESO' OR k.origen <> 'MANUAL' THEN
                RAISE EXCEPTION 'Solo los egresos manuales pueden ser provisionales (ajustables en el día).';
            END IF;
            IF NEW.forma_pago <> 'EFECTIVO' THEN
                RAISE EXCEPTION 'Solo los egresos en efectivo pueden ser provisionales: un cheque o una transferencia no se ajustan.';
            END IF;
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.provisional IS DISTINCT FROM OLD.provisional THEN
        RAISE EXCEPTION 'Un comprobante no cambia entre provisional y definitivo (comprobante %).', OLD.numero;
    END IF;
    IF (NEW.validado_por, NEW.validado_en) IS DISTINCT FROM (OLD.validado_por, OLD.validado_en)
       AND current_setting('caja.validando_movimiento', true) IS DISTINCT FROM OLD.id::text THEN
        RAISE EXCEPTION 'El comprobante % se valida desde caja.', OLD.numero;
    END IF;
    IF NEW.monto IS DISTINCT FROM OLD.monto AND (NOT OLD.provisional OR OLD.validado_por IS NOT NULL) THEN
        RAISE EXCEPTION 'El comprobante % no es provisional o ya está validado: su monto no se ajusta.', OLD.numero;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER movimiento_provisional
    BEFORE INSERT OR UPDATE ON caja.movimiento
    FOR EACH ROW EXECUTE FUNCTION caja.tg_movimiento_provisional();

-- Al anular un provisional, sus ajustes en curso se anulan con él.
CREATE FUNCTION caja.tg_movimiento_anula_ajustes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.estado = 'VIGENTE' AND NEW.estado = 'ANULADO' THEN
        PERFORM set_config('caja.ajuste_fn', 'si', true);
        UPDATE caja.movimiento_ajuste
           SET estado = 'ANULADO', observacion = COALESCE(observacion, 'Comprobante anulado')
         WHERE movimiento_id = NEW.id AND estado IN ('PENDIENTE', 'APROBADO');
        PERFORM set_config('caja.ajuste_fn', '', true);
    END IF;
    RETURN NULL;
END $$;

CREATE TRIGGER movimiento_anula_ajustes
    AFTER UPDATE OF estado ON caja.movimiento
    FOR EACH ROW EXECUTE FUNCTION caja.tg_movimiento_anula_ajustes();

