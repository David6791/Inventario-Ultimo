-- Datos comunes para operar sobre un provisional del día.
CREATE FUNCTION caja.exigir_provisional_del_dia(p_movimiento bigint) RETURNS caja.movimiento
LANGUAGE plpgsql AS $$
DECLARE
    m caja.movimiento;
    s caja.sesion;
BEGIN
    SELECT * INTO m FROM caja.movimiento WHERE id = p_movimiento FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El comprobante no existe.';
    END IF;
    IF m.estado <> 'VIGENTE' THEN
        RAISE EXCEPTION 'El comprobante % está anulado.', m.numero;
    END IF;
    IF NOT m.provisional THEN
        RAISE EXCEPTION 'El comprobante % no es provisional: no se ajusta. Si está mal, anúlelo y registre otro.', m.numero;
    END IF;
    IF m.validado_por IS NOT NULL THEN
        RAISE EXCEPTION 'El comprobante % ya está validado: no se ajusta.', m.numero;
    END IF;
    SELECT * INTO s FROM caja.sesion WHERE id = m.sesion_id;
    IF s.estado <> 'ABIERTA' THEN
        RAISE EXCEPTION 'La sesión del comprobante % ya no está abierta.', m.numero;
    END IF;
    IF m.fecha::date <> current_date THEN
        RAISE EXCEPTION 'El comprobante % es del %: los ajustes se hacen el mismo día.', m.numero, to_char(m.fecha, 'DD/MM/YYYY');
    END IF;
    RETURN m;
END $$;

-- Aplica un ajuste: cambia el monto del comprobante (la caja entrega o recibe la diferencia).
CREATE FUNCTION caja.aplicar_ajuste(p_ajuste bigint, p_usuario bigint) RETURNS caja.movimiento_ajuste
LANGUAGE plpgsql AS $$
DECLARE
    a caja.movimiento_ajuste;
    m caja.movimiento;
BEGIN
    SELECT * INTO a FROM caja.movimiento_ajuste WHERE id = p_ajuste FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El ajuste no existe.';
    END IF;
    m := caja.exigir_provisional_del_dia(a.movimiento_id);
    PERFORM caja.exigir_cajero(m.caja_id, p_usuario, 'ajustar comprobantes');

    IF a.estado = 'PENDIENTE' THEN
        RAISE EXCEPTION 'El ajuste del comprobante % espera la aprobación de un aprobador.', m.numero;
    END IF;
    IF a.estado <> 'APROBADO' THEN
        RAISE EXCEPTION 'El ajuste del comprobante % está % y no se aplica.', m.numero, lower(a.estado);
    END IF;
    IF a.resuelto_por = p_usuario THEN
        RAISE EXCEPTION 'Usted aprobó el aumento del comprobante %: debe entregarlo otro cajero.', m.numero;
    END IF;
    IF m.monto <> a.monto_anterior THEN
        RAISE EXCEPTION 'El comprobante % cambió desde que se pidió el ajuste: pida uno nuevo.', m.numero;
    END IF;

    PERFORM set_config('caja.ajustando_movimiento', m.id::text, true);
    UPDATE caja.movimiento SET monto = a.monto_nuevo, updated_at = now() WHERE id = m.id;
    PERFORM set_config('caja.ajustando_movimiento', '', true);

    PERFORM set_config('caja.ajuste_fn', 'si', true);
    UPDATE caja.movimiento_ajuste SET estado = 'APLICADO', aplicado_por = p_usuario, aplicado_en = now()
     WHERE id = a.id RETURNING * INTO a;
    PERFORM set_config('caja.ajuste_fn', '', true);
    RETURN a;
END $$;

-- La cajera registra el monto real. Baja, o sube en cajas sin aprobación:
-- se aplica al momento. Sube en caja con aprobación: queda pendiente.
CREATE FUNCTION caja.ajustar_movimiento(p_movimiento bigint, p_monto numeric, p_motivo text,
                                        p_documento text, p_usuario bigint) RETURNS caja.movimiento_ajuste
LANGUAGE plpgsql AS $$
DECLARE
    m          caja.movimiento;
    c          caja.caja;
    k          caja.concepto;
    a          caja.movimiento_ajuste;
    v_aprobar  boolean;
BEGIN
    m := caja.exigir_provisional_del_dia(p_movimiento);
    PERFORM caja.exigir_cajero(m.caja_id, p_usuario, 'ajustar comprobantes');

    IF p_monto IS NULL OR p_monto <= 0 THEN
        RAISE EXCEPTION 'El monto final debe ser mayor que cero. Si no se gastó nada, anule el comprobante.';
    END IF;
    IF p_monto = m.monto THEN
        RAISE EXCEPTION 'El monto final es igual al del comprobante (%): no hay nada que ajustar.', m.monto;
    END IF;
    IF EXISTS (SELECT 1 FROM caja.movimiento_ajuste WHERE movimiento_id = m.id AND estado IN ('PENDIENTE', 'APROBADO')) THEN
        RAISE EXCEPTION 'El comprobante % ya tiene un ajuste en curso: resuélvalo primero.', m.numero;
    END IF;

    SELECT * INTO c FROM caja.caja WHERE id = m.caja_id;
    SELECT * INTO k FROM caja.concepto WHERE id = m.concepto_id;
    v_aprobar := p_monto > m.monto AND c.requiere_aprobacion AND NOT k.exento_aprobacion;

    PERFORM set_config('caja.ajuste_fn', 'si', true);
    INSERT INTO caja.movimiento_ajuste (movimiento_id, monto_anterior, monto_nuevo, motivo, documento, estado,
                                        registrado_por, resuelto_por, resuelto_en)
    VALUES (m.id, m.monto, round(p_monto, 2), btrim(COALESCE(p_motivo, '')), NULLIF(btrim(COALESCE(p_documento, '')), ''),
            CASE WHEN v_aprobar THEN 'PENDIENTE' ELSE 'APROBADO' END, p_usuario,
            NULL, NULL)
    RETURNING * INTO a;
    PERFORM set_config('caja.ajuste_fn', '', true);

    IF v_aprobar THEN
        RETURN a;
    END IF;
    RETURN caja.aplicar_ajuste(a.id, p_usuario);
END $$;

-- El aprobador acepta o rechaza el aumento.
CREATE FUNCTION caja.resolver_ajuste(p_ajuste bigint, p_aprobar boolean, p_observacion text, p_usuario bigint)
RETURNS caja.movimiento_ajuste
LANGUAGE plpgsql AS $$
DECLARE
    a caja.movimiento_ajuste;
    m caja.movimiento;
    v_usuario varchar;
    v_ci      varchar;
BEGIN
    SELECT * INTO a FROM caja.movimiento_ajuste WHERE id = p_ajuste FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El ajuste no existe.';
    END IF;
    SELECT * INTO m FROM caja.movimiento WHERE id = a.movimiento_id;
    IF a.estado <> 'PENDIENTE' THEN
        RAISE EXCEPTION 'El ajuste del comprobante % ya está %.', m.numero, lower(a.estado);
    END IF;

    SELECT name, ci INTO v_usuario, v_ci FROM public.users WHERE id = p_usuario;
    IF NOT caja.es_aprobador(m.caja_id, p_usuario) THEN
        RAISE EXCEPTION '% no es aprobador de la caja %: no puede aprobar ni rechazar sus ajustes.',
            COALESCE(v_usuario, 'El usuario'), (SELECT codigo FROM caja.caja WHERE id = m.caja_id);
    END IF;
    IF p_usuario IN (a.registrado_por, m.registrado_por) THEN
        RAISE EXCEPTION 'Usted registró este comprobante o su ajuste (%): debe aprobarlo otro aprobador.', m.numero;
    END IF;
    IF v_ci IS NOT NULL AND m.persona_ci IS NOT NULL AND upper(btrim(v_ci)) = m.persona_ci THEN
        RAISE EXCEPTION 'El comprobante % es a su nombre: debe aprobar el ajuste otro aprobador.', m.numero;
    END IF;
    IF NOT p_aprobar AND length(btrim(COALESCE(p_observacion, ''))) < 5 THEN
        RAISE EXCEPTION 'Indique por qué se rechaza el ajuste.';
    END IF;

    PERFORM set_config('caja.ajuste_fn', 'si', true);
    UPDATE caja.movimiento_ajuste
       SET estado = CASE WHEN p_aprobar THEN 'APROBADO' ELSE 'RECHAZADO' END,
           resuelto_por = p_usuario, resuelto_en = now(), observacion = NULLIF(btrim(COALESCE(p_observacion, '')), '')
     WHERE id = a.id RETURNING * INTO a;
    PERFORM set_config('caja.ajuste_fn', '', true);
    RETURN a;
END $$;

-- La cajera valida el comprobante con el monto final.
CREATE FUNCTION caja.validar_movimiento(p_movimiento bigint, p_usuario bigint) RETURNS caja.movimiento
LANGUAGE plpgsql AS $$
DECLARE
    m caja.movimiento;
BEGIN
    SELECT * INTO m FROM caja.movimiento WHERE id = p_movimiento FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El comprobante no existe.';
    END IF;
    IF m.estado <> 'VIGENTE' THEN
        RAISE EXCEPTION 'El comprobante % está anulado.', m.numero;
    END IF;
    IF NOT m.provisional THEN
        RAISE EXCEPTION 'El comprobante % no es provisional: ya es definitivo.', m.numero;
    END IF;
    IF m.validado_por IS NOT NULL THEN
        RAISE EXCEPTION 'El comprobante % ya está validado.', m.numero;
    END IF;
    PERFORM caja.exigir_cajero(m.caja_id, p_usuario, 'validar comprobantes');
    IF EXISTS (SELECT 1 FROM caja.movimiento_ajuste WHERE movimiento_id = m.id AND estado IN ('PENDIENTE', 'APROBADO')) THEN
        RAISE EXCEPTION 'El comprobante % tiene un ajuste en curso: apruébelo y aplíquelo, o espere su rechazo, antes de validar.', m.numero;
    END IF;

    PERFORM set_config('caja.validando_movimiento', m.id::text, true);
    UPDATE caja.movimiento SET validado_por = p_usuario, validado_en = now(), updated_at = now()
     WHERE id = m.id RETURNING * INTO m;
    PERFORM set_config('caja.validando_movimiento', '', true);
    RETURN m;
END $$;

/* ---------------------------------------------------------------------
   5. Cierre: sin provisionales pendientes
   --------------------------------------------------------------------- */
CREATE FUNCTION caja.tg_sesion_sin_provisionales() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_lista text;
BEGIN
    IF OLD.estado = 'ABIERTA' AND NEW.estado = 'CERRADA' THEN
        SELECT string_agg(numero, ', ' ORDER BY numero) INTO v_lista
          FROM caja.movimiento
         WHERE sesion_id = NEW.id AND estado = 'VIGENTE' AND provisional AND validado_por IS NULL;
        IF v_lista IS NOT NULL THEN
            RAISE EXCEPTION 'Hay comprobantes provisionales sin validar (%): ajústelos y valídelos antes de cerrar la caja.', v_lista;
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER sesion_sin_provisionales
    BEFORE UPDATE OF estado ON caja.sesion
    FOR EACH ROW EXECUTE FUNCTION caja.tg_sesion_sin_provisionales();

COMMIT;
