LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.lote_par_id = NEW.id THEN
        RAISE EXCEPTION 'Un lote no puede ser su propio par.';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.lote_par_id IS NOT NULL AND NEW.lote_par_id IS DISTINCT FROM OLD.lote_par_id THEN
        RAISE EXCEPTION 'El lote % ya está ligado a su par de la recepción mixta: no se cambia.', OLD.codigo;
    END IF;
    RETURN NEW;
END $$;

