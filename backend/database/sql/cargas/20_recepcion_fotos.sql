    BEFORE INSERT OR UPDATE OF lote_par_id ON cargas.lote
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_lote_par();

-- ---------------------------------------------------------------------
-- 6. Reglas del pesaje (reemplaza la versión de 15_peso_cliente.sql)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION cargas.tg_pesaje_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_estado varchar; v_codigo varchar;
    v_corrigiendo boolean := COALESCE(current_setting('cargas.corrigiendo_peso_cliente', true), '') = 'si';
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los pesajes no se eliminan: se anulan con motivo.';
    END IF;

    SELECT estado, codigo INTO v_estado, v_codigo FROM cargas.lote WHERE id = NEW.lote_id;

    IF TG_OP = 'UPDATE' THEN
        IF (NEW.lote_id, NEW.tipo, NEW.bascula, NEW.ticket, NEW.peso_bruto_kg, NEW.tara_kg,
            NEW.modalidad, NEW.descuento_sacos_kg, NEW.pesaje_viaje_id, NEW.num_sacos)
           IS DISTINCT FROM
           (OLD.lote_id, OLD.tipo, OLD.bascula, OLD.ticket, OLD.peso_bruto_kg, OLD.tara_kg,
            OLD.modalidad, OLD.descuento_sacos_kg, OLD.pesaje_viaje_id, OLD.num_sacos)
           OR (NOT v_corrigiendo AND (NEW.peso_cliente_kg, NEW.peso_cliente_tipo)
                                     IS DISTINCT FROM (OLD.peso_cliente_kg, OLD.peso_cliente_tipo)) THEN
            RAISE EXCEPTION 'Un pesaje registrado no se corrige: se anula y se registra otro.';
        END IF;
        IF OLD.anulado AND NOT NEW.anulado THEN
            RAISE EXCEPTION 'Un pesaje anulado no se reactiva.';
        END IF;
        IF v_corrigiendo THEN
            RETURN NEW;      -- la función ya validó estado y motivo
        END IF;
    END IF;

    IF NEW.tipo = 'INGRESO' AND v_estado <> 'RECIBIDO' THEN
        RAISE EXCEPTION 'El lote % está %: los pesajes de ingreso solo se registran o anulan mientras está RECIBIDO.', v_codigo, v_estado;
    END IF;
    IF v_estado IN ('ANULADO','LIQUIDADO') THEN
        RAISE EXCEPTION 'El lote % está % y no admite pesajes.', v_codigo, v_estado;
    END IF;
    IF TG_OP = 'INSERT' AND NEW.pesaje_viaje_id IS NOT NULL THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.pesaje v
                        WHERE v.id = NEW.pesaje_viaje_id AND v.modalidad = 'BASCULA' AND v.tipo = 'INGRESO'
                          AND NOT v.anulado AND v.lote_id <> NEW.lote_id) THEN
            RAISE EXCEPTION 'Los sacos de una recepción mixta van ligados al pesaje de báscula vigente del camión, en otro lote.';
        END IF;
    END IF;
    RETURN NEW;
END $$;

-- Coherencia al cerrar la transacción: el total de los sacos cuadra con su
-- detalle, y lo restado al granel es exactamente lo que pesaron los sacos.
CREATE FUNCTION cargas.verificar_pesaje(p_id bigint) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    p cargas.pesaje; v_kg numeric; v_sacos integer; v_n integer;
BEGIN
    SELECT * INTO p FROM cargas.pesaje WHERE id = p_id;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    IF p.modalidad = 'SACOS' THEN
        SELECT count(*), COALESCE(sum(peso_kg), 0), COALESCE(sum(sacos), 0) INTO v_n, v_kg, v_sacos
          FROM cargas.pesaje_saco WHERE pesaje_id = p.id;
        IF v_n = 0 THEN
            RAISE EXCEPTION 'El pesaje de sacos necesita al menos una pesada en la balanza manual.';
        END IF;
        IF v_kg <> p.peso_bruto_kg OR v_sacos IS DISTINCT FROM p.num_sacos THEN
            RAISE EXCEPTION 'El pesaje de sacos (% kg, % sacos) no cuadra con sus pesadas (% kg, % sacos).',
                p.peso_bruto_kg, p.num_sacos, v_kg, v_sacos;
        END IF;
        IF EXISTS (SELECT 1 FROM cargas.pesaje_saco s
                    WHERE s.pesaje_id = p.id
                      AND NOT EXISTS (SELECT 1 FROM cargas.recepcion_foto f WHERE f.pesaje_saco_id = s.id)) THEN
            RAISE EXCEPTION 'Cada pesada en la balanza manual necesita su foto.';
        END IF;
    END IF;

    -- Viaje mixto: descuento del camión = sacos vigentes ligados a él.
    IF p.modalidad = 'BASCULA' AND NOT p.anulado THEN
        SELECT COALESCE(sum(s.peso_bruto_kg), 0) INTO v_kg
          FROM cargas.pesaje s WHERE s.pesaje_viaje_id = p.id AND NOT s.anulado;
        IF v_kg <> p.descuento_sacos_kg THEN
            RAISE EXCEPTION 'Al neto del ticket % se le restan % kg por sacos, pero los sacos de ese viaje pesan % kg.',
                p.ticket, p.descuento_sacos_kg, v_kg;
        END IF;
    END IF;
END $$;

CREATE FUNCTION cargas.tg_pesaje_coherencia() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_id bigint;
BEGIN
    IF TG_TABLE_NAME = 'pesaje_saco' THEN
        v_id := NEW.pesaje_id;
    ELSE
        v_id := NEW.id;
        IF NEW.pesaje_viaje_id IS NOT NULL THEN
            PERFORM cargas.verificar_pesaje(NEW.pesaje_viaje_id);
        END IF;
    END IF;
    IF v_id IS NOT NULL THEN
        PERFORM cargas.verificar_pesaje(v_id);
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER pesaje_coherencia
    AFTER INSERT OR UPDATE OF anulado ON cargas.pesaje
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_pesaje_coherencia();
CREATE CONSTRAINT TRIGGER pesaje_saco_coherencia
    AFTER INSERT ON cargas.pesaje_saco
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_pesaje_coherencia();

-- Anular un pesaje de un viaje mixto anula también su par: el camión y sus
-- sacos se registraron juntos y se corrigen juntos.
CREATE FUNCTION cargas.tg_pesaje_anulado_viaje() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.anulado AND NOT OLD.anulado THEN
        UPDATE cargas.pesaje
           SET anulado = true, motivo_anulacion = left('Viaje mixto anulado: ' || NEW.motivo_anulacion, 250), updated_at = now()
         WHERE NOT anulado
           AND (pesaje_viaje_id = NEW.id OR id = NEW.pesaje_viaje_id);
    END IF;
    RETURN NULL;
END $$;

CREATE TRIGGER pesaje_anulado_viaje
    AFTER UPDATE OF anulado ON cargas.pesaje
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_pesaje_anulado_viaje();

-- ---------------------------------------------------------------------
-- 7. Bono de transporte: uno por viaje, por el peso del camión completo
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION cargas.tg_bono_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    p cargas.pesaje; t cargas.bono_transporte_tramo; v_peso numeric;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los bonos de transporte no se eliminan: se anulan con motivo.';
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT * INTO p FROM cargas.pesaje WHERE id = NEW.pesaje_id;
        IF p.tipo <> 'INGRESO' OR p.anulado THEN
            RAISE EXCEPTION 'Solo un pesaje de INGRESO vigente genera bono de transporte.';
        END IF;
        IF p.pesaje_viaje_id IS NOT NULL THEN
            RAISE EXCEPTION 'Los sacos de una recepción mixta viajaron en el mismo camión: el bono va en el pesaje de báscula.';
        END IF;
        v_peso := p.peso_bruto_kg - p.tara_kg;        -- el camión completo, con sacos
        IF NEW.tramo_id IS NULL THEN
            NEW.tramo_id := cargas.tramo_bono(v_peso, p.fecha::date);
        END IF;
        SELECT * INTO t FROM cargas.bono_transporte_tramo
         WHERE id = NEW.tramo_id
           AND numrange(peso_desde_kg, peso_hasta_kg, '[)') @> v_peso
           AND daterange(vigente_desde, vigente_hasta, '[)') @> p.fecha::date;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No hay tramo de bono vigente para % kg al %.', v_peso, p.fecha::date;
        END IF;
        NEW.monto  := t.monto;                    -- el monto sale del tramo, no se digita
        NEW.moneda := t.moneda;
        NEW.estado := 'PENDIENTE';
        NEW.movimiento_caja_id := NULL;
        NEW.beneficiario_nombre := COALESCE(NEW.beneficiario_nombre, p.chofer_nombre);
        NEW.beneficiario_ci     := COALESCE(NEW.beneficiario_ci, p.chofer_ci);
        RETURN NEW;
    END IF;

    -- UPDATE
    IF (NEW.pesaje_id, NEW.tramo_id, NEW.monto, NEW.moneda, NEW.registrado_por)
       IS DISTINCT FROM (OLD.pesaje_id, OLD.tramo_id, OLD.monto, OLD.moneda, OLD.registrado_por) THEN
        RAISE EXCEPTION 'Los datos de un bono de transporte no se modifican.';
    END IF;
    IF NEW.estado <> OLD.estado THEN
        IF NOT (OLD.estado = 'PENDIENTE' AND NEW.estado IN ('PAGADO','ANULADO')) THEN
            RAISE EXCEPTION 'Transición no permitida para el bono: % → %.', OLD.estado, NEW.estado;
        END IF;
        IF NEW.estado = 'PAGADO' THEN
            PERFORM cargas.validar_movimiento_caja(NEW.movimiento_caja_id, 'EGRESO', 'CARGAS_BONO',
                                                   NEW.monto, NEW.moneda, 'el bono de transporte');
        END IF;
    ELSIF NEW.movimiento_caja_id IS DISTINCT FROM OLD.movimiento_caja_id THEN
        RAISE EXCEPTION 'El comprobante de pago del bono no se cambia.';
    END IF;
    RETURN NEW;
END $$;

