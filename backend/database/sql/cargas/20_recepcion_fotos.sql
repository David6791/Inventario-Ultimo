/* =====================================================================
   20. RECEPCIÓN CON FOTOS: BÁSCULA, SOLO SACOS Y MIXTA
   ---------------------------------------------------------------------
   a) Plantillas de báscula: dónde está cada dato (ticket, bruto, tara,
      neto…) en el ticket impreso de cada balanza, como recuadros en
      fracciones (0–1) del ticket enderezado. Con ellas Tesseract lee la
      foto; la persona confirma o corrige lo leído antes de guardar.
   b) Fotos de la recepción: ticket interior (báscula de la empresa, el
      peso que vale), ticket exterior (peso del cliente, informativo) y la
      balanza manual de los sacos. Una foto ligada a un pesaje es respaldo:
      no se cambia, no se desliga y no se borra.
   c) Tres tipos de recepción:
        BASCULA  — camión pesado en báscula (como hasta ahora).
        SACOS    — sacos pesados en balanza manual: un total o saco por
                   saco (o por tandas), cada pesada con su foto.
        MIXTA    — volqueta con mineral a granel y sacos: DOS lotes. El de
                   sacos lleva el peso de sus sacos; el de granel, el neto
                   del ticket menos esos sacos.
      pesaje.modalidad = BASCULA o SACOS; pesaje.descuento_sacos_kg es lo
      que se resta del neto del ticket por los sacos que van en otro lote;
      pesaje.pesaje_viaje_id liga el pesaje de sacos con el del camión.
      El bono de transporte es UNO por viaje: el del pesaje de báscula,
      con el peso del camión completo (bruto − tara).
   ===================================================================== */

BEGIN;

-- ---------------------------------------------------------------------
-- 1. Plantillas de báscula
-- ---------------------------------------------------------------------
CREATE TABLE cargas.plantilla_bascula (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          varchar(60)  NOT NULL,
    bascula         varchar(40)  NOT NULL,
    uso             varchar(10)  NOT NULL DEFAULT 'INTERIOR' CHECK (uso IN ('INTERIOR','EXTERIOR','AMBAS')),
    proporcion      numeric(6,4) NOT NULL CHECK (proporcion BETWEEN 0.1 AND 10),
    campos          jsonb        NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(campos) = 'array'),
    imagen_muestra  varchar(200),
    activa          boolean      NOT NULL DEFAULT true,
    registrado_por  bigint       NOT NULL REFERENCES public.users(id),
    created_at      timestamp(0),
    updated_at      timestamp(0)
);
CREATE UNIQUE INDEX uq_plantilla_bascula_nombre ON cargas.plantilla_bascula (upper(nombre));
COMMENT ON TABLE cargas.plantilla_bascula IS 'Dónde está cada dato en el ticket impreso de una balanza (para leer la foto con OCR).';
COMMENT ON COLUMN cargas.plantilla_bascula.bascula IS 'Nombre de la báscula que se guarda en el pesaje.';
COMMENT ON COLUMN cargas.plantilla_bascula.proporcion IS 'Ancho/alto del ticket enderezado; las fotos se enderezan a esta proporción.';
COMMENT ON COLUMN cargas.plantilla_bascula.campos IS
    '[{"campo":"peso_bruto_kg","x":0.1,"y":0.4,"w":0.5,"h":0.06,"etiqueta":"BRUTO","decimales":0}, ...] en fracciones del ticket.';

-- ---------------------------------------------------------------------
-- 2. Pesaje: modalidad, descuento por sacos y viaje compartido
-- ---------------------------------------------------------------------
ALTER TABLE cargas.pesaje
    ADD COLUMN modalidad varchar(8) NOT NULL DEFAULT 'BASCULA'
        CONSTRAINT ck_pesaje_modalidad CHECK (modalidad IN ('BASCULA','SACOS')),
    ADD COLUMN descuento_sacos_kg numeric(12,2) NOT NULL DEFAULT 0
        CONSTRAINT ck_pesaje_descuento CHECK (descuento_sacos_kg >= 0),
    ADD COLUMN pesaje_viaje_id bigint REFERENCES cargas.pesaje(id);
CREATE INDEX ix_pesaje_viaje ON cargas.pesaje (pesaje_viaje_id) WHERE pesaje_viaje_id IS NOT NULL;
COMMENT ON COLUMN cargas.pesaje.modalidad IS 'BASCULA (ticket de báscula) o SACOS (balanza manual, detalle en pesaje_saco).';
COMMENT ON COLUMN cargas.pesaje.descuento_sacos_kg IS 'Recepción mixta: kg de sacos que van en otro lote y se restan del neto del ticket.';
COMMENT ON COLUMN cargas.pesaje.pesaje_viaje_id IS 'Recepción mixta: el pesaje de báscula del camión en que llegaron estos sacos.';

-- El ticket es de la báscula; en la balanza manual no hay ticket impreso.
ALTER TABLE cargas.pesaje ALTER COLUMN ticket DROP NOT NULL;
ALTER TABLE cargas.pesaje
    ADD CONSTRAINT ck_pesaje_ticket CHECK (modalidad = 'SACOS' OR ticket IS NOT NULL),
    ADD CONSTRAINT ck_pesaje_sacos  CHECK (modalidad = 'BASCULA' OR (tara_kg = 0 AND descuento_sacos_kg = 0)),
    ADD CONSTRAINT ck_pesaje_viaje  CHECK (pesaje_viaje_id IS NULL OR modalidad = 'SACOS'),
    ADD CONSTRAINT ck_pesaje_descuento_menor CHECK (descuento_sacos_kg = 0 OR descuento_sacos_kg < peso_bruto_kg - tara_kg);

-- El neto pasa a ser bruto − tara − sacos de otro lote. La columna generada
-- no se puede cambiar en PostgreSQL 16: se rehace y se recrean las vistas
-- que dependen de ella, con su misma definición.
CREATE TEMP TABLE _vistas_pesaje ON COMMIT DROP AS
WITH RECURSIVE dep(oid, nivel) AS (
    SELECT DISTINCT r.ev_class, 1
      FROM pg_depend d JOIN pg_rewrite r ON r.oid = d.objid
     WHERE d.refobjid = 'cargas.pesaje'::regclass AND r.ev_class <> 'cargas.pesaje'::regclass
    UNION
    SELECT r.ev_class, dep.nivel + 1
      FROM dep JOIN pg_depend d ON d.refobjid = dep.oid JOIN pg_rewrite r ON r.oid = d.objid
     WHERE r.ev_class <> dep.oid AND dep.nivel < 20
)
SELECT c.oid::regclass::text AS nombre, max(dep.nivel) AS nivel, pg_get_viewdef(c.oid) AS definicion,
       obj_description(c.oid, 'pg_class') AS comentario
  FROM dep JOIN pg_class c ON c.oid = dep.oid
 WHERE c.relkind = 'v'
 GROUP BY c.oid;

ALTER TABLE cargas.pesaje DROP COLUMN peso_neto_kg CASCADE;
ALTER TABLE cargas.pesaje
    ADD COLUMN peso_neto_kg numeric(12,2) GENERATED ALWAYS AS (peso_bruto_kg - tara_kg - descuento_sacos_kg) STORED;
COMMENT ON COLUMN cargas.pesaje.peso_neto_kg IS 'Peso del lote: bruto − tara − sacos que van en otro lote (lo calcula la base).';

DO $$
DECLARE v record;
BEGIN
    FOR v IN SELECT * FROM _vistas_pesaje ORDER BY nivel, nombre LOOP
        EXECUTE format('CREATE VIEW %s AS %s', v.nombre, v.definicion);
        IF v.comentario IS NOT NULL THEN
            EXECUTE format('COMMENT ON VIEW %s IS %L', v.nombre, v.comentario);
        END IF;
    END LOOP;
END $$;

-- ---------------------------------------------------------------------
-- 3. Detalle de sacos (balanza manual)
-- ---------------------------------------------------------------------
CREATE TABLE cargas.pesaje_saco (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pesaje_id  bigint NOT NULL REFERENCES cargas.pesaje(id),
    orden      integer NOT NULL CHECK (orden > 0),
    sacos      integer NOT NULL CHECK (sacos > 0),
    peso_kg    numeric(12,2) NOT NULL CHECK (peso_kg > 0),
    created_at timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT uq_pesaje_saco_orden UNIQUE (pesaje_id, orden)
);
COMMENT ON TABLE cargas.pesaje_saco IS 'Pesadas en la balanza manual: un total, saco por saco o por tandas. Cada una con su foto.';

CREATE FUNCTION cargas.tg_pesaje_saco_control() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Las pesadas de sacos no se eliminan: se anula el pesaje y se registra otro.';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION 'Una pesada de sacos no se corrige: se anula el pesaje y se registra otro.';
    END IF;
    IF (SELECT modalidad FROM cargas.pesaje WHERE id = NEW.pesaje_id) <> 'SACOS' THEN
        RAISE EXCEPTION 'Solo un pesaje de SACOS lleva detalle de sacos.';
    END IF;
    -- Agregar pesadas después no pasa: el total del pesaje ya no cuadraría (ver verificar_pesaje).
    RETURN NEW;
END $$;

CREATE TRIGGER pesaje_saco_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.pesaje_saco
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_pesaje_saco_control();

-- ---------------------------------------------------------------------
-- 4. Fotos de la recepción
-- ---------------------------------------------------------------------
CREATE TABLE cargas.recepcion_foto (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo            varchar(16) NOT NULL CHECK (tipo IN ('TICKET_INTERIOR','TICKET_EXTERIOR','BALANZA_MANUAL')),
    ruta            varchar(200) NOT NULL,
    ruta_original   varchar(200),
    plantilla_id    bigint REFERENCES cargas.plantilla_bascula(id),
    lectura         jsonb,
    pesaje_id       bigint REFERENCES cargas.pesaje(id),
    pesaje_saco_id  bigint REFERENCES cargas.pesaje_saco(id),
    subida_por      bigint NOT NULL REFERENCES public.users(id),
    created_at      timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_foto_destino CHECK (
        (tipo = 'BALANZA_MANUAL' AND pesaje_id IS NULL) OR (tipo <> 'BALANZA_MANUAL' AND pesaje_saco_id IS NULL))
);
CREATE INDEX ix_foto_pesaje ON cargas.recepcion_foto (pesaje_id) WHERE pesaje_id IS NOT NULL;
CREATE INDEX ix_foto_saco   ON cargas.recepcion_foto (pesaje_saco_id) WHERE pesaje_saco_id IS NOT NULL;
CREATE INDEX ix_foto_suelta ON cargas.recepcion_foto (created_at) WHERE pesaje_id IS NULL AND pesaje_saco_id IS NULL;
COMMENT ON TABLE cargas.recepcion_foto IS 'Fotos de tickets y de la balanza manual. Ligada a un pesaje es respaldo: no cambia ni se borra.';
COMMENT ON COLUMN cargas.recepcion_foto.lectura IS 'Lo que leyó el OCR (texto, valor y confianza por campo), para auditoría.';

CREATE FUNCTION cargas.tg_recepcion_foto_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_modalidad varchar;
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.pesaje_id IS NOT NULL OR OLD.pesaje_saco_id IS NOT NULL THEN
            RAISE EXCEPTION 'La foto es respaldo de un pesaje: no se elimina.';
        END IF;
        RETURN OLD;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF (NEW.tipo, NEW.ruta, NEW.ruta_original, NEW.plantilla_id, NEW.lectura, NEW.subida_por)
           IS DISTINCT FROM (OLD.tipo, OLD.ruta, OLD.ruta_original, OLD.plantilla_id, OLD.lectura, OLD.subida_por) THEN
            RAISE EXCEPTION 'Una foto subida no se modifica: suba otra.';
        END IF;
        IF (OLD.pesaje_id IS NOT NULL AND NEW.pesaje_id IS DISTINCT FROM OLD.pesaje_id)
           OR (OLD.pesaje_saco_id IS NOT NULL AND NEW.pesaje_saco_id IS DISTINCT FROM OLD.pesaje_saco_id) THEN
            RAISE EXCEPTION 'La foto ya es respaldo de un pesaje: no se cambia de pesaje.';
        END IF;
    END IF;

    IF NEW.pesaje_id IS NOT NULL THEN
        SELECT modalidad INTO v_modalidad FROM cargas.pesaje WHERE id = NEW.pesaje_id;
        IF v_modalidad <> 'BASCULA' THEN
            RAISE EXCEPTION 'Las fotos de ticket van en un pesaje de báscula.';
        END IF;
        IF EXISTS (SELECT 1 FROM cargas.recepcion_foto
                    WHERE pesaje_id = NEW.pesaje_id AND tipo = NEW.tipo AND id <> NEW.id) THEN
            RAISE EXCEPTION 'El pesaje ya tiene su foto de %.',
                CASE NEW.tipo WHEN 'TICKET_INTERIOR' THEN 'ticket interior' ELSE 'ticket exterior' END;
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER recepcion_foto_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.recepcion_foto
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_recepcion_foto_control();

