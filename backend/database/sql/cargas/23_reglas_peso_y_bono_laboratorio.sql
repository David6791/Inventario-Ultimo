/* Peso que vale: la primera regla vigente que cumple, y cómo se llama lo que dio. */
DROP FUNCTION cargas.peso_que_vale(numeric, numeric, date);
CREATE FUNCTION cargas.peso_que_vale(p_empresa numeric, p_cliente numeric, p_fecha date,
                                     OUT peso_kg numeric, OUT criterio varchar, OUT regla_id bigint)
LANGUAGE plpgsql STABLE AS $$
DECLARE
    v_d numeric;
    g cargas.regla_peso;
BEGIN
    IF p_cliente IS NULL OR p_cliente <= 0 THEN
        peso_kg := p_empresa; criterio := 'EMPRESA';
        RETURN;
    END IF;
    FOR g IN SELECT * FROM cargas.regla_peso
              WHERE daterange(vigente_desde, vigente_hasta, '[)') @> p_fecha
              ORDER BY orden LOOP
        v_d := CASE g.unidad WHEN 'PCT' THEN (p_cliente - p_empresa) / NULLIF(p_empresa, 0) * 100
                             ELSE p_cliente - p_empresa END;
        IF (g.desde IS NULL OR v_d > g.desde) AND (g.hasta IS NULL OR v_d <= g.hasta) THEN
            peso_kg := cargas.evaluar_formula_peso(g.formula, p_empresa, p_cliente);
            regla_id := g.id;
            criterio := CASE WHEN peso_kg = round(p_empresa, 2) THEN 'EMPRESA'
                             WHEN peso_kg = round(p_cliente, 2) THEN 'CLIENTE'
                             WHEN peso_kg = round((p_empresa + p_cliente) / 2, 2) THEN 'PROMEDIO'
                             ELSE 'FORMULA' END;
            RETURN;
        END IF;
    END LOOP;
    peso_kg := p_empresa; criterio := 'EMPRESA';
END $$;

CREATE OR REPLACE FUNCTION cargas.tg_pesaje_peso_final() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_empresa numeric := NEW.peso_bruto_kg - NEW.tara_kg - NEW.descuento_sacos_kg;
    v_cliente numeric;
    r record;
BEGIN
    IF TG_OP = 'UPDATE' AND (NEW.peso_cliente_kg, NEW.peso_cliente_tipo) IS NOT DISTINCT FROM (OLD.peso_cliente_kg, OLD.peso_cliente_tipo) THEN
        NEW.peso_final_kg := OLD.peso_final_kg;       -- nada que recalcular (ni se toca a mano)
        NEW.criterio_peso := OLD.criterio_peso;
        NEW.regla_peso_id := OLD.regla_peso_id;
        RETURN NEW;
    END IF;
    IF NEW.tipo <> 'INGRESO' THEN
        NEW.peso_final_kg := v_empresa; NEW.criterio_peso := 'EMPRESA'; NEW.regla_peso_id := NULL;
        RETURN NEW;
    END IF;
    v_cliente := CASE WHEN NEW.peso_cliente_kg IS NULL THEN NULL
                      WHEN NEW.peso_cliente_tipo = 'BRUTO' THEN NEW.peso_cliente_kg - NEW.tara_kg
                      ELSE NEW.peso_cliente_kg END;
    r := cargas.peso_que_vale(v_empresa, v_cliente, COALESCE(NEW.fecha, now())::date);
    NEW.peso_final_kg := r.peso_kg;
    NEW.criterio_peso := r.criterio;
    NEW.regla_peso_id := r.regla_id;
    RETURN NEW;
END $$;

/* Publicar un juego de reglas: el vigente termina donde empieza el nuevo. */
CREATE FUNCTION cargas.publicar_reglas_peso(p_desde date, p_reglas jsonb, p_usuario bigint)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    v_n integer;
BEGIN
    IF p_desde IS NULL OR p_desde < current_date THEN
        RAISE EXCEPTION 'Las reglas de peso rigen desde hoy o una fecha futura: los pesajes ya registrados no cambian.';
    END IF;
    IF p_reglas IS NULL OR jsonb_array_length(p_reglas) = 0 THEN
        RAISE EXCEPTION 'Indique al menos una regla de peso.';
    END IF;
    IF EXISTS (SELECT 1 FROM cargas.pesaje p JOIN cargas.regla_peso g ON g.id = p.regla_peso_id
                WHERE g.vigente_desde >= p_desde) THEN
        RAISE EXCEPTION 'Ya hay pesajes calculados con las reglas que empiezan el % o después: publique con otra fecha.', p_desde;
    END IF;
    DELETE FROM cargas.regla_peso WHERE vigente_desde >= p_desde;
    UPDATE cargas.regla_peso SET vigente_hasta = p_desde, updated_at = now()
     WHERE vigente_desde < p_desde AND (vigente_hasta IS NULL OR vigente_hasta > p_desde);

    INSERT INTO cargas.regla_peso (orden, unidad, desde, hasta, formula, descripcion, vigente_desde, registrado_por, created_at, updated_at)
    SELECT x.n, COALESCE(NULLIF(x.r->>'unidad', ''), 'KG'), NULLIF(x.r->>'desde', '')::numeric, NULLIF(x.r->>'hasta', '')::numeric,
           x.r->>'formula', NULLIF(btrim(x.r->>'descripcion'), ''), p_desde, p_usuario, now(), now()
      FROM jsonb_array_elements(p_reglas) WITH ORDINALITY AS x(r, n);
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RETURN v_n;
END $$;

