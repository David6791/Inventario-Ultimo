CREATE OR REPLACE FUNCTION cargas.tg_mov_caja_vinculado() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_origen varchar;
BEGIN
    SELECT origen INTO v_origen FROM caja.concepto WHERE id = NEW.concepto_id;
    IF v_origen NOT LIKE 'CARGAS\_%' THEN
        RETURN NULL;
    END IF;
    IF v_origen = 'CARGAS_ANTICIPO' THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.anticipo WHERE movimiento_pago_id = NEW.id) THEN
            RAISE EXCEPTION 'El comprobante % es un pago de anticipo pero no está vinculado a ningún anticipo de un lote.', NEW.numero;
        END IF;
    ELSIF v_origen = 'CARGAS_ANTICIPO_DEVOLUCION' THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.anticipo WHERE movimiento_devolucion_id = NEW.id) THEN
            RAISE EXCEPTION 'El comprobante % es una devolución de anticipo pero no está vinculado a ningún anticipo.', NEW.numero;
        END IF;
    ELSIF v_origen = 'CARGAS_BONO' THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.bono_transporte WHERE movimiento_caja_id = NEW.id) THEN
            RAISE EXCEPTION 'El comprobante % es un pago de bono de transporte pero no está vinculado a ningún bono.', NEW.numero;
        END IF;
    ELSIF v_origen = 'CARGAS_BONO_LAB' THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.bono_laboratorio WHERE movimiento_caja_id = NEW.id) THEN
            RAISE EXCEPTION 'El comprobante % es un pago de bono de laboratorio pero no está vinculado a ningún bono.', NEW.numero;
        END IF;
    ELSE
        RAISE EXCEPTION 'El concepto de origen % todavía no tiene documento en cargas: no se puede usar.', v_origen;
    END IF;
    RETURN NULL;
END $$;

CREATE OR REPLACE FUNCTION cargas.tg_mov_caja_no_anular() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_doc varchar;
BEGIN
    IF NEW.estado = 'ANULADO' AND OLD.estado = 'VIGENTE' THEN
        SELECT 'el anticipo ' || numero INTO v_doc FROM cargas.anticipo
         WHERE movimiento_pago_id = NEW.id OR movimiento_devolucion_id = NEW.id;
        IF v_doc IS NULL THEN
            SELECT 'un bono de transporte' INTO v_doc FROM cargas.bono_transporte WHERE movimiento_caja_id = NEW.id;
        END IF;
        IF v_doc IS NULL THEN
            SELECT 'un bono de laboratorio' INTO v_doc FROM cargas.bono_laboratorio WHERE movimiento_caja_id = NEW.id;
        END IF;
        IF v_doc IS NOT NULL THEN
            RAISE EXCEPTION 'El comprobante % respalda %: no se anula desde caja. Si el pago fue indebido, registre la devolución.', NEW.numero, v_doc;
        END IF;
    END IF;
    RETURN NEW;
END $$;

-- ---------------------------------------------------------------------
-- d) Lo adelantado por lote: lo que la liquidación descuenta
-- ---------------------------------------------------------------------
CREATE VIEW cargas.v_lote_anticipos AS
SELECT l.id AS lote_id,
       COALESCE(a.bob, 0) AS anticipos_bob,          COALESCE(a.usd, 0) AS anticipos_usd,
       COALESCE(t.bob, 0) AS bono_transporte_bob,    COALESCE(t.usd, 0) AS bono_transporte_usd,
       COALESCE(b.bob, 0) AS bono_laboratorio_bob,   COALESCE(b.usd, 0) AS bono_laboratorio_usd,
       COALESCE(a.bob, 0) + COALESCE(t.bob, 0) + COALESCE(b.bob, 0) AS total_bob,
       COALESCE(a.usd, 0) + COALESCE(t.usd, 0) + COALESCE(b.usd, 0) AS total_usd,
       COALESCE(t.pendiente, 0) + COALESCE(b.pendiente, 0) AS bonos_pendientes
  FROM cargas.lote l
  LEFT JOIN (SELECT lote_id, sum(monto) FILTER (WHERE moneda = 'BOB') AS bob, sum(monto) FILTER (WHERE moneda = 'USD') AS usd
               FROM cargas.anticipo WHERE estado = 'PAGADO' GROUP BY lote_id) a ON a.lote_id = l.id
  LEFT JOIN (SELECT p.lote_id,
                    sum(bt.monto) FILTER (WHERE bt.estado = 'PAGADO' AND bt.moneda = 'BOB') AS bob,
                    sum(bt.monto) FILTER (WHERE bt.estado = 'PAGADO' AND bt.moneda = 'USD') AS usd,
                    count(*) FILTER (WHERE bt.estado = 'PENDIENTE') AS pendiente
               FROM cargas.bono_transporte bt JOIN cargas.pesaje p ON p.id = bt.pesaje_id GROUP BY p.lote_id) t ON t.lote_id = l.id
  LEFT JOIN (SELECT lote_id,
                    sum(monto) FILTER (WHERE estado = 'PAGADO' AND moneda = 'BOB') AS bob,
                    sum(monto) FILTER (WHERE estado = 'PAGADO' AND moneda = 'USD') AS usd,
                    count(*) FILTER (WHERE estado = 'PENDIENTE') AS pendiente
               FROM cargas.bono_laboratorio GROUP BY lote_id) b ON b.lote_id = l.id;
COMMENT ON VIEW cargas.v_lote_anticipos IS
    'Lo pagado por adelantado en cada lote (anticipos, bono de transporte y de laboratorio): lo que la liquidación descuenta.';

COMMIT;
