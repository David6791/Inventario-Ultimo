/* =====================================================================
   23. REGLAS DE PESO CON FÓRMULA, PESO DEL CLIENTE Y BONO DE LABORATORIO
   ---------------------------------------------------------------------
   a) Reglas del peso que vale, editables y con vigencia. Cada regla es un
      tramo de la diferencia D = C − E (C: neto del cliente, E: neto de
      nuestra báscula), en kg o en % de E, con su fórmula:
          desde < D ≤ hasta   →   fórmula
      La fórmula usa E, C, D, números (coma o punto decimal), + − * /,
      paréntesis y MIN(…; …), MAX(…; …), REDONDEAR(…), ABS(…), con «;»
      entre argumentos como en una hoja de cálculo. Vale la primera regla
      que cumpla (por orden). Sin peso del cliente, o sin regla que
      cumpla, vale E. Las reglas de arranque son las que regían
      (LIMITE_PROMEDIO_PESO_KG).
      Cada pesaje guarda con qué regla salió su peso.
   b) Peso del cliente con bruto y tara (de su boleta), informativos; el
      neto del cliente sigue en peso_cliente_kg.
   c) Bono de laboratorio: un monto por lote según cuántos elementos trae
      el material (ZN = 1, ZN-AG = 2, ZN-AG-PB = 3), con tabla con
      vigencia como la del bono de transporte. Se genera al recibir un
      lote de compra con material, queda pendiente en la caja de la sede y
      se paga al productor o a quien venga a cobrar (se anota su nombre).
   d) Los dos bonos son anticipos: v_lote_anticipos suma, por lote, lo
      pagado en anticipos, bonos de transporte y de laboratorio, que la
      liquidación descuenta.
   ===================================================================== */

BEGIN;

