/*
 * Evalúa una fórmula con E, C y D. Antes de ejecutarla se comprueba que
 * solo tenga los símbolos permitidos: no puede llegar a la base otra cosa
 * que números, operadores, paréntesis y las cuatro funciones.
 */
CREATE FUNCTION cargas.evaluar_formula_peso(p_formula text, p_e numeric, p_c numeric)
RETURNS numeric LANGUAGE plpgsql STABLE AS $$
DECLARE
    v text := upper(btrim(COALESCE(p_formula, '')));
    v_resto text;
    r numeric;
BEGIN
    IF v = '' THEN
        RAISE EXCEPTION 'La fórmula está vacía.';
    END IF;
    IF length(v) > 200 THEN
        RAISE EXCEPTION 'La fórmula es demasiado larga (máximo 200 caracteres).';
    END IF;
    v_resto := regexp_replace(v, '\m(MIN|MAX|REDONDEAR|ABS)\M', '', 'g');
    IF v_resto !~ '^[ECD0-9.,;+*/() -]*$' OR v ~ '--|/\*|\*/' THEN
        RAISE EXCEPTION 'La fórmula «%» solo puede usar E, C, D, números, + − * /, paréntesis y MIN, MAX, REDONDEAR, ABS.', p_formula;
    END IF;

    v := replace(v, ',', '.');                                  -- coma decimal
    v := replace(v, ';', ',');                                  -- separador de argumentos
    v := regexp_replace(v, '\mMIN\M', 'LEAST', 'g');
    v := regexp_replace(v, '\mMAX\M', 'GREATEST', 'g');
    v := regexp_replace(v, '\mREDONDEAR\M', 'ROUND', 'g');
    -- Como numeric: con pesos enteros, (E+C)/2 sería una división entera.
    v := regexp_replace(v, '\mE\M', '(' || p_e::text || '::numeric)', 'g');
    v := regexp_replace(v, '\mC\M', '(' || COALESCE(p_c, p_e)::text || '::numeric)', 'g');
    v := regexp_replace(v, '\mD\M', '(' || (COALESCE(p_c, p_e) - p_e)::text || '::numeric)', 'g');

    BEGIN
        EXECUTE 'SELECT (' || v || ')::numeric' INTO r;
    EXCEPTION WHEN OTHERS THEN
        RAISE EXCEPTION 'La fórmula «%» no se puede calcular (revise paréntesis y operadores).', p_formula;
    END;
    IF r IS NULL OR r <= 0 THEN
        RAISE EXCEPTION 'La fórmula «%» da % kg: el peso debe ser mayor que cero.', p_formula, r;
    END IF;
    RETURN round(r, 2);
END $$;

CREATE TABLE cargas.regla_peso (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden          smallint NOT NULL CHECK (orden > 0),
    unidad         varchar(3) NOT NULL DEFAULT 'KG' CHECK (unidad IN ('KG','PCT')),
    desde          numeric(12,2),
    hasta          numeric(12,2),
    formula        varchar(200) NOT NULL,
    descripcion    varchar(150),
    vigente_desde  date NOT NULL,
    vigente_hasta  date,
    registrado_por bigint REFERENCES public.users(id),
    created_at     timestamp(0),
    updated_at     timestamp(0),
    CONSTRAINT ck_regla_rango    CHECK (desde IS NULL OR hasta IS NULL OR hasta > desde),
    CONSTRAINT ck_regla_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta > vigente_desde),
    CONSTRAINT ux_regla_orden    UNIQUE (vigente_desde, orden)
);
COMMENT ON TABLE cargas.regla_peso IS
    'Reglas del peso que vale: si desde < D ≤ hasta (D = C − E, en kg o % de E) vale la fórmula. Vale la primera por orden.';

-- La fórmula se prueba al guardarla: si no calcula, no entra.
CREATE FUNCTION cargas.tg_regla_peso_validar() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.formula := upper(btrim(NEW.formula));
    PERFORM cargas.evaluar_formula_peso(NEW.formula, 10000, 10050);
    PERFORM cargas.evaluar_formula_peso(NEW.formula, 10000, 9950);
    RETURN NEW;
END $$;
CREATE TRIGGER regla_peso_validar
    BEFORE INSERT OR UPDATE OF formula ON cargas.regla_peso
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_regla_peso_validar();

