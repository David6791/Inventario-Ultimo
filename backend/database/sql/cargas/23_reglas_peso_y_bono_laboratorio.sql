CREATE FUNCTION cargas.num_elementos(p_material varchar) RETURNS integer
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN p_material IS NULL OR btrim(p_material) = '' THEN NULL
                ELSE array_length(string_to_array(p_material, '-'), 1) END
$$;

CREATE TABLE cargas.bono_laboratorio_tramo (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num_elementos  smallint NOT NULL CHECK (num_elementos BETWEEN 1 AND 9),
    monto          numeric(10,2) NOT NULL CHECK (monto >= 0),
    moneda         char(3) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB','USD')),
    vigente_desde  date NOT NULL,
    vigente_hasta  date,
    registrado_por bigint REFERENCES public.users(id),
    created_at     timestamp(0),
    updated_at     timestamp(0),
    CONSTRAINT ck_blt_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta > vigente_desde),
    CONSTRAINT ex_blt_solape EXCLUDE USING gist (
        num_elementos WITH =,
        daterange(vigente_desde, vigente_hasta, '[)') WITH &&)
);
COMMENT ON TABLE cargas.bono_laboratorio_tramo IS 'Monto del bono de laboratorio según cuántos elementos trae el material del lote.';

CREATE FUNCTION cargas.tramo_laboratorio(p_num integer, p_fecha date) RETURNS bigint
LANGUAGE sql STABLE AS $$
    SELECT id FROM cargas.bono_laboratorio_tramo
     WHERE num_elementos = p_num AND daterange(vigente_desde, vigente_hasta, '[)') @> p_fecha
$$;

CREATE TABLE cargas.bono_laboratorio (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id             bigint NOT NULL UNIQUE REFERENCES cargas.lote(id),
    tramo_id            bigint NOT NULL REFERENCES cargas.bono_laboratorio_tramo(id),
    num_elementos       smallint NOT NULL,
    monto               numeric(10,2) NOT NULL CHECK (monto >= 0),
    moneda              char(3) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB','USD')),
    estado              varchar(10) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','PAGADO','ANULADO')),
    beneficiario_nombre varchar(150),
    beneficiario_ci     varchar(15),
    movimiento_caja_id  bigint UNIQUE REFERENCES caja.movimiento(id),
    registrado_por      bigint NOT NULL REFERENCES public.users(id),
    anulado_por         bigint REFERENCES public.users(id),
    anulado_en          timestamp(0),
    motivo_anulacion    varchar(250),
    created_at          timestamp(0),
    updated_at          timestamp(0),
    CONSTRAINT ck_bonolab_pagado  CHECK ((estado = 'PAGADO') = (movimiento_caja_id IS NOT NULL)),
    CONSTRAINT ck_bonolab_cobra   CHECK (estado <> 'PAGADO' OR length(btrim(COALESCE(beneficiario_nombre, ''))) >= 3),
    CONSTRAINT ck_bonolab_anulado CHECK (estado <> 'ANULADO' OR (anulado_por IS NOT NULL AND anulado_en IS NOT NULL AND motivo_anulacion IS NOT NULL))
);
COMMENT ON TABLE cargas.bono_laboratorio IS
    'Bono para los ensayos de laboratorio de un lote de compra. Es un anticipo: la liquidación lo descuenta. Lo cobra el productor u otra persona (se anota).';

CREATE FUNCTION cargas.tg_bono_laboratorio_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    l cargas.lote; t cargas.bono_laboratorio_tramo;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los bonos de laboratorio no se eliminan: se anulan con motivo.';
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT * INTO l FROM cargas.lote WHERE id = NEW.lote_id;
        IF l.origen <> 'COMPRA' OR l.estado IN ('ANULADO','LIQUIDADO') THEN
            RAISE EXCEPTION 'El lote % no recibe bono de laboratorio (es de producción propia o está %).', l.codigo, l.estado;
        END IF;
        NEW.num_elementos := cargas.num_elementos(l.material);
        IF NEW.num_elementos IS NULL THEN
            RAISE EXCEPTION 'El lote % no tiene material: no se sabe cuántos elementos ensayar.', l.codigo;
        END IF;
        SELECT * INTO t FROM cargas.bono_laboratorio_tramo
         WHERE id = cargas.tramo_laboratorio(NEW.num_elementos, l.fecha_recepcion::date);
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No hay monto de bono de laboratorio vigente para % elemento(s) al %.', NEW.num_elementos, l.fecha_recepcion::date;
        END IF;
        NEW.tramo_id := t.id;
        NEW.monto  := t.monto;                    -- sale de la tabla, no se digita
        NEW.moneda := t.moneda;
        NEW.estado := 'PENDIENTE';
        NEW.movimiento_caja_id := NULL;
        RETURN NEW;
    END IF;

    -- UPDATE
    IF (NEW.lote_id, NEW.tramo_id, NEW.num_elementos, NEW.monto, NEW.moneda, NEW.registrado_por)
       IS DISTINCT FROM (OLD.lote_id, OLD.tramo_id, OLD.num_elementos, OLD.monto, OLD.moneda, OLD.registrado_por) THEN
        RAISE EXCEPTION 'Los datos de un bono de laboratorio no se modifican.';
    END IF;
    IF OLD.estado <> 'PENDIENTE' AND (NEW.beneficiario_nombre, NEW.beneficiario_ci)
                                     IS DISTINCT FROM (OLD.beneficiario_nombre, OLD.beneficiario_ci) THEN
        RAISE EXCEPTION 'Quién cobró el bono de laboratorio no se cambia.';
    END IF;
    IF NEW.estado <> OLD.estado THEN
        IF NOT (OLD.estado = 'PENDIENTE' AND NEW.estado IN ('PAGADO','ANULADO')) THEN
            RAISE EXCEPTION 'Transición no permitida para el bono de laboratorio: % → %.', OLD.estado, NEW.estado;
        END IF;
        IF NEW.estado = 'PAGADO' THEN
            PERFORM cargas.validar_movimiento_caja(NEW.movimiento_caja_id, 'EGRESO', 'CARGAS_BONO_LAB',
                                                   NEW.monto, NEW.moneda, 'el bono de laboratorio');
        END IF;
    ELSIF NEW.movimiento_caja_id IS DISTINCT FROM OLD.movimiento_caja_id THEN
        RAISE EXCEPTION 'El comprobante de pago del bono de laboratorio no se cambia.';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER bono_laboratorio_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.bono_laboratorio
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_bono_laboratorio_control();

-- Al recibir un lote de compra con material, su bono queda pendiente (si hay tabla).
CREATE FUNCTION cargas.tg_lote_bono_laboratorio() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.origen = 'COMPRA' AND NEW.material IS NOT NULL
       AND cargas.tramo_laboratorio(cargas.num_elementos(NEW.material), NEW.fecha_recepcion::date) IS NOT NULL THEN
        INSERT INTO cargas.bono_laboratorio (lote_id, tramo_id, num_elementos, monto, registrado_por, created_at, updated_at)
        VALUES (NEW.id, 0, 0, 0, NEW.registrado_por, now(), now());     -- tramo y monto los pone el control
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER lote_bono_laboratorio
    AFTER INSERT ON cargas.lote
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_lote_bono_laboratorio();

-- Lote anulado: también su bono de laboratorio pendiente.
CREATE OR REPLACE FUNCTION cargas.tg_lote_anulado_bonos() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado = 'ANULADO' AND OLD.estado <> 'ANULADO' THEN
        UPDATE cargas.bono_transporte b
           SET estado = 'ANULADO', anulado_por = cargas.usuario_actual(), anulado_en = now(),
               motivo_anulacion = left('Lote anulado: ' || NEW.motivo_anulacion, 250), updated_at = now()
          FROM cargas.pesaje p
         WHERE p.id = b.pesaje_id AND p.lote_id = NEW.id AND b.estado = 'PENDIENTE';
        UPDATE cargas.bono_laboratorio
           SET estado = 'ANULADO', anulado_por = cargas.usuario_actual(), anulado_en = now(),
               motivo_anulacion = left('Lote anulado: ' || NEW.motivo_anulacion, 250), updated_at = now()
         WHERE lote_id = NEW.id AND estado = 'PENDIENTE';
    END IF;
    RETURN NULL;
END $$;

/* Publicar la tabla del bono de laboratorio (como la de transporte). */
CREATE FUNCTION cargas.publicar_tramos_laboratorio(p_desde date, p_tramos jsonb, p_usuario bigint)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    v_n integer;
BEGIN
    IF p_desde IS NULL OR p_desde < current_date THEN
        RAISE EXCEPTION 'La tabla del bono de laboratorio rige desde hoy o una fecha futura: los bonos ya calculados no cambian.';
    END IF;
    IF p_tramos IS NULL OR jsonb_array_length(p_tramos) = 0 THEN
        RAISE EXCEPTION 'La tabla del bono de laboratorio necesita al menos una fila.';
    END IF;
    IF EXISTS (SELECT 1 FROM cargas.bono_laboratorio b JOIN cargas.bono_laboratorio_tramo t ON t.id = b.tramo_id
                WHERE t.vigente_desde >= p_desde) THEN
        RAISE EXCEPTION 'Ya hay bonos de laboratorio calculados con la tabla que empieza el % o después: publique con otra fecha.', p_desde;
    END IF;
    DELETE FROM cargas.bono_laboratorio_tramo WHERE vigente_desde >= p_desde;
    UPDATE cargas.bono_laboratorio_tramo SET vigente_hasta = p_desde, updated_at = now()
     WHERE vigente_desde < p_desde AND (vigente_hasta IS NULL OR vigente_hasta > p_desde);
    INSERT INTO cargas.bono_laboratorio_tramo (num_elementos, monto, moneda, vigente_desde, registrado_por, created_at, updated_at)
    SELECT (t->>'num_elementos')::smallint, (t->>'monto')::numeric, COALESCE(NULLIF(t->>'moneda', ''), 'BOB'), p_desde, p_usuario, now(), now()
      FROM jsonb_array_elements(p_tramos) t;
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RETURN v_n;
END $$;

