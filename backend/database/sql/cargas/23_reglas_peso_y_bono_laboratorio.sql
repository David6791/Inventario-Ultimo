    ADD CONSTRAINT ck_pesaje_cliente_bruto_tara CHECK (
        peso_cliente_bruto_kg IS NULL OR peso_cliente_tara_kg IS NULL OR peso_cliente_bruto_kg > peso_cliente_tara_kg);
COMMENT ON COLUMN cargas.pesaje.peso_cliente_bruto_kg IS 'Bruto de la boleta del cliente (informativo; su neto está en peso_cliente_kg).';
COMMENT ON COLUMN cargas.pesaje.peso_cliente_tara_kg IS 'Tara de la boleta del cliente (informativo).';

-- Bruto y tara del cliente no se cambian sueltos; si se corrige el peso del
-- cliente con la función, dejan de valer y se limpian.
CREATE FUNCTION cargas.tg_pesaje_cliente_bruto_tara() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF COALESCE(current_setting('cargas.corrigiendo_peso_cliente', true), '') = 'si' THEN
        IF (NEW.peso_cliente_kg, NEW.peso_cliente_tipo) IS DISTINCT FROM (OLD.peso_cliente_kg, OLD.peso_cliente_tipo) THEN
            NEW.peso_cliente_bruto_kg := NULL;
            NEW.peso_cliente_tara_kg := NULL;
        END IF;
    ELSIF (NEW.peso_cliente_bruto_kg, NEW.peso_cliente_tara_kg) IS DISTINCT FROM (OLD.peso_cliente_bruto_kg, OLD.peso_cliente_tara_kg) THEN
        RAISE EXCEPTION 'Un pesaje registrado no se corrige: se anula y se registra otro.';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER pesaje_cliente_bruto_tara
    BEFORE UPDATE ON cargas.pesaje
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_pesaje_cliente_bruto_tara();

