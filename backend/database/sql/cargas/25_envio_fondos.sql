/* =====================================================================
   25. ENVÍO DE DINERO DE LA SEDE CENTRAL A LAS CAJAS
   ---------------------------------------------------------------------
   La caja de la sede central (centro de costo es_central) envía dinero a
   la caja de otro centro (para abrirla o reponerla). El envío pasa por:

       EN_TRANSITO  ── el cajero de destino confirma ──►  RECIBIDO
            └──────── quien envió lo anula ───────────►  ANULADO

   - Al enviar: egreso ENVIO_FONDOS en la caja central (con control de
     saldo, como cualquier egreso). El dinero queda «en tránsito».
   - Al recibir: ingreso RECEPCION_FONDOS en la caja de destino, por el
     mismo monto y moneda.
   - Al anular (solo en tránsito): ingreso REINTEGRO_FONDOS en la caja
     central: el dinero vuelve.
   Los tres comprobantes quedan vinculados al envío; no se registran a mano
   ni se anulan desde caja.
   ===================================================================== */

BEGIN;

INSERT INTO caja.concepto (codigo, nombre, tipo, origen, created_at, updated_at) VALUES
    ('ENVIO_FONDOS',     'Envío de dinero a otra caja',          'EGRESO',  'FONDOS_ENVIO',      now(), now()),
    ('RECEPCION_FONDOS', 'Dinero recibido de la sede central',   'INGRESO', 'FONDOS_RECEPCION',  now(), now()),
    ('REINTEGRO_FONDOS', 'Reintegro de envío anulado',           'INGRESO', 'FONDOS_REINTEGRO',  now(), now())
ON CONFLICT (codigo) DO NOTHING;
-- Mover dinero entre cajas no es un gasto: no pasa por solicitudes.
UPDATE caja.concepto SET exento_aprobacion = true WHERE codigo = 'ENVIO_FONDOS';

CREATE TABLE caja.envio_fondos (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero                  varchar(30) UNIQUE,
    caja_origen_id          bigint NOT NULL REFERENCES caja.caja(id),
    caja_destino_id         bigint NOT NULL REFERENCES caja.caja(id),
    monto                   numeric(14,2) NOT NULL CHECK (monto > 0),
    moneda                  char(3) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB','USD')),
    motivo                  varchar(250) NOT NULL CHECK (length(btrim(motivo)) >= 5),
    entregado_a             varchar(150),
    estado                  varchar(11) NOT NULL DEFAULT 'EN_TRANSITO' CHECK (estado IN ('EN_TRANSITO','RECIBIDO','ANULADO')),
    movimiento_envio_id     bigint NOT NULL UNIQUE REFERENCES caja.movimiento(id),
    movimiento_recepcion_id bigint UNIQUE REFERENCES caja.movimiento(id),
    movimiento_reintegro_id bigint UNIQUE REFERENCES caja.movimiento(id),
    enviado_por             bigint NOT NULL REFERENCES public.users(id),
    enviado_en              timestamp(0) NOT NULL DEFAULT now(),
    recibido_por            bigint REFERENCES public.users(id),
    recibido_en             timestamp(0),
    anulado_por             bigint REFERENCES public.users(id),
    anulado_en              timestamp(0),
    motivo_anulacion        varchar(250),
    created_at              timestamp(0),
    updated_at              timestamp(0),
    CONSTRAINT ck_envio_cajas     CHECK (caja_origen_id <> caja_destino_id),
    CONSTRAINT ck_envio_recibido  CHECK ((estado = 'RECIBIDO') = (movimiento_recepcion_id IS NOT NULL AND recibido_por IS NOT NULL)),
    CONSTRAINT ck_envio_anulado   CHECK ((estado = 'ANULADO') = (movimiento_reintegro_id IS NOT NULL AND anulado_por IS NOT NULL
                                                                 AND length(btrim(COALESCE(motivo_anulacion, ''))) >= 5))
);
CREATE INDEX ix_envio_destino ON caja.envio_fondos (caja_destino_id, estado);
CREATE INDEX ix_envio_origen  ON caja.envio_fondos (caja_origen_id, estado);
COMMENT ON TABLE caja.envio_fondos IS
    'Dinero que la caja de la sede central envía a otra caja: en tránsito hasta que el cajero de destino lo recibe.';

/* El comprobante debe ser de esa caja, vigente, del concepto, monto y moneda del envío. */
CREATE FUNCTION caja.validar_mov_envio(p_mov bigint, p_caja bigint, p_codigo varchar, p_monto numeric, p_moneda char, p_que varchar)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    m caja.movimiento; v_codigo varchar;
BEGIN
    SELECT * INTO m FROM caja.movimiento WHERE id = p_mov;
    SELECT codigo INTO v_codigo FROM caja.concepto WHERE id = m.concepto_id;
    IF NOT FOUND OR m.caja_id <> p_caja OR v_codigo <> p_codigo OR m.estado <> 'VIGENTE'
       OR m.monto <> p_monto OR m.moneda <> p_moneda THEN
        RAISE EXCEPTION 'El comprobante de % no corresponde al envío (caja, concepto, monto o moneda).', p_que;
    END IF;
END $$;

CREATE FUNCTION caja.tg_envio_fondos_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    o caja.caja; d caja.caja; v_central boolean;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los envíos de dinero no se eliminan: se anulan con motivo.';
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT * INTO o FROM caja.caja WHERE id = NEW.caja_origen_id;
        SELECT * INTO d FROM caja.caja WHERE id = NEW.caja_destino_id;
        SELECT EXISTS (SELECT 1 FROM activos.centro_costo WHERE almacen_id = o.almacen_id AND es_central AND activo) INTO v_central;
        IF NOT v_central THEN
            RAISE EXCEPTION 'La caja % no es de la sede central: solo la sede central envía dinero a las cajas.', o.codigo;
        END IF;
        IF NOT d.activa THEN
            RAISE EXCEPTION 'La caja % está inactiva: no recibe envíos.', d.codigo;
        END IF;
        PERFORM caja.validar_mov_envio(NEW.movimiento_envio_id, NEW.caja_origen_id, 'ENVIO_FONDOS', NEW.monto, NEW.moneda, 'envío');
        NEW.estado := 'EN_TRANSITO';
        NEW.movimiento_recepcion_id := NULL; NEW.movimiento_reintegro_id := NULL;
        NEW.recibido_por := NULL; NEW.recibido_en := NULL; NEW.anulado_por := NULL; NEW.anulado_en := NULL;
        RETURN NEW;
    END IF;

    IF (NEW.caja_origen_id, NEW.caja_destino_id, NEW.monto, NEW.moneda, NEW.movimiento_envio_id, NEW.enviado_por, NEW.motivo)
       IS DISTINCT FROM (OLD.caja_origen_id, OLD.caja_destino_id, OLD.monto, OLD.moneda, OLD.movimiento_envio_id, OLD.enviado_por, OLD.motivo) THEN
        RAISE EXCEPTION 'Los datos de un envío de dinero no se modifican.';
    END IF;
    IF NEW.estado <> OLD.estado THEN
        IF OLD.estado <> 'EN_TRANSITO' THEN
            RAISE EXCEPTION 'El envío % ya está %.', OLD.numero, OLD.estado;
        END IF;
        IF NEW.estado = 'RECIBIDO' THEN
            PERFORM caja.validar_mov_envio(NEW.movimiento_recepcion_id, NEW.caja_destino_id, 'RECEPCION_FONDOS', NEW.monto, NEW.moneda, 'recepción');
            NEW.recibido_en := COALESCE(NEW.recibido_en, now());
        ELSIF NEW.estado = 'ANULADO' THEN
            PERFORM caja.validar_mov_envio(NEW.movimiento_reintegro_id, NEW.caja_origen_id, 'REINTEGRO_FONDOS', NEW.monto, NEW.moneda, 'reintegro');
            NEW.anulado_en := COALESCE(NEW.anulado_en, now());
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER envio_fondos_control
    BEFORE INSERT OR UPDATE OR DELETE ON caja.envio_fondos
    FOR EACH ROW EXECUTE FUNCTION caja.tg_envio_fondos_control();

CREATE FUNCTION caja.tg_envio_fondos_numero() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE caja.envio_fondos SET numero = 'ENV-' || to_char(NEW.enviado_en, 'YYYY') || '-' || lpad(NEW.id::text, 5, '0')
     WHERE id = NEW.id;
    RETURN NULL;
END $$;
CREATE TRIGGER envio_fondos_numero
    AFTER INSERT ON caja.envio_fondos
    FOR EACH ROW EXECUTE FUNCTION caja.tg_envio_fondos_numero();

-- Un comprobante de envío, recepción o reintegro siempre queda vinculado a su envío.
CREATE FUNCTION caja.tg_mov_fondos_vinculado() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_origen varchar;
BEGIN
    SELECT origen INTO v_origen FROM caja.concepto WHERE id = NEW.concepto_id;
    IF v_origen = 'FONDOS_ENVIO' AND NOT EXISTS (SELECT 1 FROM caja.envio_fondos WHERE movimiento_envio_id = NEW.id)
       OR v_origen = 'FONDOS_RECEPCION' AND NOT EXISTS (SELECT 1 FROM caja.envio_fondos WHERE movimiento_recepcion_id = NEW.id)
       OR v_origen = 'FONDOS_REINTEGRO' AND NOT EXISTS (SELECT 1 FROM caja.envio_fondos WHERE movimiento_reintegro_id = NEW.id) THEN
        RAISE EXCEPTION 'El comprobante % mueve dinero entre cajas pero no está vinculado a ningún envío.', NEW.numero;
    END IF;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER caja_mov_fondos_vinculado
    AFTER INSERT ON caja.movimiento
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION caja.tg_mov_fondos_vinculado();

CREATE FUNCTION caja.tg_mov_fondos_no_anular() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado = 'ANULADO' AND OLD.estado = 'VIGENTE' AND EXISTS (
           SELECT 1 FROM caja.envio_fondos
            WHERE NEW.id IN (movimiento_envio_id, movimiento_recepcion_id, movimiento_reintegro_id)) THEN
        RAISE EXCEPTION 'El comprobante % es de un envío de dinero entre cajas: no se anula desde caja. Anule el envío (si sigue en tránsito).', NEW.numero;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER caja_mov_fondos_no_anular
    BEFORE UPDATE OF estado ON caja.movimiento
    FOR EACH ROW EXECUTE FUNCTION caja.tg_mov_fondos_no_anular();

COMMIT;
