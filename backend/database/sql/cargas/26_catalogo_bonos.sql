-- Tramos de transporte: mismo id (los bonos ya calculados los referencian).
INSERT INTO cargas.tipo_bono_tramo (id, tipo_bono_id, etiqueta, desde, hasta, monto, moneda,
                                    vigente_desde, vigente_hasta, registrado_por, created_at, updated_at)
SELECT t.id, (SELECT id FROM cargas.tipo_bono WHERE codigo = 'TRANSPORTE'), t.tipo_vehiculo,
       t.peso_desde_kg, t.peso_hasta_kg, t.monto, t.moneda, t.vigente_desde, t.vigente_hasta, t.registrado_por,
       t.created_at, t.updated_at
  FROM cargas.bono_transporte_tramo t;
