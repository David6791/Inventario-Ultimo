/* =====================================================================
   26. CATÁLOGO DE BONOS
   ---------------------------------------------------------------------
   Todos los bonos que paga la caja de un acopio salen de un catálogo
   (cargas.tipo_bono). Cada tipo dice:

     - cómo se calcula:  TRAMOS_PESO   según el peso del camión (báscula)
                         POR_TONELADA  monto por tonelada del camión
                         POR_ELEMENTOS según los elementos del material
                         FIJO          el mismo monto en cada lote
                         MANUAL        el monto se anota en cada lote
     - si es ANTICIPO (la liquidación lo descuenta) o PREMIO (no se descuenta),
     - quién cobra por defecto (PRODUCTOR o CHOFER) y si puede cobrar otra
       persona (se anota su nombre en caja),
     - a qué lotes aplica (compra, producción propia o todos; o una serie).

   Los montos salen de tablas con vigencia (cargas.tipo_bono_tramo), como
   antes las de transporte y laboratorio: publicar una tabla nueva no cambia
   los bonos ya calculados.

   Los bonos nacen solos al recibir: los de peso con el pesaje de báscula de
   ingreso; los demás con el lote. Los MANUALES se agregan en la ficha.

   Los bonos de transporte y de laboratorio pasan al catálogo (con sus
   tablas, sus bonos y sus pagos) y reemplazan a sus tablas propias.
   ===================================================================== */

BEGIN;

-- ---------------------------------------------------------------------
-- 1. Catálogo
-- ---------------------------------------------------------------------
CREATE TABLE cargas.tipo_bono (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        varchar(20)  NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9_]{2,20}$'),
    nombre        varchar(80)  NOT NULL CHECK (length(btrim(nombre)) >= 3),
    descripcion   varchar(250),
    calculo       varchar(13)  NOT NULL CHECK (calculo IN ('TRAMOS_PESO','POR_TONELADA','POR_ELEMENTOS','FIJO','MANUAL')),
    naturaleza    varchar(8)   NOT NULL DEFAULT 'ANTICIPO' CHECK (naturaleza IN ('ANTICIPO','PREMIO')),
    cobra         varchar(9)   NOT NULL DEFAULT 'PRODUCTOR' CHECK (cobra IN ('PRODUCTOR','CHOFER')),
    permite_otro  boolean      NOT NULL DEFAULT true,
    aplica_a      varchar(6)   NOT NULL DEFAULT 'COMPRA' CHECK (aplica_a IN ('TODOS','COMPRA','PROPIA')),
    serie_id      bigint       REFERENCES cargas.serie_lote(id),
    concepto_id   bigint       NOT NULL UNIQUE REFERENCES caja.concepto(id),
    sistema       boolean      NOT NULL DEFAULT false,
    activo        boolean      NOT NULL DEFAULT true,
    orden         smallint     NOT NULL DEFAULT 0,
    created_at    timestamp(0),
    updated_at    timestamp(0)
);
CREATE UNIQUE INDEX ux_tipo_bono_nombre ON cargas.tipo_bono (upper(btrim(nombre)));
COMMENT ON TABLE cargas.tipo_bono IS
    'Catálogo de bonos que paga la caja del acopio: cómo se calculan, quién cobra y si la liquidación los descuenta.';
COMMENT ON COLUMN cargas.tipo_bono.naturaleza IS 'ANTICIPO: la liquidación lo descuenta. PREMIO: no se descuenta.';
COMMENT ON COLUMN cargas.tipo_bono.permite_otro IS 'En caja se puede anotar a otra persona que cobra por cuenta del productor o chofer.';
COMMENT ON COLUMN cargas.tipo_bono.sistema IS 'Transporte y laboratorio: no cambian de código ni de cálculo.';

CREATE TABLE cargas.tipo_bono_tramo (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_bono_id   bigint NOT NULL REFERENCES cargas.tipo_bono(id),
    etiqueta       varchar(30),
    desde          numeric(12,2) NOT NULL DEFAULT 0 CHECK (desde >= 0),
    hasta          numeric(12,2),
    monto          numeric(10,2) NOT NULL CHECK (monto >= 0),
    moneda         char(3) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB','USD')),
    vigente_desde  date NOT NULL,
    vigente_hasta  date,
    registrado_por bigint REFERENCES public.users(id),
    created_at     timestamp(0),
    updated_at     timestamp(0),
    CONSTRAINT ck_tbt_rango    CHECK (hasta IS NULL OR hasta > desde),
    CONSTRAINT ck_tbt_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta > vigente_desde),
    CONSTRAINT ex_tbt_solape EXCLUDE USING gist (
        tipo_bono_id WITH =,
        numrange(desde, hasta, '[)') WITH &&,
        daterange(vigente_desde, vigente_hasta, '[)') WITH &&)
);
CREATE INDEX ix_tbt_tipo ON cargas.tipo_bono_tramo (tipo_bono_id, vigente_desde);
COMMENT ON TABLE cargas.tipo_bono_tramo IS
    'Montos de cada bono con vigencia. Peso: tramos [desde, hasta) en kg. Elementos: desde = cantidad. Fijo y por tonelada: una fila.';

CREATE FUNCTION cargas.tramo_tipo_bono(p_tipo bigint, p_base numeric, p_fecha date) RETURNS bigint
LANGUAGE sql STABLE AS $$
    SELECT id FROM cargas.tipo_bono_tramo
     WHERE tipo_bono_id = p_tipo
       AND numrange(desde, hasta, '[)') @> COALESCE(p_base, 0)
       AND daterange(vigente_desde, vigente_hasta, '[)') @> p_fecha
$$;

CREATE TABLE cargas.bono (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_bono_id        bigint NOT NULL REFERENCES cargas.tipo_bono(id),
    lote_id             bigint NOT NULL REFERENCES cargas.lote(id),
    pesaje_id           bigint REFERENCES cargas.pesaje(id),
    tramo_id            bigint REFERENCES cargas.tipo_bono_tramo(id),
    base                numeric(12,2),
    monto               numeric(10,2) NOT NULL CHECK (monto >= 0),
    moneda              char(3) NOT NULL DEFAULT 'BOB' CHECK (moneda IN ('BOB','USD')),
    naturaleza          varchar(8) NOT NULL CHECK (naturaleza IN ('ANTICIPO','PREMIO')),
    estado              varchar(10) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','PAGADO','ANULADO')),
    beneficiario_nombre varchar(150),
    beneficiario_ci     varchar(15),
    observacion         varchar(250),
    movimiento_caja_id  bigint UNIQUE REFERENCES caja.movimiento(id),
    registrado_por      bigint NOT NULL REFERENCES public.users(id),
    anulado_por         bigint REFERENCES public.users(id),
    anulado_en          timestamp(0),
    motivo_anulacion    varchar(250),
    created_at          timestamp(0),
    updated_at          timestamp(0),
    CONSTRAINT ck_bono_cat_pagado  CHECK ((estado = 'PAGADO') = (movimiento_caja_id IS NOT NULL)),
    CONSTRAINT ck_bono_cat_cobra   CHECK (estado <> 'PAGADO' OR length(btrim(COALESCE(beneficiario_nombre, ''))) >= 3),
    CONSTRAINT ck_bono_cat_anulado CHECK (estado <> 'ANULADO' OR (anulado_por IS NOT NULL AND anulado_en IS NOT NULL AND motivo_anulacion IS NOT NULL))
);
CREATE INDEX ix_bono_lote   ON cargas.bono (lote_id);
CREATE INDEX ix_bono_pesaje ON cargas.bono (pesaje_id);
CREATE INDEX ix_bono_estado ON cargas.bono (estado, tipo_bono_id);
-- Un bono de cada tipo por lote (o por pesaje, en los de peso), salvo los anulados.
CREATE UNIQUE INDEX ux_bono_uno_por_tipo ON cargas.bono (tipo_bono_id, lote_id, COALESCE(pesaje_id, 0))
    WHERE estado <> 'ANULADO';
COMMENT ON TABLE cargas.bono IS
    'Bono de un lote (o de su pesaje de báscula) según el catálogo. Se paga por la caja del acopio con un egreso vinculado.';
COMMENT ON COLUMN cargas.bono.base IS 'Con qué se calculó: kg del camión o cantidad de elementos.';
COMMENT ON COLUMN cargas.bono.naturaleza IS 'Copia de la del tipo al nacer: ANTICIPO se descuenta en la liquidación.';

