-- Cada bono nuevo trae su concepto de caja (egreso, solo lo genera cargas).
CREATE FUNCTION cargas.tg_tipo_bono_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_concepto bigint;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los bonos del catálogo no se eliminan: se desactivan.';
    END IF;
    NEW.nombre := btrim(NEW.nombre);

    IF TG_OP = 'INSERT' THEN
        NEW.sistema := COALESCE(NEW.sistema, false);
        IF NEW.concepto_id IS NULL THEN
            INSERT INTO caja.concepto (codigo, nombre, tipo, origen, created_at, updated_at)
            VALUES ('BONO_' || NEW.codigo, 'Pago de ' || lower(left(NEW.nombre, 1)) || substr(NEW.nombre, 2),
                    'EGRESO', 'CARGAS_BONO', now(), now())
            RETURNING id INTO v_concepto;
            NEW.concepto_id := v_concepto;
        END IF;
        RETURN NEW;
    END IF;

    IF NEW.sistema IS DISTINCT FROM OLD.sistema OR NEW.concepto_id <> OLD.concepto_id THEN
        RAISE EXCEPTION 'El bono «%»: su concepto de caja y si es del sistema no se cambian.', OLD.nombre;
    END IF;
    IF NEW.codigo <> OLD.codigo AND (OLD.sistema OR EXISTS (SELECT 1 FROM cargas.bono WHERE tipo_bono_id = OLD.id)) THEN
        RAISE EXCEPTION 'El bono «%» ya se usa: su código no se cambia.', OLD.nombre;
    END IF;
    IF NEW.calculo <> OLD.calculo AND (OLD.sistema
            OR EXISTS (SELECT 1 FROM cargas.bono WHERE tipo_bono_id = OLD.id)
            OR EXISTS (SELECT 1 FROM cargas.tipo_bono_tramo WHERE tipo_bono_id = OLD.id)) THEN
        RAISE EXCEPTION 'El bono «%» ya tiene tabla de montos o bonos calculados: su forma de cálculo no se cambia. Cree otro bono.', OLD.nombre;
    END IF;
    IF NEW.nombre <> OLD.nombre THEN
        UPDATE caja.concepto SET nombre = 'Pago de ' || lower(left(NEW.nombre, 1)) || substr(NEW.nombre, 2), updated_at = now()
         WHERE id = NEW.concepto_id AND NOT OLD.sistema;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tipo_bono_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.tipo_bono
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_tipo_bono_control();

-- ¿El bono aplica a este lote?
CREATE FUNCTION cargas.bono_aplica(t cargas.tipo_bono, l cargas.lote) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT (t.aplica_a = 'TODOS' OR t.aplica_a = l.origen)
       AND (t.serie_id IS NULL OR t.serie_id = l.serie_id)
$$;

/* Publicar la tabla de montos de un bono.
   p_tramos: peso    [{"etiqueta": "TONKA", "desde": 500, "hasta": 7000, "monto": 50}, ...]
             elementos [{"desde": 2, "monto": 40}, ...]
             fijo / por tonelada [{"monto": 30}] */
CREATE FUNCTION cargas.publicar_tramos_tipo_bono(p_tipo bigint, p_desde date, p_tramos jsonb, p_usuario bigint)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    t cargas.tipo_bono; v_n integer;
BEGIN
    SELECT * INTO t FROM cargas.tipo_bono WHERE id = p_tipo;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El bono % no existe.', p_tipo;
    END IF;
    IF t.calculo = 'MANUAL' THEN
        RAISE EXCEPTION 'El bono «%» es de monto manual: no lleva tabla.', t.nombre;
    END IF;
    IF p_desde IS NULL OR p_desde < current_date THEN
        RAISE EXCEPTION 'La tabla del bono rige desde hoy o una fecha futura: los bonos ya calculados no cambian.';
    END IF;
    IF p_tramos IS NULL OR jsonb_array_length(p_tramos) = 0 THEN
        RAISE EXCEPTION 'La tabla del bono «%» necesita al menos una fila.', t.nombre;
    END IF;
    IF t.calculo IN ('FIJO','POR_TONELADA') AND jsonb_array_length(p_tramos) <> 1 THEN
        RAISE EXCEPTION 'El bono «%» lleva un solo monto.', t.nombre;
    END IF;
    IF EXISTS (SELECT 1 FROM cargas.bono b JOIN cargas.tipo_bono_tramo r ON r.id = b.tramo_id
                WHERE r.tipo_bono_id = p_tipo AND r.vigente_desde >= p_desde) THEN
        RAISE EXCEPTION 'Ya hay bonos «%» calculados con la tabla que empieza el % o después: publique con otra fecha.', t.nombre, p_desde;
    END IF;

    DELETE FROM cargas.tipo_bono_tramo WHERE tipo_bono_id = p_tipo AND vigente_desde >= p_desde;
    UPDATE cargas.tipo_bono_tramo SET vigente_hasta = p_desde, updated_at = now()
     WHERE tipo_bono_id = p_tipo AND vigente_desde < p_desde AND (vigente_hasta IS NULL OR vigente_hasta > p_desde);

    INSERT INTO cargas.tipo_bono_tramo (tipo_bono_id, etiqueta, desde, hasta, monto, moneda, vigente_desde, registrado_por, created_at, updated_at)
    SELECT p_tipo,
           NULLIF(upper(btrim(COALESCE(r->>'etiqueta', ''))), ''),
           CASE WHEN t.calculo IN ('FIJO','POR_TONELADA') THEN 0 ELSE (r->>'desde')::numeric END,
           CASE t.calculo WHEN 'TRAMOS_PESO'   THEN NULLIF(r->>'hasta', '')::numeric
                          WHEN 'POR_ELEMENTOS' THEN (r->>'desde')::numeric + 1 END,
           (r->>'monto')::numeric, COALESCE(NULLIF(r->>'moneda', ''), 'BOB'), p_desde, p_usuario, now(), now()
      FROM jsonb_array_elements(p_tramos) r;
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RETURN v_n;
END $$;

-- ---------------------------------------------------------------------
-- 4. Reglas del bono
-- ---------------------------------------------------------------------
CREATE FUNCTION cargas.tg_bono_catalogo_control() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    t cargas.tipo_bono; l cargas.lote; p cargas.pesaje; r cargas.tipo_bono_tramo;
    v_fecha date; v_origen varchar; v_pr record;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Los bonos no se eliminan: se anulan con motivo.';
    END IF;

    IF TG_OP = 'INSERT' THEN
        SELECT * INTO t FROM cargas.tipo_bono WHERE id = NEW.tipo_bono_id;
        SELECT * INTO l FROM cargas.lote WHERE id = NEW.lote_id;
        IF NOT t.activo THEN
            RAISE EXCEPTION 'El bono «%» está desactivado en el catálogo.', t.nombre;
        END IF;
        IF l.estado IN ('ANULADO','LIQUIDADO') THEN
            RAISE EXCEPTION 'El lote % está %: ya no recibe bonos.', l.codigo, l.estado;
        END IF;
        IF NOT cargas.bono_aplica(t, l) THEN
            RAISE EXCEPTION 'El bono «%» no aplica al lote % (es para %).', t.nombre, l.codigo,
                CASE WHEN t.serie_id IS NOT NULL THEN 'otra serie' WHEN t.aplica_a = 'COMPRA' THEN 'lotes de compra' ELSE 'producción propia' END;
        END IF;
        v_fecha := l.fecha_recepcion::date;

        IF t.calculo IN ('TRAMOS_PESO','POR_TONELADA') THEN
            SELECT * INTO p FROM cargas.pesaje WHERE id = NEW.pesaje_id;
            IF NOT FOUND OR p.lote_id <> l.id OR p.tipo <> 'INGRESO' OR p.anulado
               OR p.modalidad <> 'BASCULA' OR p.pesaje_viaje_id IS NOT NULL THEN
                RAISE EXCEPTION 'El bono «%» va con un pesaje de báscula de ingreso vigente del lote.', t.nombre;
            END IF;
            NEW.base := p.peso_bruto_kg - p.tara_kg;          -- el camión completo (con sacos, si es mixta)
            v_fecha := p.fecha::date;
        ELSE
            IF NEW.pesaje_id IS NOT NULL THEN
                RAISE EXCEPTION 'El bono «%» es del lote, no de un pesaje.', t.nombre;
            END IF;
            NEW.base := CASE WHEN t.calculo = 'POR_ELEMENTOS' THEN cargas.num_elementos(l.material) END;
            IF t.calculo = 'POR_ELEMENTOS' AND NEW.base IS NULL THEN
                RAISE EXCEPTION 'El lote % no tiene material: no se sabe cuántos elementos ensayar.', l.codigo;
            END IF;
        END IF;

        IF t.calculo = 'MANUAL' THEN
            IF NEW.monto IS NULL OR NEW.monto <= 0 THEN
                RAISE EXCEPTION 'Anote el monto del bono «%».', t.nombre;
            END IF;
            NEW.tramo_id := NULL;
        ELSE
            SELECT * INTO r FROM cargas.tipo_bono_tramo
             WHERE id = cargas.tramo_tipo_bono(t.id, CASE WHEN t.calculo = 'POR_TONELADA' THEN 0 ELSE NEW.base END, v_fecha);
            IF NOT FOUND THEN
                RAISE EXCEPTION 'No hay monto vigente del bono «%» para % al %.', t.nombre,
                    CASE t.calculo WHEN 'POR_ELEMENTOS' THEN NEW.base::integer || ' elemento(s)'
                                   WHEN 'FIJO' THEN 'el lote' ELSE NEW.base || ' kg' END, v_fecha;
            END IF;
            NEW.tramo_id := r.id;
            NEW.moneda := r.moneda;
            NEW.monto := CASE WHEN t.calculo = 'POR_TONELADA' THEN round(r.monto * NEW.base / 1000, 2) ELSE r.monto END;
        END IF;

        NEW.naturaleza := t.naturaleza;
        NEW.estado := 'PENDIENTE';
        NEW.movimiento_caja_id := NULL;
        NEW.anulado_por := NULL; NEW.anulado_en := NULL; NEW.motivo_anulacion := NULL;
        IF NEW.beneficiario_nombre IS NULL THEN
            IF t.cobra = 'CHOFER' THEN
                SELECT chofer_nombre, chofer_ci INTO v_pr FROM cargas.pesaje
                 WHERE id = COALESCE(NEW.pesaje_id, (SELECT id FROM cargas.pesaje WHERE lote_id = l.id AND tipo = 'INGRESO'
                                                     AND NOT anulado ORDER BY id LIMIT 1));
            ELSE
                SELECT nombre AS chofer_nombre, ci AS chofer_ci INTO v_pr FROM cargas.productor WHERE id = l.productor_id;
            END IF;
            NEW.beneficiario_nombre := v_pr.chofer_nombre;
            NEW.beneficiario_ci := COALESCE(NEW.beneficiario_ci, v_pr.chofer_ci);
        END IF;
        RETURN NEW;
    END IF;

    -- UPDATE
    IF (NEW.tipo_bono_id, NEW.lote_id, NEW.pesaje_id, NEW.tramo_id, NEW.base, NEW.monto, NEW.moneda, NEW.naturaleza, NEW.registrado_por)
       IS DISTINCT FROM
       (OLD.tipo_bono_id, OLD.lote_id, OLD.pesaje_id, OLD.tramo_id, OLD.base, OLD.monto, OLD.moneda, OLD.naturaleza, OLD.registrado_por) THEN
        RAISE EXCEPTION 'Los datos de un bono no se modifican: se anula y, si corresponde, se registra otro.';
    END IF;
    IF OLD.estado <> 'PENDIENTE' AND (NEW.beneficiario_nombre, NEW.beneficiario_ci)
                                     IS DISTINCT FROM (OLD.beneficiario_nombre, OLD.beneficiario_ci) THEN
        RAISE EXCEPTION 'Quién cobró el bono no se cambia.';
    END IF;
    IF NEW.estado <> OLD.estado THEN
        IF NOT (OLD.estado = 'PENDIENTE' AND NEW.estado IN ('PAGADO','ANULADO')) THEN
            RAISE EXCEPTION 'Transición no permitida para el bono: % → %.', OLD.estado, NEW.estado;
        END IF;
        IF NEW.estado = 'PAGADO' THEN
            SELECT * INTO t FROM cargas.tipo_bono WHERE id = NEW.tipo_bono_id;
            SELECT origen INTO v_origen FROM caja.concepto WHERE id = t.concepto_id;
            PERFORM cargas.validar_movimiento_caja(NEW.movimiento_caja_id, 'EGRESO', v_origen,
                                                   NEW.monto, NEW.moneda, 'el bono «' || t.nombre || '»');
            IF (SELECT concepto_id FROM caja.movimiento WHERE id = NEW.movimiento_caja_id) <> t.concepto_id THEN
                RAISE EXCEPTION 'El comprobante no es del concepto del bono «%».', t.nombre;
            END IF;
        END IF;
    ELSIF NEW.movimiento_caja_id IS DISTINCT FROM OLD.movimiento_caja_id THEN
        RAISE EXCEPTION 'El comprobante de pago del bono no se cambia.';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER bono_catalogo_control
    BEFORE INSERT OR UPDATE OR DELETE ON cargas.bono
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_bono_catalogo_control();

-- ---------------------------------------------------------------------
-- 5. Los bonos nacen solos al recibir
-- ---------------------------------------------------------------------
-- Con el lote: fijos y por elementos.
CREATE FUNCTION cargas.tg_lote_bonos() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    t cargas.tipo_bono;
BEGIN
    FOR t IN SELECT * FROM cargas.tipo_bono
              WHERE activo AND calculo IN ('FIJO','POR_ELEMENTOS') ORDER BY orden, id LOOP
        CONTINUE WHEN NOT cargas.bono_aplica(t, NEW);
        CONTINUE WHEN t.calculo = 'POR_ELEMENTOS' AND cargas.num_elementos(NEW.material) IS NULL;
        CONTINUE WHEN cargas.tramo_tipo_bono(t.id,
                          CASE WHEN t.calculo = 'POR_ELEMENTOS' THEN cargas.num_elementos(NEW.material) END,
                          NEW.fecha_recepcion::date) IS NULL;
        INSERT INTO cargas.bono (tipo_bono_id, lote_id, monto, naturaleza, registrado_por, created_at, updated_at)
        VALUES (t.id, NEW.id, 0, t.naturaleza, NEW.registrado_por, now(), now());   -- monto y tramo los pone el control
    END LOOP;
    RETURN NULL;
END $$;
CREATE TRIGGER lote_bonos
    AFTER INSERT ON cargas.lote
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_lote_bonos();

-- Con el pesaje de báscula de ingreso: por peso y por tonelada.
CREATE FUNCTION cargas.tg_pesaje_bonos() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    t cargas.tipo_bono; l cargas.lote;
BEGIN
    IF NEW.tipo <> 'INGRESO' OR NEW.anulado OR NEW.modalidad <> 'BASCULA' OR NEW.pesaje_viaje_id IS NOT NULL THEN
        RETURN NULL;
    END IF;
    SELECT * INTO l FROM cargas.lote WHERE id = NEW.lote_id;
    IF l.estado IN ('ANULADO','LIQUIDADO') THEN
        RETURN NULL;
    END IF;
    FOR t IN SELECT * FROM cargas.tipo_bono
              WHERE activo AND calculo IN ('TRAMOS_PESO','POR_TONELADA') ORDER BY orden, id LOOP
        CONTINUE WHEN NOT cargas.bono_aplica(t, l);
        CONTINUE WHEN cargas.tramo_tipo_bono(t.id,
                          CASE WHEN t.calculo = 'TRAMOS_PESO' THEN NEW.peso_bruto_kg - NEW.tara_kg ELSE 0 END,
                          NEW.fecha::date) IS NULL;
        INSERT INTO cargas.bono (tipo_bono_id, lote_id, pesaje_id, monto, naturaleza, registrado_por, created_at, updated_at)
        VALUES (t.id, l.id, NEW.id, 0, t.naturaleza, NEW.registrado_por, now(), now());
    END LOOP;
    RETURN NULL;
END $$;
CREATE TRIGGER pesaje_bonos
    AFTER INSERT ON cargas.pesaje
    FOR EACH ROW EXECUTE FUNCTION cargas.tg_pesaje_bonos();

-- ---------------------------------------------------------------------
-- 6. Anulaciones: pesaje y lote
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION cargas.tg_pesaje_anulado() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_comprobante varchar; v_bono varchar;
BEGIN
    IF NEW.anulado AND NOT OLD.anulado THEN
        SELECT m.numero, t.nombre INTO v_comprobante, v_bono
          FROM cargas.bono b JOIN caja.movimiento m ON m.id = b.movimiento_caja_id
          JOIN cargas.tipo_bono t ON t.id = b.tipo_bono_id
         WHERE b.pesaje_id = NEW.id AND b.estado = 'PAGADO'
         LIMIT 1;
        IF FOUND THEN
            RAISE EXCEPTION 'El % de este pesaje ya se pagó (comprobante %): el pesaje no se anula.', lower(v_bono), v_comprobante;
        END IF;

        UPDATE cargas.bono
           SET estado = 'ANULADO', anulado_por = cargas.usuario_actual(), anulado_en = now(),
               motivo_anulacion = left('Pesaje anulado: ' || NEW.motivo_anulacion, 250), updated_at = now()
         WHERE pesaje_id = NEW.id AND estado = 'PENDIENTE';
    END IF;
    RETURN NULL;
END $$;

CREATE OR REPLACE FUNCTION cargas.tg_lote_anulado_bonos() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado = 'ANULADO' AND OLD.estado <> 'ANULADO' THEN
        UPDATE cargas.bono
           SET estado = 'ANULADO', anulado_por = cargas.usuario_actual(), anulado_en = now(),
               motivo_anulacion = left('Lote anulado: ' || NEW.motivo_anulacion, 250), updated_at = now()
         WHERE lote_id = NEW.id AND estado = 'PENDIENTE';
    END IF;
    RETURN NULL;
END $$;

-- ---------------------------------------------------------------------
-- 7. Caja: el egreso de un bono siempre está vinculado a su bono
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION cargas.tg_mov_caja_vinculado() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_origen varchar;
BEGIN
    SELECT origen INTO v_origen FROM caja.concepto WHERE id = NEW.concepto_id;
    IF v_origen NOT LIKE 'CARGAS\_%' THEN
        RETURN NULL;
    END IF;
    IF v_origen = 'CARGAS_ANTICIPO' THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.anticipo WHERE movimiento_pago_id = NEW.id) THEN
            RAISE EXCEPTION 'El comprobante % es un pago de anticipo pero no está vinculado a ningún anticipo de un lote.', NEW.numero;
        END IF;
    ELSIF v_origen = 'CARGAS_ANTICIPO_DEVOLUCION' THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.anticipo WHERE movimiento_devolucion_id = NEW.id) THEN
            RAISE EXCEPTION 'El comprobante % es una devolución de anticipo pero no está vinculado a ningún anticipo.', NEW.numero;
        END IF;
    ELSIF v_origen IN ('CARGAS_BONO','CARGAS_BONO_LAB') THEN
        IF NOT EXISTS (SELECT 1 FROM cargas.bono WHERE movimiento_caja_id = NEW.id) THEN
            RAISE EXCEPTION 'El comprobante % es un pago de bono pero no está vinculado a ningún bono de un lote.', NEW.numero;
        END IF;
    ELSE
        RAISE EXCEPTION 'El concepto de origen % todavía no tiene documento en cargas: no se puede usar.', v_origen;
    END IF;
    RETURN NULL;
END $$;

CREATE OR REPLACE FUNCTION cargas.tg_mov_caja_no_anular() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_doc varchar;
BEGIN
    IF NEW.estado = 'ANULADO' AND OLD.estado = 'VIGENTE' THEN
        SELECT 'el anticipo ' || numero INTO v_doc FROM cargas.anticipo
         WHERE movimiento_pago_id = NEW.id OR movimiento_devolucion_id = NEW.id;
        IF v_doc IS NULL THEN
            SELECT 'el ' || lower(t.nombre) INTO v_doc
              FROM cargas.bono b JOIN cargas.tipo_bono t ON t.id = b.tipo_bono_id WHERE b.movimiento_caja_id = NEW.id;
        END IF;
        IF v_doc IS NOT NULL THEN
            RAISE EXCEPTION 'El comprobante % respalda %: no se anula desde caja. Si el pago fue indebido, registre la devolución.', NEW.numero, v_doc;
        END IF;
    END IF;
    RETURN NEW;
END $$;

-- ---------------------------------------------------------------------
-- 8. Lo que la liquidación descuenta (anticipos y bonos de tipo anticipo)
-- ---------------------------------------------------------------------
CREATE VIEW cargas.v_lote_anticipos AS
SELECT l.id AS lote_id,
       COALESCE(a.bob, 0) AS anticipos_bob,  COALESCE(a.usd, 0) AS anticipos_usd,
       COALESCE(b.bob, 0) AS bonos_bob,      COALESCE(b.usd, 0) AS bonos_usd,
       COALESCE(b.premio_bob, 0) AS premios_bob, COALESCE(b.premio_usd, 0) AS premios_usd,
       COALESCE(a.bob, 0) + COALESCE(b.bob, 0) AS total_bob,
       COALESCE(a.usd, 0) + COALESCE(b.usd, 0) AS total_usd,
       COALESCE(b.pendiente, 0) AS bonos_pendientes
  FROM cargas.lote l
  LEFT JOIN (SELECT lote_id, sum(monto) FILTER (WHERE moneda = 'BOB') AS bob, sum(monto) FILTER (WHERE moneda = 'USD') AS usd
               FROM cargas.anticipo WHERE estado = 'PAGADO' GROUP BY lote_id) a ON a.lote_id = l.id
  LEFT JOIN (SELECT lote_id,
                    sum(monto) FILTER (WHERE estado = 'PAGADO' AND naturaleza = 'ANTICIPO' AND moneda = 'BOB') AS bob,
                    sum(monto) FILTER (WHERE estado = 'PAGADO' AND naturaleza = 'ANTICIPO' AND moneda = 'USD') AS usd,
                    sum(monto) FILTER (WHERE estado = 'PAGADO' AND naturaleza = 'PREMIO' AND moneda = 'BOB') AS premio_bob,
                    sum(monto) FILTER (WHERE estado = 'PAGADO' AND naturaleza = 'PREMIO' AND moneda = 'USD') AS premio_usd,
                    count(*) FILTER (WHERE estado = 'PENDIENTE') AS pendiente
               FROM cargas.bono GROUP BY lote_id) b ON b.lote_id = l.id;
COMMENT ON VIEW cargas.v_lote_anticipos IS
    'Lo pagado por adelantado en cada lote. total = anticipos + bonos de tipo ANTICIPO: lo que la liquidación descuenta. Los premios no se descuentan.';

CREATE OR REPLACE VIEW cargas.v_lote_anticipos_a_descontar AS
SELECT l.id AS lote_id, l.codigo AS lote, x.moneda,
       sum(x.monto) AS total, count(*) AS cantidad,
       string_agg(x.ref, ', ' ORDER BY x.ref) AS anticipos
  FROM (SELECT lote_id, moneda, monto, numero::text AS ref FROM cargas.anticipo WHERE estado = 'PAGADO'
        UNION ALL
        SELECT b.lote_id, b.moneda, b.monto, t.nombre::text
          FROM cargas.bono b JOIN cargas.tipo_bono t ON t.id = b.tipo_bono_id
         WHERE b.estado = 'PAGADO' AND b.naturaleza = 'ANTICIPO') x
  JOIN cargas.lote l ON l.id = x.lote_id
 GROUP BY l.id, l.codigo, x.moneda;

