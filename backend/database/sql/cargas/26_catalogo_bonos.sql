              GREATEST((SELECT COALESCE(max(id), 0) FROM cargas.tipo_bono_tramo), 1));

-- Tramos de laboratorio: cada cantidad de elementos n es el rango [n, n+1).
INSERT INTO cargas.tipo_bono_tramo (tipo_bono_id, etiqueta, desde, hasta, monto, moneda,
                                    vigente_desde, vigente_hasta, registrado_por, created_at, updated_at)
SELECT (SELECT id FROM cargas.tipo_bono WHERE codigo = 'LABORATORIO'), NULL, t.num_elementos, t.num_elementos + 1,
       t.monto, t.moneda, t.vigente_desde, t.vigente_hasta, t.registrado_por, t.created_at, t.updated_at
  FROM cargas.bono_laboratorio_tramo t;

INSERT INTO cargas.bono (tipo_bono_id, lote_id, pesaje_id, tramo_id, base, monto, moneda, naturaleza, estado,
                         beneficiario_nombre, beneficiario_ci, movimiento_caja_id, registrado_por,
                         anulado_por, anulado_en, motivo_anulacion, created_at, updated_at)
SELECT (SELECT id FROM cargas.tipo_bono WHERE codigo = 'TRANSPORTE'), p.lote_id, b.pesaje_id, b.tramo_id,
       p.peso_bruto_kg - p.tara_kg, b.monto, b.moneda, 'ANTICIPO', b.estado,
       b.beneficiario_nombre, b.beneficiario_ci, b.movimiento_caja_id, b.registrado_por,
       b.anulado_por, b.anulado_en, b.motivo_anulacion, b.created_at, b.updated_at
  FROM cargas.bono_transporte b JOIN cargas.pesaje p ON p.id = b.pesaje_id;

INSERT INTO cargas.bono (tipo_bono_id, lote_id, tramo_id, base, monto, moneda, naturaleza, estado,
                         beneficiario_nombre, beneficiario_ci, movimiento_caja_id, registrado_por,
                         anulado_por, anulado_en, motivo_anulacion, created_at, updated_at)
SELECT k.id, b.lote_id, n.id, b.num_elementos, b.monto, b.moneda, 'ANTICIPO', b.estado,
       COALESCE(b.beneficiario_nombre, pr.nombre),                  -- pendientes: cobra el productor, salvo que venga otro
       CASE WHEN b.beneficiario_nombre IS NULL THEN pr.ci ELSE b.beneficiario_ci END,
       b.movimiento_caja_id, b.registrado_por,
       b.anulado_por, b.anulado_en, b.motivo_anulacion, b.created_at, b.updated_at
  FROM cargas.bono_laboratorio b
  JOIN cargas.lote l ON l.id = b.lote_id
  LEFT JOIN cargas.productor pr ON pr.id = l.productor_id
  JOIN cargas.bono_laboratorio_tramo o ON o.id = b.tramo_id
  JOIN cargas.tipo_bono k ON k.codigo = 'LABORATORIO'
  JOIN cargas.tipo_bono_tramo n ON n.tipo_bono_id = k.id AND n.desde = o.num_elementos AND n.vigente_desde = o.vigente_desde;

